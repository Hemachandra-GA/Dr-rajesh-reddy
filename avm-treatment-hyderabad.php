          <!-- Symptoms of Brain AVM -->
          <section id="symptoms" class="pillar-section">
            <h2 class="pillar-section-title">Symptoms of Brain AVM</h2>
            <p>AVMs can present in a wide variety of ways depending on their size, location, and whether they have bled:</p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Haemorrhage — The Most Common Presentation</h3>
            <p>
              Approximately 50% of AVMs present with intracranial haemorrhage — most commonly intracerebral haemorrhage (ICH) rather than subarachnoid haemorrhage (SAH). AVM bleeding typically presents as a sudden headache with rapid neurological deterioration — weakness, speech difficulty, loss of consciousness — corresponding to the location of the haematoma. The annual risk of haemorrhage from an unruptured AVM is approximately 2–4%, rising significantly after a first bleed (approximately 6–18% per year in the year following haemorrhage).
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Seizures</h3>
            <p>
              Approximately 25–30% of AVMs present with new-onset seizures — either focal (affecting one limb or one side of the face) or generalised tonic-clonic seizures. Seizures occur because the AVM irritates surrounding cortical tissue through abnormal blood flow, arterial steal phenomena, or haemosiderin deposition from previous microbleeds. Any new-onset seizure in an adult under 40 should prompt an MRI of the brain to rule out an underlying AVM or other structural cause.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Progressive Neurological Deficit</h3>
            <p>
              Some AVMs cause progressive weakness, sensory loss, or visual disturbance without obvious haemorrhage — through arterial steal (blood being diverted from normal brain to the AVM), venous hypertension, or gradual cortical injury from repeated microbleeds too small to cause acute symptoms. These presentations can mimic brain tumour or demyelinating disease and require MRI and DSA for definitive diagnosis.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Headaches</h3>
            <p>
              Chronic headaches — not thunderclap, but persistent and sometimes pulsatile — may be an AVM presentation, particularly for large AVMs with significant haemodynamic impact or for AVMs located in the posterior fossa. Headaches alone are an uncommon isolated AVM presentation.
            </p>

            <div style="background-color: #fff8e6; border-left: 4px solid #d32f2f; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              <strong>Note:</strong> New-onset seizures in an adult under 45, unexplained progressive neurological deficit, or recurrent pulsatile headaches should prompt MRI of the brain with contrast. AVMs have a characteristic MRI appearance — a flow void 'bag of worms' with surrounding haemosiderin — that is usually immediately recognisable to a neurosurgeon.
            </div>
          </section>

          <!-- Diagnosing a Brain AVM -->
          <section id="diagnosis" class="pillar-section">
            <h2 class="pillar-section-title">Diagnosing a Brain AVM</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/Brain_avm_treatment/how_a_brain_avm_is_diagonosed.webp" alt="Diagnosing a Brain AVM" style="width: 100%; height: auto; display: block;">
            </div>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">MRI Brain with Contrast</h3>
            <p>
              MRI is the primary diagnostic tool for AVM detection. The AVM nidus appears as a cluster of flow voids — dark tangles of high-flow vessels — on T2 sequences. Surrounding haemosiderin (from previous bleeds) appears as dark 'staining' on gradient-echo sequences. Gadolinium contrast enhancement helps delineate the nidus boundaries and the draining veins. Functional MRI (fMRI) and DTI tractography are used for AVMs near eloquent cortex to assess surgical risk.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">CT Angiography (CTA)</h3>
            <p>
              CTA provides a rapid three-dimensional map of the AVM's feeding arteries, nidus, and draining veins — particularly useful in the emergency setting of AVM haemorrhage where DSA may not be immediately available. CTA has largely replaced diagnostic-only DSA for initial AVM characterisation.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Digital Subtraction Angiography (DSA) — Mandatory Before Treatment</h3>
            <p>
              DSA remains the gold standard for AVM characterisation before any treatment. 3D rotational DSA provides real-time dynamic information that static CT or MRI cannot: which arteries are feeding the AVM (arterial phase), the morphology of the nidus, which veins are draining it and in which direction, and — critically — whether any flow-related aneurysms are present on the feeding arteries. This information determines the Spetzler-Martin grade, the treatment approach, and the embolisation strategy.
            </p>
          </section>

