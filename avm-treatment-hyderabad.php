          <section id="procedure-details" class="pillar-section">
            <h2 class="pillar-section-title">AVM Embolisation: What the Procedure Involves</h2>
            <p>
              AVM embolisation is performed under general anaesthesia in a biplane neurointerventional suite. A guide catheter is placed in the internal carotid or vertebral artery, and a microcatheter is navigated into each AVM feeding artery in turn. Before injection, a test injection confirms the catheter is in the correct position and that the embolic material will reach the nidus without refluxing into normal arteries.
            </p>
            <p>
              Onyx — the most commonly used liquid embolic — is injected slowly and continuously under real-time fluoroscopic guidance, watched as it fills the AVM vessels in a controlled front. The injection continues as long as the Onyx is progressing into the nidus; it is stopped when reflux threatens normal arteries or when the run is complete. The procedure may involve 1–4 embolisation sessions for a large AVM, each addressing different feeding arteries, typically spaced 4–6 weeks apart to allow healing between sessions.
            </p>
            <p>
              Embolisation of a brain AVM is one of the most technically demanding endovascular procedures in neurosurgery — requiring precise control of liquid embolic injection over extended periods, detailed knowledge of AVM angioarchitecture, and the ability to recognise and manage complications in real time. The quality of the embolisation directly determines the safety of the subsequent surgery.
            </p>
