            <h2 class="pillar-section-title">Introduction</h2>
            <p>
              An arteriovenous malformation — AVM — is one of the most complex conditions in cerebrovascular medicine. Unlike a brain aneurysm, which is a localised bulge in a single artery, an AVM is a tangled mass of abnormal blood vessels connecting arteries directly to veins — bypassing the normal capillary network that regulates pressure, flow, and oxygen exchange. Present from birth, an AVM may be silent for decades, or it may announce itself catastrophically through bleeding into the brain, a first seizure, or a progressive neurological deficit.
            </p>
            <p>
              The treatment of brain AVMs sits at the intersection of three neurosurgical disciplines — open microsurgery, endovascular embolisation, and stereotactic radiosurgery — and often requires all three working in a carefully planned sequence. Few neurological conditions demand more from a treating team, and few offer more complete cures when managed optimally.
            </p>
            <p>
              <strong>Dr. Rajesh Reddy Sannareddy</strong>, Senior Consultant Endovascular Neurosurgeon in Hyderabad, brings a uniquely integrated skill set to AVM management: open microsurgical resection, endovascular embolisation using modern liquid embolic agents (Onyx, NBCA, Squid, PHIL), and coordination with radiosurgery teams for multimodal treatment of complex AVMs. His FINR fellowship in Zurich and visiting scholar experience at Barrow Neurological Institute, Phoenix — among the world's highest-volume cerebrovascular centres — have shaped his approach to these rare and challenging lesions.
            </p>
          </section>

          <!-- What Is a Brain AVM? -->
          <section id="what-is-avm" class="pillar-section">
            <h2 class="pillar-section-title">What Is a Brain AVM?</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/Brain_avm_treatment/Brainavm.webp" alt="Brain AVM" style="width: 100%; height: auto; display: block;">
            </div>
            <p>
              A cerebral arteriovenous malformation is a congenital (present from birth) abnormality of blood vessel development in which arteries connect directly to veins through a tangle of abnormal vessels — called the nidus — without an intervening capillary bed. Normally, capillaries slow blood down from high-pressure arterial flow to low-pressure venous flow, allowing oxygen exchange and protecting the veins from arterial pressure. In an AVM, this pressure regulation is absent: high-pressure arterial blood surges directly into thin-walled venous structures that are not designed to handle it.
            </p>
            <p>
              Over time, this haemodynamic stress causes the AVM to enlarge, the feeding arteries to dilate, and the draining veins to become arterialized (thickened and prone to rupture). Flow-related aneurysms — true aneurysms that form on AVM feeding arteries due to increased flow — occur in approximately 10% of AVM patients and increase the overall bleeding risk significantly.
            </p>
          </section>

          <!-- How Common Are Brain AVMs? -->
          <section id="how-common" class="pillar-section">
            <h2 class="pillar-section-title">How Common Are Brain AVMs?</h2>
            <p>
              Brain AVMs are rare — affecting approximately 0.01–0.1% of the population, or roughly 1–2 per 100,000 people. They are typically diagnosed in the 2nd–4th decade of life, reflecting either the time it takes for the AVM to become symptomatic or the increasing use of brain MRI for other conditions. Unlike aneurysms, which are more common in women, AVMs have a roughly equal sex distribution.
            </p>
          </section>

