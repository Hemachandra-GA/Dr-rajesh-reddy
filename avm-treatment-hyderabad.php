            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 32px; margin-bottom: 12px;">Microsurgical AVM Resection</h3>
            <p>
              For low-grade AVMs (SM I–II) — and selected SM Grade III AVMs in accessible, non-eloquent locations — microsurgical resection offers the most durable cure: complete removal of the AVM nidus in a single procedure, with immediate cure confirmed by intraoperative DSA. The surgery involves a craniotomy, meticulous microsurgical dissection to identify all feeding arteries (which are individually coagulated and divided), circumferential dissection of the nidus, and finally occlusion of the draining veins — which are preserved until last, as premature venous occlusion causes the AVM to swell and bleed. Intraoperative ICG fluorescence angiography and intraoperative DSA confirm complete resection before wound closure.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Endovascular Embolisation</h3>
            <p>
              Embolisation is performed by navigating microcatheters into the AVM's feeding arteries under biplane fluoroscopic guidance and injecting liquid embolic agents — most commonly Onyx (ethylene vinyl alcohol copolymer), NBCA (N-butyl cyanoacrylate glue), Squid or PHIL (precipitating hydrophobic injectable liquid) — that solidify within the AVM vessels and permanently block flow. Modern liquid embolics — particularly Onyx — allow controlled, extended injections that can penetrate deeply into the AVM nidus, achieving more complete embolisation than was possible with older coil-based or particle techniques. Complete cure by embolisation alone is achievable in select cases in highly experienced hands.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Stereotactic Radiosurgery (SRS)</h3>
            <p>
              SRS delivers a high, precisely focused dose of radiation to the AVM nidus in a single session, causing progressive endothelial damage, vessel wall thickening, and eventual thrombosis of the AVM over 2–3 years. Complete obliteration is achieved in approximately 70–85% of AVMs under 3 cm at 3 years. SRS is the treatment of choice for small, deep, or eloquently located AVMs (particularly thalamic, basal ganglia, and brainstem AVMs) where open surgery carries unacceptably high risk. The main limitation is the 2–3 year latency period during which the AVM remains patent and carries its full bleeding risk — in approximately 5% of cases the AVM bleeds during this waiting period.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">The Combined Multimodal Approach</h3>
            <p>
              For large or complex AVMs (SM Grade III–IV), the optimal approach combines all three modalities in a planned sequence: targeted embolization of the weak spot (intranidal aneurysm), followed by microsurgical resection or SRS for the residual nidus. This staged approach reduces the risk at each individual procedure and achieves cure in AVMs that would be untreatable by any single modality.
            </p>
