            <p>For patients who had elective treatment of an unruptured aneurysm — the most straightforward recovery scenario — here is what to expect at each stage:</p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Days 1–3: Procedure and Discharge</h3>
            
            <h4 style="font-size: 1.1rem; color: #0066cc; margin-top: 16px; margin-bottom: 8px;">After Coiling</h4>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li>Waking from anaesthesia in the recovery room; neurological check performed immediately</li>
              <li>Groin puncture site monitored — pressure dressing in place; 4–6 hours bed rest to prevent haematoma</li>
              <li>Mild groin bruising and tenderness is normal and typically resolves within 1–2 weeks</li>
              <li>Headache after coiling is common — usually mild and manageable with paracetamol</li>
              <li>Discharge day 1–2 for simple coiling; day 2–3 for stent-assisted coiling or flow diversion</li>
              <li>Antiplatelet medication: aspirin + clopidogrel or Ticagrelor (stent/flow diversion) — do not miss doses</li>
            </ul>

            <h4 style="font-size: 1.1rem; color: #0066cc; margin-top: 24px; margin-bottom: 8px;">After Clipping</h4>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li>Recover in neurosurgical ICU for 24–48 hours; neurological observations every 2–4 hours</li>
              <li>Scalp wound with sutures or staples — wound checked daily; removed at 10–14 days</li>
              <li>Headache after craniotomy is more significant than after coiling — managed with regular analgesics</li>
              <li>Facial swelling around the eye on the side of the craniotomy — peaks at 48–72 hours and resolves over 1–2 weeks</li>
              <li>Anti-seizure medication commenced and continued for atleast 3–6 months</li>
              <li>Early physiotherapy — walking with support begins day 1–2</li>
            </ul>
          </section>

          <!-- Week 1–2: Early Home Recovery -->
          <section id="week-1-2" class="pillar-section">
            <h2 class="pillar-section-title">Week 1–2: Early Home Recovery</h2>
            <p>Whether home after 2 days (coiling) or 7 days (clipping), the first two weeks at home are about rest and gradual recovery. The brain and body are healing, and fatigue is the most universal — and most underestimated — early symptom.</p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">What Is Normal in Week 1–2</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Fatigue</strong> — often profound; activities that were effortless before may feel exhausting</li>
              <li><strong>Mild headache</strong> — improving progressively; paracetamol is usually sufficient</li>
              <li><strong>Scalp numbness or tingling</strong> around the clipping wound — normal nerve regeneration</li>
              <li><strong>Mild mood changes</strong> — feeling emotional, anxious, or flat is a normal response to the experience</li>
              <li><strong>Poor appetite</strong> — common in the first week; small frequent meals help</li>
              <li><strong>Sleep disturbance</strong> — difficulty sleeping or excessive sleepiness; both are temporary</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Activity Restrictions — Week 1–2</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>No driving</strong> — minimum 4 weeks for clipping; 1–2 weeks for coiling (in the absence of neurological deficit or seizure)</li>
              <li><strong>No heavy lifting (> 5 kg)</strong> — avoid straining, which raises blood pressure and intracranial pressure</li>
              <li><strong>No alcohol</strong> — particularly while on anti-epileptic or antiplatelet medications</li>
              <li><strong>No strenuous exercise</strong> — light walks are encouraged and beneficial</li>
              <li><strong>No swimming</strong> — until wound is fully healed (minimum 4–6 weeks)</li>
              <li><strong>Constipation management</strong> — straining at stool causes dangerous spikes in intracranial pressure; use stool softeners from day 1 if needed; maintain adequate hydration</li>
            </ul>
            <div style="background-color: #fff8e6; border-left: 4px solid #f5a623; padding: 16px; margin-top: 24px; border-radius: 4px;">
              <p style="margin-bottom: 0; font-size: 0.95rem; color: #333;"><strong>Important Note:</strong> Managing constipation actively is essential for all brain aneurysm patients in the recovery period. Straining at stool causes sudden surges in intracranial pressure that can be dangerous. Stool softeners (lactulose or sodium docusate) should be used from the first day at home if bowel movements are not occurring easily.</p>
            </div>
          </section>

          <!-- Week 2–6: Progressive Recovery -->
          <section id="week-2-6" class="pillar-section">
            <h2 class="pillar-section-title">Week 2–6: Progressive Recovery</h2>
            <p>By week 2–3, most patients begin to feel meaningfully better — more energy, clearer thinking, reducing headaches. This is when gradual reintegration into normal activity begins.</p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Physical Recovery Milestones</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Week 2–3:</strong> Short walks (15–30 minutes), light household activity, reading and screen time in limited amounts</li>
              <li><strong>Week 3–4:</strong> Increasing walking distance; light cooking; social activity; short car trips as a passenger</li>
              <li><strong>Week 4–6 (coiling):</strong> Return to desk work; driving after medical clearance; light exercise (walking, gentle swimming after wound healed)</li>
              <li><strong>Week 6–10 (clipping):</strong> Return to desk work; driving after 6-week neurosurgical review; suture removal at 10–14 days; physiotherapy if any motor deficit</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">6-Week Neurosurgical Review</h3>
            <p>A clinic review — in person or via video consultation — is scheduled at approximately 6 weeks. This appointment covers:</p>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li>Neurological assessment — any ongoing deficits, headache status, functional recovery</li>
              <li>Anti-epileptic medication review — tapering plan if no seizures have occurred</li>
              <li>Antiplatelet medication review — plan for clopidogrel or Ticagrelor cessation at 6 months (stent/flow diversion)</li>
              <li>Driving fitness — formal clearance for driving based on neurological status and seizure risk</li>
              <li>Return-to-work discussion — what activities are safe, what modifications may be needed</li>
              <li>Follow-up imaging schedule confirmed — DSA or MRA/ CTA at 6 months</li>
            </ul>
          </section>

          <!-- Month 2–6: Functional Reintegration -->
          <section id="month-2-6" class="pillar-section">
            <h2 class="pillar-section-title">Month 2–6: Functional Reintegration</h2>
            <p>For elective patients, month 2–6 marks a return to most normal activities. For SAH survivors, this period may still be early in recovery — particularly for those with higher-grade bleeds or vasospasm-related deficits.</p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Return to Work</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Desk-based / office work:</strong> typically possible from week 4–6 (coiling) or week 6–8 (clipping), starting with part-time hours and building up over 2–4 weeks.</li>
              <li><strong>Professional roles (doctors, lawyers, teachers):</strong> typically week 6–10; cognitive demands should be considered — early return may require reduced caseload.</li>
              <li><strong>Manual or physically demanding roles:</strong> 3–6 months; formal occupational health assessment recommended.</li>
              <li><strong>SAH survivors:</strong> 3–6 months for good-grade; 6–12 months for moderate-grade; some poor-grade patients require permanent work modification.</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Driving After Brain Aneurysm Treatment</h3>
            <p>Driving regulations after brain aneurysm treatment depend on the type of treatment and whether seizures have occurred:</p>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Coiling (unruptured, no seizure):</strong> driving typically from 1–2 weeks; confirm with Dr. Rajesh Reddy at follow-up</li>
              <li><strong>Clipping (unruptured, no seizure):</strong> driving from 4–6 weeks after neurosurgical clearance</li>
              <li><strong>Any patient who has had a seizure (at rupture or post-operative):</strong> typically 6–12 months seizure-free before driving is permitted — discuss with Dr. Rajesh Reddy and the transport authority</li>
              <li><strong>SAH survivors (no seizure):</strong> driving typically from 3–6 months; return to driving requires formal neurosurgical clearance</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Exercise and Physical Activity</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Light aerobic exercise (walking, gentle cycling)</strong> — from week 2–3 for coiling; week 4–6 for clipping</li>
              <li><strong>Swimming</strong> — from week 4–6 once all wounds are fully healed</li>
              <li><strong>Gym / weight training</strong> — from month 3 for coiling; month 3–4 for clipping; avoid breath-holding, heavy squats, or explosive lifting</li>
              <li><strong>Contact sports</strong> — discuss with Dr. Rajesh Reddy; generally avoided for 6–12 months after any aneurysm treatment</li>
              <li><strong>Sexual activity</strong> — generally safe from week 2–3 for coiling; week 3–4 for clipping</li>
            </ul>
          </section>

          <!-- Recovery After SAH -->
          <section id="sah-recovery" class="pillar-section">
            <h2 class="pillar-section-title">Recovery After SAH: A Different Journey</h2>
            <p>Recovery after subarachnoid hemorrhage is a fundamentally different experience from recovery after elective aneurysm treatment. The aneurysm treatment itself is only one part of what the brain has endured — the haemorrhage, the ICP spike, the blood-brain barrier disruption, and the complications (vasospasm, hydrocephalus) all contribute to a recovery that unfolds over months to years.</p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Physical Recovery After SAH</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Total hospital stay:</strong> 3–6 weeks for good-grade SAH (WFNS I–II) without major complications</li>
              <li><strong>Rehabilitation:</strong> physiotherapy (motor), occupational therapy (daily function), speech and language therapy (language and swallowing) initiated in hospital and continued as outpatient</li>
              <li><strong>Fatigue:</strong> the most persistent physical symptom; typically present for 6–12 months; pace activity carefully</li>
              <li><strong>Headaches:</strong> often present for weeks to months after SAH; typically tension-type in character; managed with regular analgesics and headache diary</li>
              <li><strong>VP shunt (15–20% of patients):</strong> typically inserted 3–6 weeks after SAH; dramatic improvement in walking, cognition, and quality of life usually follows within days</li>
            </ul>
          </section>

          <!-- Post-SAH Syndrome -->
          <section id="post-sah-syndrome" class="pillar-section">
            <h2 class="pillar-section-title">Post-SAH Syndrome: The Invisible Recovery</h2>
            <p>Even patients who make a full physical recovery after SAH frequently experience what is now recognised as post-SAH syndrome — a constellation of cognitive and psychological symptoms that are not visible on imaging but profoundly affect quality of life. Families often recognise the change before the patient does.</p>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Fatigue:</strong> A profound, qualitatively different tiredness from anything experienced before SAH. Unlike normal tiredness, it is not always relieved by sleep and can be triggered by cognitive effort as much as physical activity. It typically improves progressively over 12–24 months but may be permanent in severe SAH.</li>
              <li><strong>Memory and concentration:</strong> Difficulty forming new memories, word-finding problems, slowed information processing, and difficulty multitasking. These are collectively described as 'brain fog' and are a recognised sequela of SAH — not a sign of ongoing damage, but of a brain that is still healing.</li>
              <li><strong>Headaches:</strong> Persistent — often daily in the first months — and can be severe enough to interfere with return to work. The mechanism is multifactorial: vasomotor changes, medication effects, and psychological contributors all play a role.</li>
              <li><strong>Depression and anxiety:</strong> Affect approximately 40–50% of SAH survivors. The combination of a frightening experience, changed life circumstances, ongoing physical symptoms, and the neurobiological effects of SAH on mood regulation creates a high risk of affective disorder. Proactive psychological support — counselling, psychiatry if needed — is not optional; it is part of good SAH care.</li>
              <li><strong>Personality and behavioural changes:</strong> Subtle shifts in emotional regulation, patience, impulsivity, or social judgement may be noticed by family members. These typically improve over time but may require psychological or neuropsychological support.</li>
            </ul>
            <div style="background-color: #f8fbff; border-left: 4px solid #0066cc; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              Post-SAH syndrome is not a sign of weakness or that something has gone wrong with recovery. It is a recognised, well-documented consequence of subarachnoid haemorrhage that reflects the brain's healing process. Most symptoms improve substantially over 12–24 months with appropriate support. Do not dismiss or minimise these symptoms — bring them to Dr. Rajesh Reddy's attention at follow-up.
            </div>
          </section>

