          <section id="long-term" class="pillar-section">
            <h2 class="pillar-section-title">Long-Term Life After Brain Aneurysm Treatment</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/life-after-brain-aneurysm-surgery/betterlife.webp" alt="Long-Term Life After SAH" style="width: 100%; height: auto; display: block;">
            </div>
            <p>Most patients who undergo successful treatment of a brain aneurysm — whether ruptured or unruptured — go on to live full, active lives. The key to long-term wellbeing is a combination of ongoing surveillance, risk factor control, and realistic expectations about the recovery timeline.</p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Risk Factor Control for Life</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Blood pressure:</strong> target &lt; 130/80 mmHg; medication if needed; home BP monitoring encouraged</li>
              <li><strong>Smoking:</strong> cessation mandatory — smoking significantly increases the risk of recurrence and new aneurysm formation</li>
              <li><strong>Constipation:</strong> manage actively long-term — straining at stool remains a risk for both treated and any remaining untreated aneurysms</li>
              <li><strong>Alcohol:</strong> moderate — heavy alcohol use is associated with increased cerebrovascular risk</li>
              <li><strong>Exercise:</strong> regular moderate aerobic exercise is beneficial and recommended after the initial recovery period</li>
              <li><strong>Stress management:</strong> chronic psychological stress elevates blood pressure; mindfulness, relaxation techniques, and psychological support are part of long-term aneurysm health</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Multiple Aneurysms & Family Screening</h3>
            <p>Patients with one brain aneurysm have a 15–20% chance of harbouring one or more additional aneurysms. Any untreated additional aneurysms detected at the time of initial treatment are monitored with regular MRA — their risk assessment and treatment planning follows the same evidence-based framework used for the index aneurysm. Dr. Rajesh Reddy will discuss the surveillance and management plan for any additional aneurysms at your follow-up consultation.</p>
            <p>First-degree relatives of a patient with a confirmed brain aneurysm have 3–7 times the population risk of harbouring an aneurysm themselves. Screening with MRA — non-invasive, no radiation — is recommended for relatives with two or more affected first-degree relatives, or for those with one affected relative combined with other risk factors (hypertension, smoking, Polycystic Kidney Disease, Ehler Danlos or Marfan Syndrome). Please discuss family screening with Dr. Rajesh Reddy at your follow-up appointment.</p>
