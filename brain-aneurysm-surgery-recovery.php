          <section id="medications" class="pillar-section">
            <h2 class="pillar-section-title">Medications After Brain Aneurysm Treatment</h2>
            <p>Understanding the medications prescribed after brain aneurysm treatment — what each is for and how long to take it — helps patients stay adherent and avoid dangerous interruptions:</p>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>Aspirin (75–150 mg daily):</strong> After stent-assisted coiling or flow diversion — continued for at least 3–5 years (decision of treating doctor) as single antiplatelet after clopidogrel is stopped. Never stop without consulting Dr. Rajesh Reddy.</li>
              <li><strong>Clopidogrel (75 mg daily) or Ticagrelor (90 mg twice daily):</strong> After stent-assisted coiling or extrasaccular flow diversion — dual therapy with aspirin for 6 months, then stopped. Stopping clopidogrel/ Ticagrelor early risks in-stent thrombosis and stroke.</li>
              <li><strong>Anti-epileptic medication:</strong> After surgical clipping (and in some SAH patients) — typically continued for 3–6 months. Tapered under medical supervision; never stopped suddenly.</li>
              <li><strong>Nimodipine (60 mg every 4 hours):</strong> After SAH — the only proven medical prophylaxis against vasospasm-related delayed cerebral ischaemia. Continued for the full 21-day course from the day of SAH regardless of how well the patient feels.</li>
              <li><strong>Stool softeners (lactulose or sodium docusate):</strong> For all post-operative patients — preventing straining at stool and the associated dangerous surges in intracranial pressure. Continue until bowel habits are normal and easy.</li>
              <li><strong>Analgesics (paracetamol):</strong> For post-operative headache — safe and effective. Avoid ibuprofen and aspirin-containing analgesics in the first weeks (unless aspirin is prescribed as antiplatelet therapy).</li>
            </ul>
          </section>

          <!-- Follow-Up Imaging -->
          <section id="follow-up-imaging" class="pillar-section">
            <h2 class="pillar-section-title">Follow-Up Imaging: Why It Is Non-Negotiable</h2>
            <p>The aneurysm treatment does not end in the operating or angiography suite. Post-treatment surveillance imaging is an essential part of aneurysm management — particularly after endovascular coiling, where recanalisation can occur over time.</p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">After Coiling or Flow Diversion</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>6 months:</strong> DSA (preferred) or high-resolution 3T MRA/ CTAngiogram — confirms aneurysm occlusion, absence of recanalisation, in-stent patency</li>
              <li><strong>18 months:</strong> DSA or MRA /CT angiogram— second surveillance point; most clinically significant recanalisation detected here</li>
              <li><strong>Annual MRA thereafter:</strong> for large aneurysms, stented cases, and flow diversion — long-term surveillance to confirm sustained occlusion and sac shrinkage</li>
              <li><strong>If recanalisation detected:</strong> retreatment with further coiling, flow diversion, or — rarely — surgical clipping is recommended before the aneurysm returns to its pre-treatment anatomy</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">After Surgical Clipping</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li><strong>6 months:</strong> MRA / CT angiogram— confirms clip position and aneurysm occlusion; assesses parent vessel patency</li>
              <li><strong>5 years:</strong> MRA / CT angiogram— checks for de novo aneurysm formation (patients with one aneurysm have 15–20% chance of another)</li>
              <li><strong>Annual thereafter if stable:</strong> for patients with additional unruptured aneurysms being observed</li>
            </ul>
            <div style="background-color: #fce8e6; border-left: 4px solid #d93025; padding: 16px; margin-top: 24px; border-radius: 4px;">
              <p style="margin-bottom: 0; font-size: 0.95rem; color: #a50e0e;"><strong>WARNING:</strong> Skipping follow-up imaging is not safe. Approximately 15–20% of coiled aneurysms show recanalisation at 5 years — most can be treated with a further straightforward procedure if caught early. An undetected recanalised aneurysm that re-ruptures is a catastrophe that follow-up imaging prevents.</p>
            </div>
          </section>

