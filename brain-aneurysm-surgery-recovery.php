          <section id="week-1-3" class="pillar-section">
            <h2 class="pillar-section-title">Week-by-Week Recovery After Elective Aneurysm Treatment (Unruptured)</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/life-after-brain-aneurysm-surgery/weekbyweekrecovery.webp" alt="Week-by-Week Recovery" style="width: 100%; height: auto; display: block;">
