            <h2 class="pillar-section-title">Symptoms of an Unruptured but Symptomatic Aneurysm</h2>
            <p>A minority of unruptured aneurysms do cause symptoms — typically through mass effect (the aneurysm
              pressing on adjacent structures) rather than through bleeding. These symptoms are important because they
              are warning signs that the aneurysm is growing or is at higher risk of rupture.</p>
          </section>

