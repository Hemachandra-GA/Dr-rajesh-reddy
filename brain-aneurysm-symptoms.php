          <section id="faq" class="pillar-section">
            <h2 class="pillar-section-title">Frequently Asked Questions</h2>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q1: My headache was severe but it has gone away — do I still need to go to hospital?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Yes — absolutely. A sudden severe headache that resolves on its own may be a sentinel bleed — a minor
                  leak from an aneurysm before major rupture. The fact that the headache improved does not mean you are
                  safe; it may mean the initial leak sealed temporarily. The risk of catastrophic rupture in the
                  following days to weeks is very high. You must be investigated with a CT brain and, if negative, a
                  lumbar puncture — on the same day if possible.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q2: Can a brain aneurysm cause headaches every day?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  An unruptured aneurysm does not typically cause daily headaches — headache is an uncommon symptom of
                  unruptured aneurysms unless they are very large and causing mass effect. If you have a known aneurysm
                  and develop a new headache pattern that is different from your usual headaches — particularly
                  sudden-onset, severe, or associated with any neurological symptom — this requires urgent evaluation.
                  Routine tension headaches or migraines in someone who happens to have an aneurysm are not necessarily
                  related to the aneurysm.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q3: What does a third nerve palsy look like and why is it an emergency?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  A third nerve (CN III) palsy from aneurysm compression presents as a drooping upper eyelid (ptosis)
                  that the patient cannot open fully, combined with a dilated pupil that does not constrict in light —
                  both on the same side. The eye may also deviate outward and downward because the muscles it controls
                  are paralysed. This combination — ptosis + dilated fixed pupil — is a neurosurgical emergency because
                  it means an aneurysm (almost always at the posterior communicating artery) is compressing the third
                  cranial nerve and may rupture within hours or days. Go to emergency immediately.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q4: Is a thunderclap headache always an aneurysm?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  No — thunderclap headache (sudden, severe, maximal-onset headache) has several causes: subarachnoid
                  hemorrhage from a ruptured aneurysm is the most dangerous and must be excluded first; other causes
                  include reversible cerebral vasoconstriction syndrome (RCVS), cerebral venous thrombosis, hypertensive
                  emergency, and — in a minority — primary thunderclap headache with no underlying cause ('benign
                  thunderclap headache'). The critical point is that SAH must be excluded with CT brain and lumbar
                  puncture before a benign cause is accepted. Approximately 10–25% of thunderclap headaches presenting
                  to emergency departments are caused by SAH.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q5: Can physical exertion trigger an aneurysm rupture?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Yes. Physical exertion — heavy lifting, straining, intense exercise, sexual activity, defaecation —
                  causes a transient spike in blood pressure and intracranial pressure that can trigger aneurysm
                  rupture. This is why approximately 10–20% of SAH episodes occur during or immediately after exertion.
                  Patients with a known unruptured aneurysm awaiting treatment are generally advised to avoid heavy
                  exertion and activities that cause significant straining or blood pressure spikes until the aneurysm
                  is treated.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q6: How is brain aneurysm treated after the emergency is identified?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Once a ruptured aneurysm is confirmed, the priority is to secure it (prevent rebleeding) as early as
                  possible — ideally within 24 hours of SAH. The two main treatments are endovascular coiling (a
                  catheter-based procedure through the groin, no open surgery) and microsurgical clipping (open
                  neurosurgery). Dr. Rajesh Reddy offers both and selects the approach based on the aneurysm's anatomy,
                  the patient's clinical grade, and what is most likely to achieve a safe and durable outcome. For
                  detailed information, see our pillar page on <a href="brain-aneurysm-treatment"
                    style="color: #0066cc;">Brain Aneurysm Treatment</a>.
                </div>
              </div>
            </div>
