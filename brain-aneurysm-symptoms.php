          <!-- Investigations Section -->
          <section id="investigations" class="pillar-section">
            <h2 class="pillar-section-title">How a Brain Aneurysm Is Investigated After Symptoms</h2>



            <h3>CT Brain (Non-Contrast) — First Line in Emergency</h3>
            <p>CT brain is the first investigation in any patient presenting with a thunderclap headache. It is 98%
              sensitive for subarachnoid hemorrhage within the first 12 hours — blood appears as a white (hyperdense)
              area in the basal cisterns, sylvian fissures, or around the brainstem. A negative CT in the first 6 hours
              makes SAH very unlikely, but does not exclude it entirely.</p>

            <h3>Lumbar Puncture — When CT Is Negative</h3>
            <p>If CT is negative but the headache was genuinely sudden-onset and severe, a lumbar puncture is essential.
              CSF is examined for xanthochromia — a yellow discolouration caused by the breakdown of red blood cells in
              the subarachnoid space. Xanthochromia persists for up to 2 weeks after SAH, even when CT has normalised. A
              positive LP in the context of a thunderclap headache is diagnostic of SAH.</p>

            <h3>CT Angiography (CTA) — Identifying the Aneurysm</h3>
            <p>Once SAH is confirmed (or suspected based on symptoms and CT), CT angiography of the cerebral vessels is
              performed urgently to identify the responsible aneurysm — its location, size, shape, and relationship to
              surrounding vessels. Modern multi-slice CT scanners provide near-angiographic resolution and are the
              standard first-line vascular imaging in the emergency setting.</p>
            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/brain-aneurysm-symptoms/CT ANGIOGRAM BRAIN.webp" alt="CT Angiogram Brain"
                style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>Digital Subtraction Angiography (DSA) — The Gold Standard</h3>
            <p>DSA provides the highest resolution imaging of cerebral vessels and is mandatory before any endovascular
              treatment (coiling, flow diversion). It allows real-time visualisation of blood flow, 3D rotational
              imaging of the aneurysm, and precise measurement of the aneurysm neck and dome — essential for planning
              the most appropriate treatment. Dr. Rajesh Reddy performs DSA as part of his integrated diagnostic and
              treatment pathway.</p>
            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/brain-aneurysm-symptoms/Digital Subtraction Angiography (DSA).webp"
                alt="Digital Subtraction Angiography (DSA)"
                style="width: 100%; max-width: 600px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>MRI Brain and MR Angiography (MRA) — For Non-Emergency Cases</h3>
            <p>For patients with an incidentally discovered aneurysm, or for follow-up imaging after treatment, MRI and
              MRA provide excellent non-invasive assessment without radiation. High-resolution 3T MRI with dedicated MRA
              sequences can detect aneurysms as small as 2–3 mm.</p>
