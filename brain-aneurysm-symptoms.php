            <h2 class="pillar-section-title">What to Do If You Suspect a Brain Aneurysm Symptom</h2>

            <h3>Emergency — Thunderclap Headache or Loss of Consciousness</h3>
            <ul>
              <li><strong>Call emergency services (108 or nearest emergency number) immediately</strong> — do not drive
              </li>
              <li>Lay the patient on their side if they are vomiting — to prevent aspiration</li>
              <li>Stay with the patient and monitor their level of consciousness</li>
              <li><strong>Do not give aspirin or ibuprofen</strong> — these may worsen bleeding</li>
              <li>At hospital: insist on an urgent CT brain scan — any delay in imaging increases risk</li>
            </ul>

            <h3>Urgent — New Drooping Eyelid with Dilated Pupil</h3>
            <ul>
              <li>Go to the nearest emergency department immediately — do not wait for an outpatient appointment</li>
              <li>Tell the treating doctor: <em>"I have a new drooping eyelid and dilated pupil — please rule out
                  posterior communicating artery aneurysm"</em></li>
              <li>CT angiography or MR angiography must be performed urgently to visualise the cerebral arteries</li>
            </ul>

            <h3>Urgent — Sentinel Headache That Has Resolved</h3>
            <ul>
              <li>Go to an emergency department on the same day — even if the headache has improved</li>
              <li>Request a CT brain scan — if negative, ask specifically about lumbar puncture to test for
                xanthochromia</li>
              <li>Do not accept a diagnosis of migraine without neuroimaging if the headache was sudden-onset and unlike
                your usual headaches</li>
            </ul>

            <h3>Elective — Incidentally Discovered Aneurysm</h3>
            <ul>
              <li>Book a neurosurgical consultation with Dr. Rajesh Reddy for a comprehensive risk assessment</li>
              <li>Bring all imaging (MRI, MRA, CT angiogram reports and digital films)</li>
              <li>Avoid heavy exertion, straining, or activities that significantly raise blood pressure until the
                assessment is complete</li>
              <li>Do not stop any prescribed blood pressure or other medications without medical advice</li>
            </ul>
