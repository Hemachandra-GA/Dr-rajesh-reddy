          <section id="third-nerve-palsy" class="pillar-section">
            <h2 class="pillar-section-title">Third Nerve Palsy — The Most Important Warning Sign</h2>
            <p>The single most important warning symptom of an unruptured brain aneurysm is a sudden drooping eyelid
              (ptosis) combined with a dilated, non-reactive pupil on the same side. This is called a third cranial
              nerve palsy (CN III palsy) and it signals that an aneurysm — almost always at the posterior communicating
              artery (PComm) — is pressing on or compressing the oculomotor nerve.</p>

            <div class="pillar-callout"
              style="background-color: #fff3e0; border-left: 5px solid #ff9800; padding: 20px; border-radius: 8px; margin: 24px 0;">
              <h4 style="color: #e65100; margin-top: 0; margin-bottom: 8px; font-size: 1.1rem;"><i
                  class="fa-solid fa-triangle-exclamation"></i> CRITICAL WARNING</h4>
              <p style="margin: 0; color: #333;"><strong>NEW DROOPING EYELID + DILATED PUPIL = NEUROSURGICAL
                  EMERGENCY.</strong> This combination, even without headache, indicates possible aneurysm compression
                of the third cranial nerve. Go to emergency immediately.</p>
            </div>

            <p>A CN III palsy from aneurysm compression is a neurological emergency even if the patient has no headache.
              The aneurysm may rupture within hours or days. Any patient who develops a new drooping eyelid with a
              dilated pupil must be taken to an emergency department immediately for CT angiography.</p>
          </section>

          <!-- Mass Effect Symptoms Section -->
          <section id="mass-effect" class="pillar-section">
            <h2 class="pillar-section-title">Other Mass Effect Symptoms of Unruptured Aneurysms</h2>
            <ul>
              <li><strong>Progressive visual loss:</strong> A large aneurysm at the ophthalmic artery or internal
                carotid artery can compress the optic nerve, causing gradual or sudden visual loss in one eye. A large
                anterior communicating or cavernous sinus aneurysm may cause bitemporal visual field loss by compressing
                the optic chiasm.</li>
              <li><strong>Facial pain or numbness:</strong> A cavernous sinus or basilar artery aneurysm may compress
                the trigeminal nerve (CN V), causing facial pain, numbness, or a pins-and-needles sensation across the
                cheek, jaw, or forehead.</li>
              <li><strong>Double vision without ptosis:</strong> Involvement of CN IV or CN VI — which control eye
                movement — produces double vision without the drooping eyelid or pupil dilation seen in CN III palsy.
                Seen with cavernous sinus or posterior circulation aneurysms.</li>
              <li><strong>Pulsatile tinnitus:</strong> A rhythmic whooshing sound in the ear, synchronous with the
                heartbeat, occasionally reported with large aneurysms close to the ear or cavernous sinus.</li>
              <li><strong>Headache:</strong> A persistent, new headache — particularly one felt behind one eye —
                associated with a known or suspected aneurysm warrants urgent evaluation. Aneurysmal headaches are often
                described as dull and persistent, rather than throbbing or episodic.</li>
            </ul>

            <h3>Giant Aneurysms — A Distinct Presentation</h3>
            <p>Giant aneurysms (≥ 25 mm) that are partially thrombosed — where blood has clotted within part of the
              aneurysm sac — can present in an entirely different way from smaller aneurysms. The clot within the sac
              can shed small emboli into the brain circulation, causing Transient Ischaemic Attacks (TIAs, or
              mini-strokes) — brief, reversible episodes of weakness, speech difficulty, or visual disturbance lasting
              minutes to hours. The partially thrombosed sac may also irritate adjacent cortex, triggering new-onset
              seizures. In large aneurysms exerting significant mass effect on the adjacent brain tissue, patients may
              develop progressive weakness of one side of the body (hemiparesis) that worsens over weeks — closely
              mimicking a brain tumour presentation. These mass-effect and embolic presentations of giant aneurysms are
              important to recognise because the correct diagnosis requires urgent neurovascular imaging, not just a
              standard stroke or tumour workup.</p>
          </section>

          <!-- Sentinel Headache Section -->
          <section id="sentinel-headache" class="pillar-section">
            <h2 class="pillar-section-title">The Sentinel Headache: The Warning That Is Most Often Missed</h2>
            <p>In the days, weeks, or occasionally months before a major aneurysm rupture, approximately 20–50% of
              patients experience what is called a <strong>sentinel headache</strong> — a sudden, severe headache caused
              by a minor leak or rapid expansion of the aneurysm wall that does not constitute a full rupture. Blood
              leaks into the subarachnoid space in a small quantity, causing sudden irritation of the meninges — but not
              the catastrophic flooding of SAH.</p>
            <p>The sentinel headache is clinically indistinguishable from the headache of full SAH in terms of its onset
              speed and initial severity. However, because the blood leak is small, the patient may recover relatively
              quickly — within hours — and be tempted to attribute the headache to stress, dehydration, or a
              particularly severe migraine. This is the most dangerous mistake in cerebrovascular medicine.</p>

            <h3>Characteristics of a Sentinel Headache</h3>
            <ul>
              <li><strong>Sudden onset</strong> — reaching maximum severity within seconds, not minutes</li>
              <li><strong>Severe</strong> — typically described as the worst or one of the worst headaches the patient
                has ever experienced</li>
              <li><strong>Genuinely new</strong> — different in character, location, or severity from any previous
                headache</li>
              <li>May be associated with nausea, vomiting, or transient neck stiffness</li>
              <li>May be followed by a period of feeling 'not quite right' or unusually fatigued</li>
              <li><strong>Resolves within hours or a day</strong> — which reassures the patient but does not indicate
                safety</li>
            </ul>

            <div class="pillar-callout"
              style="background-color: #fbe9e7; border-left: 5px solid #d32f2f; padding: 20px; border-radius: 8px; margin: 24px 0;">
              <h4 style="color: #c62828; margin-top: 0; margin-bottom: 8px; font-size: 1.1rem;"><i
                  class="fa-solid fa-triangle-exclamation"></i> CRITICAL CLINICAL INSIGHT</h4>
              <p style="margin: 0; color: #333;">A sudden severe headache that resolves within hours is not necessarily
                safe. If it was the worst headache of your life, you must be investigated. A CT scan negative for blood
                does not exclude a small sentinel bleed — a lumbar puncture is required to look for xanthochromia
                (yellow CSF from blood breakdown). Studies show that sentinel headaches are misdiagnosed as migraine in
                up to 50% of cases, and these patients return days to weeks later with a catastrophic rupture.</p>
            </div>

            <h3>What Happens If a Sentinel Headache Is Missed</h3>
            <p>If a sentinel headache is not investigated and the underlying aneurysm is not treated, the risk of major
              rupture (full SAH) in the following weeks is very high — estimated at 30–50% within 30 days. Major SAH
              carries a mortality of approximately 40–50%, and half of survivors have permanent neurological disability.
              The sentinel headache represents the last window of opportunity to prevent catastrophe.</p>
          </section>

          <!-- Thunderclap Headache Section -->
          <section id="thunderclap-headache" class="pillar-section">
            <h2 class="pillar-section-title">The Thunderclap Headache: A Ruptured Aneurysm Until Proven Otherwise</h2>
            <p>Rupture of a brain aneurysm causes subarachnoid hemorrhage (SAH) — sudden, high-pressure bleeding into
              the subarachnoid space that bathes the brain. The hallmark is the <strong>thunderclap headache</strong>:
              an instantaneous, explosive headache that reaches absolute maximum severity within 1–2 seconds.</p>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/brain-aneurysm-symptoms/ruptured_aneurysm.webp" alt="Ruptured Brain Aneurysm"
                style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>
            <p>Patients who have experienced it describe it with remarkable consistency:</p>
            <ul>
              <li><em>"A gun went off inside my head"</em></li>
              <li><em>"Someone hit me on the back of the head with a cricket bat"</em></li>
              <li><em>"The worst pain I have ever felt in my life — like an explosion"</em></li>
              <li><em>"I was absolutely fine one moment and then could not see, hear, or move for the pain"</em></li>
            </ul>

            <h3>Associated Symptoms of Ruptured Aneurysm / SAH</h3>
            <ul>
              <li><strong>Immediate vomiting:</strong> Often projectile, occurring within seconds to minutes of the
                headache. The vomiting is caused by the sudden rise in intracranial pressure from the haemorrhage and
                the irritation of the meninges.</li>
              <li><strong>Neck stiffness (meningism):</strong> Blood in the subarachnoid space irritates the meninges,
                causing painful resistance to neck flexion — typically developing within 3–6 hours of rupture. This is
                one of the classic signs of SAH on clinical examination.</li>
              <li><strong>Photophobia and phonophobia:</strong> Extreme sensitivity to light and sound, also from
                meningeal irritation — similar to severe migraine, but in the context of a thunderclap headache.</li>
              <li><strong>Loss of consciousness:</strong> Transient loss of consciousness at the time of rupture occurs
                in approximately 45% of SAH patients — caused by the sudden spike in intracranial pressure momentarily
                stopping cerebral perfusion. Prolonged unconsciousness indicates a more severe bleed.</li>
              <li><strong>Seizure:</strong> Occurs in approximately 10–20% of SAH patients at or shortly after rupture.
                A seizure in the context of a thunderclap headache is a strong indicator of SAH.</li>
              <li><strong>Focal neurological deficits:</strong> Weakness on one side, speech difficulty, or visual loss
                — indicating that the haemorrhage or associated haematoma has affected specific brain regions.</li>
              <li><strong>Sudden death:</strong> Approximately 10–15% of SAH patients die before reaching hospital —
                from the initial haemorrhage causing catastrophic brain injury or cardiac arrest. This underlines why
                every thunderclap headache is a medical emergency.</li>
            </ul>

