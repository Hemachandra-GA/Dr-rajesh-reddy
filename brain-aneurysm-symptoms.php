              <p style="margin: 0; color: #333;"><strong>CALL EMERGENCY SERVICES IMMEDIATELY</strong> if anyone
                experiences: a sudden severe headache reaching maximum intensity within seconds — particularly if
                accompanied by vomiting, neck pain, loss of consciousness, or seizure. Do not drive to hospital. Do not
                wait to see if the headache improves. Every minute without treatment after aneurysm rupture increases
                the risk of rebleeding, vasospasm, and death.</p>
            </div>
