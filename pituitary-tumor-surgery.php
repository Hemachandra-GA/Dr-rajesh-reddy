            <h2 class="pillar-section-title">Pituitary Tumor Symptoms: Why They Are Often Missed</h2>
            <p>Pituitary tumor symptoms fall into two categories that often develop so gradually that patients adapt to them before recognising they are abnormal:</p>

            <h3>Hormonal (Endocrine) Symptoms — The Most Commonly Missed</h3>
            <p><strong>Prolactinoma:</strong> Irregular or absent menstrual periods; unexpected milk discharge from the breasts (galactorrhoea) without pregnancy; difficulty conceiving in women. In men: reduced libido, erectile dysfunction, infertility, and rarely — gynaecomastia (breast enlargement). Because these symptoms overlap with many other causes, patients are often investigated and treated for other conditions before the prolactinoma is identified.</p>
            <p><strong>Cushing's Disease (ACTH excess):</strong> Progressive weight gain predominantly around the abdomen and face ('moon face'); purple stretch marks (striae) on the abdomen, thighs, and arms; easy bruising; high blood pressure; elevated blood sugar (diabetes); muscle weakness; mood disturbances including depression. The diagnosis requires specific cortisol testing — not just a blood glucose check.</p>
            <p><strong>Acromegaly (GH excess):</strong> Gradual enlargement of the hands and feet (patients notice rings and shoes no longer fitting); coarsening of facial features; enlarged jaw, brow, and nose; excessive sweating; joint pain; carpal tunnel syndrome; obstructive sleep apnoea. These changes are so gradual that patients — and their families — often fail to notice them until they compare old photographs.</p>

            <h3>Mass Effect Symptoms — Pressing on Surrounding Structures</h3>
            <ul>
              <li><strong>Bitemporal hemianopia:</strong> The classic visual field defect of pituitary macroadenoma — loss of the outer (temporal) half of the visual field in both eyes, caused by compression of the optic chiasm directly above the pituitary. Patients often describe walking into door frames or difficulty seeing objects to their side.</li>
              <li><strong>Headache:</strong> Dull, often retro-orbital (behind the eyes); caused by pressure within the sella turcica or by tumour extension beyond it.</li>
              <li><strong>Pituitary insufficiency (hypopituitarism):</strong> When a macroadenoma compresses normal pituitary tissue, it can suppress production of any or all pituitary hormones — leading to fatigue, weight changes, cold intolerance (hypothyroidism), reduced libido, and adrenal insufficiency.</li>
              <li><strong>Diabetes Insipidus:</strong> Excessive thirst and very high urine output, caused by compression or damage to the posterior pituitary or hypothalamus.</li>
            </ul>

