            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Inferior Petrosal Sinus Sampling (IPSS)</h3>
            <p>Inferior Petrosal Sinus Sampling (IPSS) is a specialised endovascular procedure recommended for patients with biochemically confirmed Cushing's disease when the pituitary MRI is normal or equivocal — which occurs in up to 40% of cases. It involves sampling blood from the inferior petrosal sinuses (small veins draining the pituitary) after stimulation with CRH, to confirm that the ACTH excess is of pituitary origin and to lateralise the source to the left or right side of the gland. This information directly guides the surgeon during endoscopic exploration. Dr. Rajesh Reddy's endovascular training equips him to perform this procedure himself, providing an integrated diagnostic and surgical pathway for Cushing's disease patients.</p>

