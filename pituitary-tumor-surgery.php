            <h2 class="pillar-section-title">Endoscopic Transsphenoidal Pituitary Surgery: How It Works</h2>
            <p>The endoscopic transsphenoidal approach to the pituitary gland is one of the great success stories of modern minimally invasive neurosurgery. It exploits a natural anatomical corridor — the nostrils &rarr; nasal cavity &rarr; sphenoid sinus &rarr; sella turcica — to access the pituitary gland without any external incision or brain retraction.</p>

            <h3>Step-by-Step: What Happens During the Procedure</h3>
            <ul>
              <li>The patient is placed supine with the head slightly extended. General anaesthesia is administered.</li>
              <li>Neuronavigation is set up using pre-operative MRI data, providing real-time 3D GPS guidance throughout the procedure.</li>
              <li>A high-definition 4mm endoscope is introduced through one nostril. The nasal mucosa is gently displaced rather than incised where possible.</li>
              <li>The sphenoid sinus — an air-filled cavity directly in front of the sella turcica — is entered. The bony face of the sella is identified and a small opening is made.</li>
              <li>The dura (the protective membrane over the pituitary) is opened carefully, exposing the pituitary gland and the tumor within it.</li>
              <li>The tumor is removed using fine curettes, suction, and ring curettes, working within the pituitary fossa and — where the tumor extends upward — gently following it into the suprasellar space as it descends after intrasellar removal.</li>
              <li>The sella is then closed using a multilayer reconstruction — typically with a fat graft and a small piece of fascia harvested through a tiny 1–2 cm incision on the outer aspect of the thigh (a quick, separate part of the same procedure, leaving a small scar that heals well). The fat and fascia are used to seal the portal of entry in the sphenoid sinus and the floor of the sella, supplemented with a dural sealant and, where needed, a vascularised nasoseptal flap — to prevent CSF leak.</li>
              <li>The nasal passage is inspected and, if a septal flap was raised, repositioned. No external sutures. Nasal sponges (soft absorbable or non-absorbable packs) are placed in the nostrils at the end of the procedure and remain for 24–48 hours. During this period patients breathe through the mouth — the nursing team will ensure mouth care and adequate hydration. The sponges are removed bedside without anaesthesia before discharge.</li>
            </ul>

