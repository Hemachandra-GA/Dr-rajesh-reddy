            <h2 class="pillar-section-title">Special Cases: Surgery for Cushing's Disease & Acromegaly</h2>

            <h3>A Special Case: Surgery for Cushing's Disease</h3>
            <p>Cushing's disease — caused by an ACTH-secreting pituitary microadenoma — is among the most surgically challenging pituitary conditions. The responsible microadenoma is often very small (3–5 mm) and may not be visible on MRI. In these cases, surgical cure depends entirely on surgeon experience, quality IPSS lateralisation data, and meticulous intraoperative exploration.</p>
            <p><strong>Biochemical cure in Cushing's disease</strong> is defined as a morning serum cortisol of less than 50–138 nmol/L in the immediate post-operative period. Remission rates after endoscopic transsphenoidal surgery in experienced centres are <strong>70–90% for microadenomas</strong> and <strong>50–65% for macroadenomas</strong>.</p>

            <h3>Surgery for Acromegaly: Goals and Outcomes</h3>
            <p>Acromegaly — caused by a GH-secreting somatotroph adenoma — is treated primarily with surgery. The goals are:</p>
            <ul>
              <li><strong>Achieve biochemical remission</strong> — normalisation of IGF-1 and suppression of GH to &lt; 1 ng/mL on glucose tolerance test</li>
              <li><strong>Decompress the optic chiasm</strong> if visual field defects are present</li>
              <li><strong>Reduce tumor bulk</strong> to improve response to medical therapy (somatostatin analogues) if complete resection is not achieved</li>
            </ul>
            <p>Remission rates after surgery for acromegaly are 85–90% for microadenomas and 50–70% for macroadenomas without cavernous sinus invasion.</p>

