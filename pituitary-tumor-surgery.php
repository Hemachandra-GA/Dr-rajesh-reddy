            <h2 class="pillar-section-title">Types of Pituitary Tumors: Functioning vs. Non-Functioning</h2>
            <p>Pituitary adenomas are benign tumors of the pituitary gland. They are classified by size and by whether they secrete hormones. Understanding this classification is essential, because it determines the symptoms, the diagnosis, and critically — the treatment approach.</p>

            <h3>By Size</h3>
            <p><strong>Microadenoma:</strong> Less than 10 mm in diameter. Often found incidentally or during workup for hormonal symptoms. Treated medically or surgically depending on the hormone secreted.</p>
            <p><strong>Macroadenoma:</strong> 10 mm or larger. More likely to cause mass effect — compressing the optic chiasm, invading the cavernous sinus, or causing pituitary insufficiency. Almost always requires surgery.</p>

