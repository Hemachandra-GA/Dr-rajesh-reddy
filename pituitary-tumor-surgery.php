            <h2 class="pillar-section-title">Recovery After Endoscopic Pituitary Surgery</h2>

            <h3>Day 0–1 (Surgery & Immediate Post-Op)</h3>
            <ul>
              <li>Surgery typically takes 1.5–3 hours depending on tumor size and complexity.</li>
              <li>Patient wakes in the recovery room and is transferred to a neurosurgical ward (HDU monitoring for the first night).</li>
              <li>Mild nasal congestion and a sensation of fullness in the nose are the most common complaints.</li>
              <li>Headache is usually mild and well-controlled with simple analgesics.</li>
              <li>If a lumbar drain has been placed to reduce the risk of cerebrospinal fluid (CSF) leak, it is typically maintained for several days while drainage is carefully monitored.</li>
              <li>Sodium and fluid balance monitored closely for the first 48–72 hours — diabetes insipidus, if it occurs, typically presents in this window.</li>
            </ul>

            <h3>Days 2–3 (Discharge Planning)</h3>
            <ul>
              <li>Nasal packs (absorbable or sponge packs, if used) are usually removed on post-operative Day 2, resulting in improved nasal breathing and comfort.</li>
              <li>Most patients are fit for discharge on day 2 or 3.</li>
              <li>Hormonal blood tests repeated to assess immediate post-operative pituitary function.</li>
              <li>Nasal saline irrigation started to aid mucosal healing and prevent crusting.</li>
              <li>Clear instructions given on symptoms that require urgent return: clear fluid dripping from the nose (possible CSF leak), new severe headache, sudden vision change, or high fever.</li>
            </ul>

            <h3>Day 5 (If Lumbar Drain Was Placed)</h3>
            <ul>
              <li>The lumbar drain, if inserted during surgery, is typically removed around Day 5 after confirming there is no evidence of a CSF leak and the skull base repair is healing satisfactorily.</li>
            </ul>

