  <script>
    document.addEventListener('DOMContentLoaded', function () {
      // Intersection Observer for highlighting sidebar links based on scroll position
      const sections = document.querySelectorAll('.pillar-section');
      const navLinks = document.querySelectorAll('.sidebar-nav-link');

      const observerOptions = {
        root: null,
        rootMargin: '-20% 0px -60% 0px',
        threshold: 0
      };

      const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            const currentId = entry.target.getAttribute('id');
            navLinks.forEach(link => {
              link.classList.remove('active');
              if (link.getAttribute('href') === `#${currentId}`) {
                link.classList.add('active');
              }
            });
          }
        });
      }, observerOptions);

      sections.forEach(section => {
        observer.observe(section);
      });

      // FAQ Accordion functionality
      const faqQuestions = document.querySelectorAll('.pillar-faq-q');
      faqQuestions.forEach(question => {
        question.addEventListener('click', () => {
          const answer = question.nextElementSibling;
          const icon = question.querySelector('i');

          if (answer.style.maxHeight) {
            answer.style.maxHeight = null;
            icon.style.transform = 'rotate(0deg)';
          } else {
            // Close all others
            document.querySelectorAll('.pillar-faq-a').forEach(a => a.style.maxHeight = null);
            document.querySelectorAll('.pillar-faq-q i').forEach(i => i.style.transform = 'rotate(0deg)');

            // Open this one
            answer.style.maxHeight = answer.scrollHeight + "px";
            icon.style.transform = 'rotate(180deg)';
          }
        });
      });
    });
  </script>
