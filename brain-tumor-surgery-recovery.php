            <h2 class="pillar-section-title">Frequently Asked Questions</h2>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q1: How long will I be in hospital after brain tumor surgery?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Hospital stay after craniotomy is typically 5–7 days for most procedures. Endoscopic pituitary surgery has a shorter stay of 2–3 days. Patients who experience post-operative complications, significant neurological deficits, or medical comorbidities may stay longer.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q2: Is it normal to feel worse before I feel better after brain surgery?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Yes — and this is one of the most important things for patients and families to understand. In the first 48–72 hours after surgery, post-operative brain swelling often causes a temporary worsening of the same symptoms the tumor was causing — more headache, more fatigue, sometimes more weakness or speech difficulty. This typically improves significantly as steroids reduce the swelling over the first week.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q3: When can I wash my hair after brain tumor surgery?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Gentle hair washing is typically permitted from day 10–14, after sutures or staples have been removed. Use lukewarm water and a mild shampoo; avoid scrubbing the wound. Do not submerge the head in water (swimming, bathing) until the wound is fully healed — usually at 4–6 weeks.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q4: Will I have seizures after brain tumor surgery?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  The risk of post-operative seizures depends on the tumor type and its location. Cortical tumors — particularly gliomas and convexity meningiomas — carry the highest seizure risk. Anti-epileptic medication is prescribed prophylactically after these procedures and is typically continued for a minimum of 3–6 months.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q5: When can I travel after brain tumor surgery?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Short-distance travel by car is typically permissible from week 2–3 as a passenger. Long-distance travel or air travel is generally deferred until at least 6 weeks after surgery — air travel in particular carries a risk of intracranial pressure changes at altitude in the immediate post-operative period.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q6: How often will I need MRI scans after brain tumor surgery?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  MRI surveillance schedule depends on the tumor type. For benign tumors after complete resection: typically at 6 weeks, then annually for 5 years, then every 2 years. For low-grade gliomas: every 3–6 months for 2 years, then annually. For GBM and high-grade gliomas: every 2–3 months throughout treatment.
                </div>
              </div>
