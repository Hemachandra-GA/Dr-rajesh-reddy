            <h2 class="pillar-section-title">Week-by-Week Recovery Guide</h2>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/recovery-after-brain-tumor-surgery/recovery_timeline.webp" alt="Brain Tumor Surgery Recovery Timeline" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
