            <h2 class="pillar-section-title">A Note for Caregivers and Family Members</h2>
            <p>Brain tumor surgery does not happen to a patient in isolation — it happens to a family. Caregivers carry an enormous burden during the recovery period: providing physical care, managing medications, attending appointments, and supporting the patient emotionally while managing their own anxiety and grief.</p>

            <h4 style="font-size: 1.1rem; margin-bottom: 12px;">Practical Guidance for Caregivers</h4>
            <ul>
              <li><strong>Keep a medication record:</strong> Note the name, dose, and timing of every medication, and tick it off when given. Errors in medication are a significant source of post-discharge problems.</li>
              <li><strong>Observe and report:</strong> You will often notice neurological changes before the patient does. If the patient seems more confused, slower, or different from their baseline, contact the clinic.</li>
              <li><strong>Encourage but do not push:</strong> Fatigue is real, and patients cannot think their way through it. Balance encouragement to move with acceptance that rest is part of healing.</li>
              <li><strong>Monitor mood:</strong> Depression and anxiety after brain tumor surgery are common and treatable. If the patient withdraws or expresses hopelessness, discuss this with Dr. Rajesh Reddy.</li>
              <li><strong>Look after yourself:</strong> Caregiver burnout is real. Accept help from extended family, friends, and community.</li>
            </ul>
