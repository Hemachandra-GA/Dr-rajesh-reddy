            <h3>Day 0–2: Surgery Day and ICU / HDU</h3>
            <p>Immediately after surgery, you will wake in the recovery room. You will be transferred to the Neurosurgical ICU or HDU for close monitoring. Neurological observations (level of consciousness, pupil responses, limb movement, speech) are performed every 1–2 hours.</p>
            <ul>
              <li><strong>Headache:</strong> Dull pressure ache around operative site, managed with IV and oral analgesics.</li>
              <li><strong>Nausea:</strong> Common in the first 12–24 hours; routinely treated with anti-emetics.</li>
              <li><strong>Fatigue:</strong> Exhaustion is normal as the brain uses significant energy for early healing.</li>
              <li><strong>Facial Swelling:</strong> Peaks at 48–72 hours and resolves over 1–2 weeks.</li>
              <li><strong>Steroids (Dexamethasone):</strong> Administered to control brain swelling.</li>
            </ul>

            <div class="pillar-callout" style="border-left-color: #d9383a; background-color: #fdf2f2;">
              <h4 style="color: #d9383a;"><i class="fa-solid fa-triangle-exclamation" style="margin-right: 8px;"></i>SEEK IMMEDIATE ATTENTION IF YOU DEVELOP:</h4>
              <p style="margin-bottom: 0; color: #1d1d1f;">Sudden severe headache worse than before surgery — new or rapidly worsening weakness/speech loss — seizure — unequal pupils — sudden loss of consciousness.</p>
            </div>

            <h3 style="margin-top: 28px;">Day 3–7: Ward Recovery and Discharge Preparation</h3>
            <p>By day 3, patients transfer to the neurosurgical ward. IV lines and urinary catheters are removed, and mobility begins with physiotherapy support.</p>
            <ul>
              <li><strong>Post-operative MRI:</strong> Performed at 24–72 hours to confirm resection extent and establish a baseline.</li>
              <li><strong>Wound Care:</strong> Sutures/staples are typically removed at 10–14 days.</li>
              <li><strong>Physiotherapy & Speech Therapy:</strong> In-hospital assessment and mobility exercises commence.</li>
              <li><strong>Discharge Criteria:</strong> Neurologically stable, walking independently or with minimal aid, eating/drinking normally.</li>
            </ul>

            <h3 style="margin-top: 28px;">Week 2–4: Early Home Recovery</h3>
            <p>The first two weeks at home prioritize rest. Fatigue is biology, not laziness — the brain requires quiet energy to repair itself.</p>
            <ul>
              <li><strong>Fatigue:</strong> Peaks in week 2–3; short daily rest periods are normal and helpful.</li>
              <li><strong>Headaches:</strong> Typically progressively improving to dull, intermittent discomfort managed with paracetamol.</li>
              <li><strong>Scalp Numbness &amp; Hair Loss:</strong> Numbness around the incision cut nerves regenerates over months. Hair thinning near the incision is temporary.</li>
              <li><strong>Activity Restrictions:</strong> No driving for 4–6+ weeks (subject to medical clearance &amp; seizure-risk assessment); no heavy lifting or strenuous exercise; no swimming until wound is fully healed.</li>
            </ul>

            <h4 style="font-size: 1.1rem; margin-top: 18px; margin-bottom: 10px;">Wound Care at Home</h4>
            <ul>
              <li>Keep the wound clean and dry for the first 2 weeks.</li>
              <li>Gentle hair washing permitted after suture/staple removal (day 10–14).</li>
              <li>Avoid direct sun on the scar for at least 3 months — use a hat or sunscreen once healed.</li>
              <li>Do not apply creams, oils, or traditional remedies to the wound without medical advice.</li>
            </ul>

            <h3 style="margin-top: 28px;">Week 4–8: Progressive Recovery</h3>
            <p>By week 4, energy improves and cognitive 'brain fog' starts to clear. Focus shifts from rest to gradual reintegration into daily life.</p>
            
            <h4 style="font-size: 1.1rem; margin-top: 18px; margin-bottom: 10px;">Cognitive Recovery</h4>
            <p>Brain surgery can temporarily impair concentration, word-finding, short-term memory, and processing speed as the brain heals. Practical strategies during this phase:</p>
            <ul>
              <li>Use lists and reminders for tasks previously done from memory.</li>
              <li>Take regular breaks during cognitively demanding activities (reading, screens, conversation).</li>
              <li>Avoid multitasking; focus on one activity at a time.</li>
              <li>Accept help from family members; cognitive fatigue is real and should not be pushed through.</li>
            </ul>

            <h4 style="font-size: 1.1rem; margin-top: 18px; margin-bottom: 10px;">Return to Work &amp; 6-Week Review</h4>
            <ul>
              <li><strong>Return to Work:</strong> Desk jobs from week 4–6 (starting part-time); manual or physical roles from 3–6 months.</li>
              <li><strong>6-Week Follow-Up Appointment:</strong> 6-week MRI review, neurological exam, steroid/AED tapering plan, and pathology/oncology treatment planning.</li>
            </ul>

            <h3 style="margin-top: 28px;">Month 2–3: Adjuvant Treatment (Malignant Tumors)</h3>
            <p>For patients with high-grade gliomas (GBM) or brain metastases, adjuvant radiation and chemotherapy begin around week 4–6.</p>
            <ul>
              <li><strong>Stupp Protocol (GBM):</strong> 6 weeks of daily radiotherapy (60 Gy) + daily oral temozolomide, followed by 6 monthly cycles of adjuvant temozolomide.</li>
              <li><strong>Fatigue Management:</strong> Prioritize 8–9 hours of sleep, light 15-minute daily walks, and adequate nutrition with clinical dietitian support.</li>
            </ul>

            <h3 style="margin-top: 28px;">Month 3–6: Functional Recovery and Rehabilitation</h3>
            <p>For patients requiring ongoing functional recovery, targeted rehabilitation services help optimize long-term independence:</p>
            <ul>
              <li><strong>Physiotherapy:</strong> Progressive exercises for motor strength, gait, and balance (deficits continue to improve up to 12 months).</li>
              <li><strong>Speech and Language Therapy (SLT):</strong> Structured home &amp; clinic exercises for word-finding and articulation.</li>
              <li><strong>Occupational Therapy:</strong> Workplace adaptation and daily task independence.</li>
              <li><strong>Neuropsychological Rehabilitation:</strong> Structured cognitive strategies guided by 3-month neuropsychological assessment.</li>
              <li><strong>Psychological Support:</strong> Routine counselling for anxiety, depression, and coping strategies for patients and caregivers.</li>
            </ul>
          </section>

