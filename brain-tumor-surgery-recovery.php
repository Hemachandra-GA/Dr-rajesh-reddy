          <section id="warning-signs" class="pillar-section">
            <h2 class="pillar-section-title">Warning Signs: When to Seek Urgent Help</h2>

            <div class="pillar-callout" style="border-left-color: #d9383a; background-color: #fdf2f2;">
              <h4 style="color: #d9383a;"><i class="fa-solid fa-triangle-exclamation" style="margin-right: 8px;"></i>SEEK IMMEDIATE MEDICAL ATTENTION IF YOU EXPERIENCE:</h4>
              <ul style="margin-bottom: 0; color: #1d1d1f;">
                <li>A new or first seizure at any point after discharge</li>
                <li>Rapidly worsening headache different from your usual post-op headache</li>
                <li>New weakness, speech loss, or vision change</li>
                <li>Fever above 38.5°C with headache and stiff neck</li>
                <li>Wound that is red, hot, swollen, or discharging pus</li>
                <li>Clear fluid dripping from the nose (possible CSF leak after pituitary surgery)</li>
                <li>Sudden confusion or unresponsiveness</li>
              </ul>
            </div>

            <h4 style="font-size: 1.1rem; margin-top: 24px; margin-bottom: 12px;">Symptoms That Are Normal and Do Not Require Emergency Care</h4>
            <ul>
              <li>Mild to moderate headache that is improving over time — manageable with paracetamol</li>
              <li>Fatigue, even if profound — this is a normal part of brain healing</li>
              <li>Scalp numbness, tingling, or itching around the wound — nerve regeneration</li>
              <li>Mild mood changes or emotional sensitivity</li>
              <li>Some degree of cognitive fog or word-finding difficulty in the first 6 weeks</li>
              <li>Hair thinning around the wound site — almost always temporary</li>
            </ul>
          </section>

