          <section id="endovascular-coiling" class="pillar-section">
            <h2 class="pillar-section-title">Endovascular Coiling: Treating a Brain Aneurysm Without Opening the Skull</h2>
            <div style="margin: 20px 0 24px; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 16px rgba(0,0,0,0.08); display: flex; justify-content: center;">
              <img src="images/expert-care-for-brain-aneurysms/endovascular_coiling.webp" alt="Endovascular Coiling Treatment" style="max-width: 100%; height: auto; display: block;">
            </div>
            <p>Endovascular coiling has become the preferred treatment for the majority of ruptured brain aneurysms following the landmark ISAT trial (International Subarachnoid Aneurysm Trial, 2002), which demonstrated superior outcomes for coiling compared to surgical clipping in patients suitable for both techniques.</p>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">How Coiling Works</h3>
            <p>Under general anaesthesia, a catheter is introduced through a small puncture in the femoral artery (groin) and navigated under X-ray fluoroscopy guidance up through the aorta, the carotid or vertebral arteries, and into the cerebral vasculature. A microcatheter is then advanced into the aneurysm sac, and soft platinum coils — thinner than a human hair — are deployed to fill the aneurysm. The coils cause thrombosis (clotting) within the aneurysm, which progressively seals it from the circulation.</p>
            <p>For aneurysms with a wide neck — where simple coiling risks coil herniation into the parent artery — additional techniques are used: balloon-assisted coiling (temporarily inflating a balloon across the aneurysm neck during coil deployment) or stent-assisted coiling (placing a stent in the parent artery to provide a scaffold that holds the coils within the aneurysm).</p>
          </section>

          <!-- Flow Diversion -->
          <section id="flow-diversion" class="pillar-section">
            <h2 class="pillar-section-title">Flow Diversion: Extrasaccular Flow Diverters — Pipeline, Surpass, SILK, p64, FRED, Derivo</h2>
            <p>Flow diversion represents the most significant advance in endovascular aneurysm treatment of the past decade. Rather than filling the aneurysm with coils, a flow diverter is a densely woven, stent-like device deployed in the parent artery across the aneurysm neck. The device redirects blood flow away from the aneurysm, causing progressive thrombosis and eventual complete occlusion — while simultaneously providing a scaffold for neo-endothelialisation across the aneurysm neck.</p>
            <p>Flow diversion achieves complete aneurysm occlusion in approximately 75–85% of cases at 6 months and up to 95% at 2 years. It has become the treatment of choice for large and giant aneurysms, fusiform aneurysms, and wide-neck aneurysms that are not amenable to simple coiling. The patient requires dual antiplatelet medication (aspirin + clopidogrel) for 3–6 months after device deployment to prevent device thrombosis.</p>
