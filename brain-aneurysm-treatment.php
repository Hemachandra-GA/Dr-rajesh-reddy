          <!-- What Is a Brain Aneurysm? -->
          <section id="what-is-aneurysm" class="pillar-section">
            <h2 class="pillar-section-title">What Is a Brain Aneurysm?</h2>
            <div style="margin: 20px 0 24px; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 16px rgba(0,0,0,0.08); display: flex; justify-content: center;">
              <img src="images/expert-care-for-brain-aneurysms/brain_anueurysm.webp" alt="What Is a Brain Aneurysm" style="max-width: 100%; height: auto; display: block;">
            </div>
            <p>A brain aneurysm (also called an intracranial or cerebral aneurysm) is a localised ballooning or bulging of a brain artery caused by a weakness in the arterial wall. As blood pulses through the artery, the weakened segment expands under pressure — much like a weak spot in a bicycle tyre bulging outward. The aneurysm may remain stable for years, or it may grow and eventually rupture, releasing blood into the subarachnoid space (the fluid-filled area between the brain and its protective membranes).</p>
            <p>Brain aneurysms are more common than most people realise — population studies estimate a prevalence of approximately 2–5% of the adult population, meaning millions of people worldwide carry an unruptured aneurysm without knowing it. The challenge is that the vast majority cause no symptoms until — or unless — they rupture.</p>
          </section>

          <!-- Where Do Brain Aneurysms Form? -->
          <section id="locations" class="pillar-section">
            <h2 class="pillar-section-title">Where Do Brain Aneurysms Form?</h2>
            <p>Aneurysms preferentially develop at the branching points of cerebral arteries, where haemodynamic stress is highest. The most common locations include:</p>
            <ul>
              <li><strong>Anterior communicating artery (ACoA)</strong> — most common single site (~30%)</li>
              <li><strong>Posterior communicating artery (PCoA)</strong> — arises at the junction of the internal carotid and posterior communicating arteries (~25%)</li>
              <li><strong>Middle cerebral artery (MCA) bifurcation</strong> — the most common location for aneurysms treated surgically (~20%)</li>
              <li><strong>Internal carotid artery</strong> — including cavernous and paraclinoid segments (~10%)</li>
              <li><strong>Basilar artery tip and posterior circulation</strong> — (~10%); these carry higher rupture risk</li>
              <li><strong>Anterior cerebral / pericallosal artery</strong> — less common</li>
            </ul>
          </section>

