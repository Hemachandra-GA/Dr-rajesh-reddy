          <!-- Intrasaccular Devices -->
          <section id="intrasaccular-devices" class="pillar-section">
            <h2 class="pillar-section-title">Intrasaccular Devices: WEB, Contour, Artisse</h2>
            <p>The Woven EndoBridge (WEB) device is a single-layer or double-layer mesh device deployed entirely within the aneurysm sac, disrupting flow at the aneurysm neck. It is particularly suited to wide-neck bifurcation aneurysms — such as MCA bifurcation and basilar tip aneurysms — where it avoids the need for a stent in the parent vessel and the associated requirement for dual antiplatelet therapy. The WEB device can be deployed in a single session and does not require a stent, simplifying the procedure and the post-operative medication regimen. Other intrasaccular devices now available include the Contour and Artisse devices — each designed for specific aneurysm neck geometries, offering expanding options for wide-neck bifurcation aneurysms without the need for parent vessel stenting.</p>
          </section>

          <!-- Microsurgical Clipping -->
          <section id="microsurgical-clipping" class="pillar-section">
            <h2 class="pillar-section-title">Microsurgical Clipping: When Surgery Is the Better Choice</h2>
            <p>Despite the widespread adoption of endovascular techniques, microsurgical clipping remains an essential treatment for a significant proportion of brain aneurysms — and in experienced hands, it offers a level of durability and completeness that endovascular treatment has not yet matched in all aneurysm types.</p>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">When Clipping Is Preferred</h3>
            <ul>
              <li><strong>Middle cerebral artery (MCA) aneurysms</strong> — the MCA's complex branch anatomy makes endovascular treatment more challenging; direct surgical access provides excellent visualisation and clip placement</li>
              <li><strong>Aneurysms with a broad base or complex shape</strong> — where complete endovascular occlusion is difficult to achieve reliably</li>
              <li><strong>Giant aneurysms</strong> — particularly those causing mass effect; surgical decompression and clip reconstruction may be required</li>
              <li><strong>Failed or recanalised endovascular treatment</strong> — clipping provides a definitive solution when coiling has been incomplete</li>
              <li><strong>Young patients</strong> — the long-term durability of clipping is particularly valuable in patients who would otherwise face decades of angiographic surveillance after coiling</li>
              <li><strong>Aneurysms with associated haematoma</strong> — where the haematoma requires surgical evacuation in any case</li>
            </ul>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">The Clipping Procedure</h3>
            <p>Under general anaesthesia, a craniotomy is performed — typically a pterional (frontotemporal) craniotomy for anterior circulation aneurysms, or a retrosigmoid / suboccipital craniotomy for posterior fossa aneurysms. The Sylvian fissure is opened under the operating microscope, the aneurysm-bearing vessel is exposed, and the aneurysm neck is identified. A titanium clip is then placed across the aneurysm neck under direct microscopic visualisation, permanently excluding the aneurysm from the circulation while preserving blood flow in the parent and branch vessels.</p>
            <p>Intraoperative fluorescence angiography (indocyanine green, ICG) is performed after clip placement to confirm complete aneurysm occlusion and patency of all adjacent vessels — providing immediate confirmation of the surgical result without the need for a separate post-operative angiogram.</p>
          </section>

