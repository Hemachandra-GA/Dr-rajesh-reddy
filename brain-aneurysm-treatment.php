          <section id="symptoms" class="pillar-section">
            <h2 class="pillar-section-title">Brain Aneurysm Symptoms: Unruptured vs. Ruptured</h2>
            <div style="margin: 20px 0 24px; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 16px rgba(0,0,0,0.08); display: flex; justify-content: center;">
              <img src="images/expert-care-for-brain-aneurysms/recognizing_the_sign_of_brain_aneurysm.webp" alt="Recognizing the Signs of Brain Aneurysm" style="max-width: 100%; height: auto; display: block;">
            </div>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">Unruptured Brain Aneurysms: The Silent Majority</h3>
            <p>The majority of unruptured brain aneurysms produce no symptoms and are discovered incidentally — on an MRI or CT scan performed for an unrelated reason such as headache investigation, a head injury, or routine screening in a patient with a family history. This incidental discovery, while initially alarming, is actually the best possible scenario — it allows a measured, unhurried evaluation of the aneurysm's risk and an informed treatment decision.</p>
            <p>However, some large unruptured aneurysms — particularly those compressing adjacent structures — can produce symptoms:</p>
            <ul>
              <li><strong>Posterior communicating artery aneurysm pressing on the third cranial nerve</strong> &rarr; sudden onset drooping eyelid (ptosis) and double vision — a neurosurgical emergency requiring immediate evaluation</li>
              <li><strong>Large internal carotid artery aneurysm</strong> &rarr; visual field loss from optic nerve or chiasm compression</li>
              <li><strong>Giant aneurysms</strong> &rarr; headache, focal neurological deficits from mass effect on adjacent brain</li>
              <li><strong>Cavernous sinus aneurysm</strong> &rarr; facial numbness, double vision, or eye movement problems</li>
            </ul>

            <div style="background-color: #fff8e6; border-left: 4px solid #f5a623; padding: 16px; margin-top: 24px; margin-bottom: 24px; border-radius: 4px;">
              <p style="margin-bottom: 0; font-size: 0.95rem; color: #333;"><strong>Warning Sign:</strong> A sudden, painful drooping of one eyelid with double vision — even without headache — should prompt immediate neurovascular evaluation. This combination of signs is classic for a posterior communicating artery aneurysm compressing the third cranial nerve and may precede rupture by hours to days.</p>
            </div>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">Ruptured Brain Aneurysm: The Thunderclap Headache</h3>
            <p>When a brain aneurysm ruptures, it causes subarachnoid haemorrhage (SAH) — sudden bleeding into the subarachnoid space around the brain. The hallmark symptom is a thunderclap headache: a sudden, explosive headache of maximal severity at onset, often described as 'the worst headache of my life' or 'like a thunderbolt to the head.'</p>
            <p>Other symptoms of ruptured aneurysm (SAH) include:</p>
            <ul>
              <li><strong>Sudden onset neck stiffness (meningism)</strong> — from blood irritating the meninges</li>
              <li><strong>Photophobia</strong> — severe sensitivity to light</li>
              <li><strong>Nausea and vomiting</strong> — often projectile</li>
              <li><strong>Loss of consciousness</strong> — occurs in approximately 50% of patients at ictus</li>
              <li><strong>Focal neurological deficits</strong> — depending on the aneurysm location and extent of bleeding</li>
              <li><strong>Seizures</strong> — occur in approximately 10% of SAH patients</li>
              <li><strong>Coma</strong> — in severe cases (WFNS Grade IV–V)</li>
            </ul>

            <div style="background-color: #fce8e6; border-left: 4px solid #d93025; padding: 16px; margin-top: 24px; margin-bottom: 24px; border-radius: 4px;">
              <p style="margin-bottom: 0; font-size: 0.95rem; color: #a50e0e;"><strong>EMERGENCY:</strong> A sudden, severe headache of maximal intensity at onset — the 'thunderclap headache' — requires immediate emergency department attendance and urgent CT brain scan. Do not wait to see if it improves. Up to 50% of SAH patients describe a 'sentinel headache' in the days before major rupture — a warning sign that is too often dismissed. Every thunderclap headache must be treated as a ruptured aneurysm until proven otherwise.</p>
            </div>
          </section>

          <!-- Diagnosing a Brain Aneurysm: The Workup -->
          <section id="diagnosis" class="pillar-section">
            <h2 class="pillar-section-title">Diagnosing a Brain Aneurysm: The Workup</h2>
            <div style="margin: 20px 0 24px; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 16px rgba(0,0,0,0.08); display: flex; justify-content: center;">
              <img src="images/expert-care-for-brain-aneurysms/adv_img_for_accurate_diagnosis.webp" alt="Advanced Imaging for Accurate Aneurysm Diagnosis" style="max-width: 100%; height: auto; display: block;">
            </div>

            <h3 style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">CT Brain (Non-Contrast) — The Emergency Investigation</h3>
            <p>In a patient presenting with thunderclap headache, a non-contrast CT brain scan is the first-line investigation. It detects subarachnoid blood in approximately 98% of SAH cases within 6 hours of symptom onset. The sensitivity decreases after 24 hours as blood is reabsorbed — which is why immediate investigation is essential.</p>

            <h3 style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">CT Angiography (CTA)</h3>
            <p>If the CT brain confirms SAH — or if the clinical suspicion of unruptured aneurysm is high — CT angiography is performed immediately. CTA provides a rapid, non-invasive three-dimensional roadmap of the cerebral vasculature, identifying the aneurysm's location, size, shape, neck morphology, and relationship to surrounding vessels. Modern CTA has a sensitivity approaching 97–99% for aneurysms &ge; 3mm.</p>

            <h3 style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">Lumbar Puncture (LP)</h3>
            <p>If the CT brain is normal but clinical suspicion of SAH remains high — particularly if the patient presents more than 6 hours after symptom onset — a lumbar puncture is performed to analyse the cerebrospinal fluid (CSF) for xanthochromia (yellow discolouration from haemoglobin breakdown products). A positive LP in the context of thunderclap headache confirms SAH even when CT is negative.</p>

            <h3 style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">Digital Subtraction Angiography (DSA) — The Gold Standard</h3>
            <p>Digital subtraction angiography — conventional catheter angiography — remains the gold standard for definitive aneurysm characterisation. A catheter is introduced through the femoral artery and advanced under X-ray guidance to selectively inject contrast into each cerebral vessel. DSA provides the highest resolution imaging of aneurysm anatomy — including the neck width, dome-to-neck ratio, relationship to branch vessels, and aneurysm haemodynamics — which is essential for precise treatment planning.</p>
            <p>In the setting of confirmed SAH, DSA is performed as a combined diagnostic and therapeutic procedure: the aneurysm is characterised and — when anatomy is suitable — treated with coiling or other endovascular devices in the same sitting.</p>

            <h3 style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">MRI Brain and MR Angiography (MRA)</h3>
