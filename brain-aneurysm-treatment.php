                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  What is the difference between coiling and clipping — and how do I know which one I need?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Both coiling and clipping aim to permanently exclude the aneurysm from the circulation — they differ in approach. Coiling is endovascular (through the groin, no craniotomy) and is preferred for most ruptured aneurysms and for posterior circulation aneurysms. Clipping requires a craniotomy but provides immediate, durable occlusion and is preferred for MCA aneurysms and cases where coiling cannot achieve complete occlusion. The decision is made by Dr. Rajesh Reddy based on your specific aneurysm anatomy, location, and the most likely treatment to achieve a complete, durable result. Many patients are suitable for both approaches — the team's combined expertise ensures you receive the best option, not just the most available one.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  How dangerous is a brain aneurysm that has not ruptured?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    The annual rupture risk for an unruptured brain aneurysm depends primarily on its size and location. Small aneurysms (&lt; 7mm) in low-risk locations carry an annual rupture risk of approximately 0.1–0.5% per year. Larger aneurysms, posterior circulation aneurysms, and those in patients who have previously had a SAH from another aneurysm carry substantially higher risk. The overall lifetime risk of rupture depends on the patient's age — a small aneurysm in a 35-year-old represents a meaningfully different lifetime risk than the same aneurysm in a 75-year-old. Dr. Rajesh Reddy will calculate your specific risk and present treatment options with full transparency.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  What is a 'sentinel headache' and should I be concerned about it?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    A sentinel headache is a sudden, severe headache — often described as 'different' from any previous headache — that occurs in the days or weeks before a major aneurysm rupture. It is thought to represent a small 'warning leak' from the aneurysm, or a sudden change in aneurysm pressure. Approximately 20–50% of patients who suffer a major SAH report a sentinel headache in the preceding days that was not investigated. Any new, sudden, severe headache — even if it resolves — should be evaluated immediately with a CT brain and neurovascular assessment if no clear benign cause is identified.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  Can I fly after brain aneurysm treatment?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    After elective endovascular treatment of an unruptured aneurysm, most patients can fly from 2–4 weeks after the procedure, once any groin access site is fully healed and the neurological status is stable. After SAH and aneurysm treatment, flying is typically deferred for 3–6 months due to the risk of complications (chronic hydrocephalus, seizures, cognitive impairment) that may require urgent intervention. Dr. Rajesh Reddy will provide specific guidance based on your recovery, the treatment performed, and any ongoing medications.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  My parent had a brain aneurysm — should I be screened?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Yes — family history is a significant risk factor for intracranial aneurysms. First-degree relatives of a patient with a proven intracranial aneurysm have approximately 3–7 times the population risk. Screening is recommended for individuals with two or more first-degree relatives affected, or for individuals with a family history combined with other risk factors (hypertension, smoking, polycystic kidney disease). Screening is performed with MR angiography (MRA) — a non-invasive, radiation-free examination that can reliably detect aneurysms &ge; 3mm. Dr. Rajesh Reddy will advise on appropriate family screening if you or a family member has been diagnosed.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  What is a cerebral AVM and how is it related to aneurysm?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    An arteriovenous malformation (AVM) is a tangle of abnormal blood vessels connecting arteries directly to veins, bypassing the normal capillary bed. AVMs can bleed, causing haemorrhagic stroke, and may be associated with flow-related aneurysms on the feeding arteries. Unlike aneurysms, AVMs are typically congenital. Treatment options include endovascular embolisation, microsurgery, and stereotactic radiosurgery — often used in combination. Dr. Rajesh Reddy's combined endovascular and microsurgical expertise makes him uniquely suited to manage complex AVMs, including those with associated aneurysms.
                  </div>
                </div>
              </div>

