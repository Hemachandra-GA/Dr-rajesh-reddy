          <section id="unruptured-management" class="pillar-section">
            <h2 class="pillar-section-title">Managing Unruptured Brain Aneurysms: Treatment vs. Observation</h2>
            <p>The discovery of an unruptured brain aneurysm inevitably raises the question: does it need to be treated? The answer requires balancing the risk of aneurysm rupture (without treatment) against the risk of the treatment itself.</p>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">Annual Rupture Risk: Size and Location Matter</h3>
            <p>The annual risk of rupture for an unruptured intracranial aneurysm varies significantly by size and location. The PHASES score — incorporating Population (country), Hypertension, Age, Size, Earlier SAH, and Site (location) — is used to calculate an individualised annual rupture risk. As a general guide:</p>
            <ul>
              <li><strong>Aneurysms &lt; 7mm in low-risk locations:</strong> annual rupture risk approximately 0.1–0.5%</li>
              <li><strong>Aneurysms 7–12mm:</strong> annual rupture risk approximately 0.5–1.5%</li>
              <li><strong>Aneurysms &gt; 12mm:</strong> annual rupture risk &gt; 1.5–3% per year</li>
              <li><strong>Posterior circulation (basilar tip, posterior communicating artery) aneurysms:</strong> significantly higher rupture risk at any size</li>
              <li><strong>Prior SAH from another aneurysm:</strong> higher rupture risk for remaining unruptured aneurysms</li>
            </ul>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">Treatment Risk: Procedural Morbidity and Mortality</h3>
            <p>In experienced hands, the procedural morbidity and mortality for both endovascular and surgical treatment of unruptured aneurysms is low — approximately 1–3% for major morbidity and &lt; 1% mortality for elective procedures in good-grade patients. However, this risk increases with patient age, medical comorbidities, aneurysm size, and complexity.</p>
            <p>Dr. Rajesh Reddy uses the PHASES score and UIATS (Unruptured Intracranial Aneurysm Treatment Score) in combination with his clinical assessment to provide patients with an individualised, evidence-based recommendation on whether treatment or observation is more appropriate for their specific aneurysm.</p>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">When Observation Is Appropriate</h3>
            <ul>
              <li>Small aneurysms (&lt; 5–7mm) in low-risk locations in elderly patients or those with significant medical comorbidities</li>
              <li>Patient preference after thorough counselling on rupture and treatment risk</li>
              <li>Aneurysms showing stability on serial imaging over 2+ years</li>
            </ul>

            <h3 style="font-size: 1.3rem; font-weight: 700; color: #1d1d1f; margin-top: 1.5rem; margin-bottom: 0.75rem;">Risk Factor Modification — Essential in All Cases</h3>
            <p>Regardless of whether treatment or observation is chosen, all patients with a known brain aneurysm should:</p>
            <ul>
              <li><strong>Control blood pressure rigorously</strong> — target &lt; 130/80 mmHg</li>
              <li><strong>Stop smoking</strong> — smoking substantially increases aneurysm growth and rupture risk</li>
              <li><strong>Avoid cocaine and stimulant drugs</strong> — associated with acute aneurysm rupture</li>
              <li><strong>Moderate caffeine and alcohol intake</strong></li>
              <li><strong>Attend all surveillance imaging appointments without delay</strong></li>
              <li><strong>Avoid straining and manage constipation actively</strong> — sudden rises in intracranial pressure from straining can trigger aneurysm rupture; stool softeners should be used routinely in all aneurysm patients</li>
            </ul>
