          <section id="headaches" class="pillar-section">
            <h2 class="pillar-section-title">Brain Tumor Headaches: How to Tell Them Apart</h2>
            <p>Headache is the symptom most people associate with brain tumors — and one of the most frequently Googled. The reality is nuanced: headache is a symptom in only about 50% of brain tumor patients at diagnosis, and most headaches are not caused by brain tumors. However, certain headache characteristics are genuine red flags that warrant investigation.</p>

            <h3>Characteristics of a Brain Tumor Headache</h3>
            <ul>
              <li><strong>Progressive</strong> — worsening in frequency and intensity over days to weeks, rather than following the episodic pattern of migraine or tension headache</li>
              <li><strong>Morning predominance</strong> — often worst on waking, because lying flat overnight allows ICP to rise</li>
              <li><strong>Position-dependent</strong> — worsens when bending forward, coughing, sneezing, or straining (Valsalva manoeuvre)</li>
              <li><strong>Associated with nausea or vomiting</strong> — particularly in the morning</li>
              <li><strong>Accompanied by neurological symptoms</strong> — weakness, vision changes, speech difficulty, or seizures alongside the headache</li>
              <li><strong>Not relieved by standard painkillers</strong> — over-the-counter analgesics provide partial or no relief</li>
              <li><strong>New in onset</strong> — a headache pattern that is genuinely new for the patient, particularly in middle age or older adulthood</li>
            </ul>

