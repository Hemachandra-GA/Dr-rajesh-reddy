          <section id="seizures" class="pillar-section">
            <h2 class="pillar-section-title">Seizures: A Key Red Flag</h2>
            <p>New-onset seizures in an adult who has no previous history of epilepsy are one of the most important red flags for an underlying brain tumor. Seizures occur when a tumor irritates the surrounding brain tissue, creating abnormal electrical activity that spreads through the cortex.</p>

            <h3>Types of Seizures in Brain Tumor Patients</h3>
            <p><strong>Focal (partial) seizures:</strong> Affect a specific part of the body corresponding to the tumor's location — for example, rhythmic twitching of one hand (frontal lobe), a rising sensation in the abdomen or déjà vu (temporal lobe), or visual flashes (occipital lobe). The patient may remain conscious.</p>
            <p><strong>Focal seizures with secondary generalisation:</strong> Begin as a focal seizure but spread to involve the whole brain, producing a generalised tonic-clonic (convulsive) seizure with loss of consciousness.</p>
            <p><strong>Generalised seizures:</strong> Involve the whole brain from the outset — less common as a first presentation of brain tumor than focal seizures.</p>

            <h3>What to Do After a First Seizure</h3>
            <p>Any first seizure in an adult — even a mild one — requires urgent medical evaluation. The standard workup includes blood tests, an EEG, and crucially, an MRI of the brain with contrast. Do not wait to see if 'it happens again.' A single unexplained seizure in a previously healthy adult is sufficient reason for neuroimaging.</p>
            <p>Low-grade gliomas in particular often present with seizures as their only symptom for months or years before the tumor is discovered. Early detection through post-seizure MRI gives patients the widest range of treatment options.</p>
          </section>

          <!-- Cognitive & Personality Shifts Section -->
          <section id="cognitive-changes" class="pillar-section">
            <h2 class="pillar-section-title">Cognitive Changes and Personality Shifts</h2>
            <p>Changes in thinking, memory, and personality are among the most distressing — and most frequently overlooked — symptoms of brain tumors. They are often attributed to stress, depression, ageing, or burnout before a neurological cause is considered. Family members frequently notice these changes before the patient does.</p>

            <h3>Cognitive Symptoms to Watch For</h3>
            <ul>
              <li><strong>Memory problems</strong> — difficulty forming new memories, forgetting recent conversations or appointments</li>
              <li><strong>Concentration difficulties</strong> — inability to focus, losing track mid-sentence or mid-task</li>
              <li><strong>Word-finding problems</strong> — struggling to retrieve words during speech, even familiar ones</li>
              <li><strong>Slowed thinking</strong> — processing information more slowly than usual, taking longer to respond</li>
              <li><strong>Disorientation</strong> — confusion about time, place, or recent events</li>
            </ul>

            <h3>Personality and Behavioural Changes</h3>
            <ul>
              <li><strong>Apathy and loss of motivation</strong> — previously engaged individuals becoming withdrawn and disinterested</li>
              <li><strong>Disinhibition</strong> — saying or doing things that are socially inappropriate without apparent awareness</li>
              <li><strong>Increased irritability or aggression</strong> — low frustration tolerance, uncharacteristic outbursts</li>
              <li><strong>Depression or anxiety</strong> — new-onset mood disturbances without a clear psychological trigger</li>
              <li><strong>Impaired judgement</strong> — making poor decisions, difficulty assessing risk</li>
            </ul>
            <p>These symptoms are particularly associated with tumors of the frontal lobe — the brain's centre of executive function, personality regulation, and social behaviour. Frontal lobe tumors can grow to a significant size before causing the headaches and neurological deficits that typically prompt a scan, making cognitive and personality changes the earliest and sometimes only warning signs.</p>
          </section>

          <!-- Vision Changes Section -->
          <section id="vision-changes" class="pillar-section">
            <h2 class="pillar-section-title">Vision Changes and Brain Tumors</h2>
            <p>The brain devotes a substantial portion of its territory to visual processing, and the visual pathway runs from the retina all the way to the occipital lobe at the back of the skull. Tumors anywhere along this pathway can cause visual symptoms.</p>

            <h3>Types of Visual Disturbance</h3>
            <p><strong>Bitemporal hemianopia:</strong> Loss of the outer (temporal) half of the visual field in both eyes. This is the classic sign of a pituitary tumor pressing on the optic chiasm — the point where the optic nerves cross. Patients often describe it as difficulty seeing objects to the side, or walking into door frames.</p>
            <p><strong>Homonymous hemianopia:</strong> Loss of the same half of the visual field in both eyes — for example, loss of the right visual field in both the right and left eye. This results from tumors affecting the optic radiation or occipital lobe.</p>
            <p><strong>Vision loss in one eye:</strong> Can occur when a tumor — such as a Meningioma — directly compresses one optic nerve or compromises its blood supply, depriving it of nutrition. This may present as progressive blurring or complete loss of vision in that eye and should be investigated urgently.</p>
            <p><strong>Diplopia (double vision):</strong> Two images of a single object. Common with brainstem tumors or tumors affecting the cranial nerves that control eye movement (CN III, IV, VI).</p>
            <p><strong>Papilloedema:</strong> Not a visual symptom the patient necessarily notices, but a sign the doctor sees on examining the back of the eye — swelling of the optic disc caused by raised intracranial pressure. When severe, it can cause visual obscurations (momentary greying out of vision) and eventually permanent visual loss if ICP is not relieved.</p>
            <p><strong>Visual hallucinations:</strong> Seeing shapes, colours, or images that are not present — associated with occipital lobe tumors.</p>
          </section>

          <!-- Weakness & Speech Problems Section -->
          <section id="neurological-deficits" class="pillar-section">
            <h2 class="pillar-section-title">Weakness, Numbness, and Speech Problems</h2>
            <p>Focal neurological deficits — weakness, sensory loss, or speech difficulty — are among the most diagnostically useful symptoms of brain tumors because they point directly to the tumor's location.</p>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/Brain Tumor Symptoms/Brain_Tumor_Location_Symptoms_progress.webp" alt="Location Symptoms Progress Map" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>Motor Weakness</h3>
            <p>Progressive weakness on one side of the body — hemiparesis — develops when a tumor involves the motor cortex (located in the posterior frontal lobe) or the motor pathways running through the internal capsule. The weakness typically affects the arm and leg on the opposite side to the tumor (contralateral weakness), because the motor pathway crosses before descending to the spinal cord.</p>
            <p>Patients describe it as clumsiness, dropping objects, difficulty climbing stairs, or dragging one foot. It is gradual and progressive — unlike the sudden onset of stroke — though tumors that bleed (haemorrhage into a tumor) can cause sudden onset deficits that mimic stroke.</p>

            <h3>Speech and Language Difficulties</h3>
            <p>Speech problems from brain tumors take two distinct forms, depending on which language area is affected:</p>
            <ul>
              <li><strong>Broca's aphasia (expressive aphasia):</strong> The patient understands what is being said but has difficulty forming words or sentences. Speech is laboured, telegraphic, and frustrating. Associated with tumors in Broca's area in the inferior frontal gyrus of the dominant hemisphere.</li>
              <li><strong>Wernicke's aphasia (receptive aphasia):</strong> The patient speaks fluently but the words are jumbled or nonsensical, and they have difficulty understanding speech. Associated with tumors in Wernicke's area in the posterior temporal lobe.</li>
            </ul>
            <p>Language difficulties are among the most distressing symptoms for patients and families. They are also among the most important to identify before surgery — because planning an awake craniotomy requires knowing exactly which language areas are at risk, so they can be mapped and protected during tumor resection.</p>

            <h3>Sensory Symptoms</h3>
            <p>Numbness, tingling, or altered sensation on one side of the body — contralateral to the tumor — indicate involvement of the sensory cortex in the parietal lobe or the sensory pathways. Some patients describe a feeling that one hand or foot 'doesn't belong to them' or that sensations feel different on the two sides of the body.</p>
          </section>

          <!-- Cranial Nerve Dysfunction Section -->
          <section id="cranial-nerves" class="pillar-section">
            <h2 class="pillar-section-title">Cranial Nerve Dysfunction: An Overlooked Group of Symptoms</h2>
            <p>Brain tumors — particularly those at the skull base, in the posterior fossa, or along the brainstem — can affect the cranial nerves, which control many essential functions of the head, face, and throat. Cranial nerve dysfunction produces a specific and recognisable set of symptoms that patients and families should be aware of:</p>
            <ul>
              <li><strong>Drooping of one eyelid (ptosis)</strong> — caused by compression or involvement of the third cranial nerve (CN III); may also be accompanied by a dilated, unreactive pupil on the same side</li>
              <li><strong>Double vision (diplopia)</strong> — from involvement of CN III, IV, or VI, which control eye movement; the patient sees two images of a single object</li>
              <li><strong>Facial asymmetry or weakness</strong> — caused by facial nerve (CN VII) involvement; one side of the face droops, the patient cannot close one eye fully, and the smile appears uneven</li>
              <li><strong>Numbness over the face</strong> — caused by trigeminal nerve (CN V) compression; may feel like a dental anaesthesia that does not wear off, or persistent tingling across one cheek, jaw, or forehead</li>
              <li><strong>Loss of hearing or tinnitus</strong> — from involvement of the vestibulocochlear nerve (CN VIII); a classic presentation of vestibular schwannoma (acoustic neuroma)</li>
              <li><strong>Swallowing difficulty (dysphagia)</strong> — from glossopharyngeal (CN IX) or vagus nerve (CN X) involvement; patients may cough or choke on food or liquids</li>
              <li><strong>Nasal regurgitation of feeds</strong> — food or liquid returning through the nose during or after swallowing, indicating soft palate weakness from CN IX or X dysfunction</li>
              <li><strong>Change in voice quality</strong> — hoarseness or a nasal quality to the voice, caused by vagus nerve (CN X) involvement affecting the vocal cords or soft palate</li>
              <li><strong>Tongue weakness</strong> — causing difficulty with chewing, forming words clearly, or moving food within the mouth; caused by hypoglossal nerve (CN XII) involvement; patients may inadvertently bite the tongue due to impaired tongue muscle control</li>
              <li><strong>Shoulder drooping or weakness in raising the arm</strong> — from accessory nerve (CN XI) involvement; patients cannot shrug one shoulder or turn their head against resistance</li>
            </ul>
            <p>These cranial nerve symptoms are particularly associated with skull base tumors (meningiomas, schwannomas, chordomas, craniopharyngiomas), posterior fossa tumors, and brainstem gliomas. Their presence should prompt urgent neurological evaluation and dedicated MRI of the brain and skull base.</p>
          </section>

          <!-- Hormonal Symptoms Section -->
          <section id="hormonal-symptoms" class="pillar-section">
            <h2 class="pillar-section-title">Hormonal Symptoms: Pituitary Tumor Presentation</h2>
            <p>Pituitary tumors deserve special mention because their symptoms are often hormonal rather than neurological — leading patients to consult gynaecologists, endocrinologists, or general physicians before a neurosurgeon is ever involved.</p>
            <ul>
              <li><strong>Prolactinoma:</strong> irregular or absent periods, milk discharge from the breasts (galactorrhoea), infertility in women; reduced libido, erectile dysfunction, and infertility in men</li>
              <li><strong>Cushing's disease (ACTH-secreting):</strong> weight gain concentrated around the abdomen and face (moon face), purple stretch marks (striae), easy bruising, high blood pressure, diabetes, and mood disturbances</li>
              <li><strong>Acromegaly (GH-secreting):</strong> gradual enlargement of the hands, feet, and jaw; coarsening of facial features; excessive sweating; joint pain; carpal tunnel syndrome</li>
              <li><strong>Non-functioning macroadenoma:</strong> bitemporal visual field loss, headache behind the eyes, fatigue from pituitary insufficiency</li>
            </ul>
            <p>Pituitary tumors can be present for years before diagnosis. If you have been treated for infertility, irregular periods, or unexplained hormonal abnormalities without a clear cause, ask your doctor whether a pituitary MRI has been performed.</p>
          </section>

          <!-- Emergency Symptoms Section -->
          <section id="emergency-symptoms" class="pillar-section">
            <h2 class="pillar-section-title">Emergency Symptoms: When to Go to Hospital Immediately</h2>
            <p>Most brain tumor symptoms develop gradually over weeks to months. However, certain situations demand immediate emergency care — they indicate either a rapidly expanding tumor, hemorrhage into a tumor, or acute hydrocephalus.</p>

            <div class="pillar-callout" style="border-left-color: #d9383a; background-color: #fdf2f2;">
              <h4 style="color: #d9383a;"><i class="fa-solid fa-triangle-exclamation" style="margin-right: 8px;"></i>SEEK EMERGENCY CARE IMMEDIATELY IF YOU EXPERIENCE:</h4>
              <ul style="margin-bottom: 0; color: #1d1d1f;">
                <li>A sudden, severe headache described as <strong>'the worst headache of my life'</strong></li>
                <li>Sudden loss of speech, vision, or ability to move one side of the body</li>
                <li>A first seizure or a prolonged seizure</li>
                <li>Sudden loss of consciousness or unresponsiveness</li>
                <li>Sudden extreme confusion or agitation</li>
              </ul>
            </div>

            <p style="margin-top: 20px;">Hemorrhage into a brain tumor — where the tumor's abnormal blood vessels rupture — can cause sudden, stroke-like symptoms. This is a neurosurgical emergency. Similarly, a colloid cyst or ventricular tumor that suddenly blocks CSF circulation can cause acute hydrocephalus with rapid deterioration. Both require immediate CT imaging and neurosurgical assessment.</p>
          </section>

          <!-- When Should You See a Neurosurgeon Section -->
          <section id="when-to-see-doctor" class="pillar-section">
            <h2 class="pillar-section-title">When Should You See a Neurosurgeon?</h2>
            <p>You should seek a neurosurgical consultation — which will typically begin with an MRI of the brain — if you experience any of the following:</p>

            <ul>
              <li>New-onset seizures at any age with no prior epilepsy history</li>
              <li>A headache pattern that is genuinely new, progressively worsening, or worst in the morning</li>
              <li>Any focal neurological symptom: progressive weakness, numbness, vision change, or speech difficulty</li>
              <li>Unexplained personality or cognitive changes noticed by yourself or family members</li>
              <li>Hormonal symptoms suggesting a pituitary tumor (menstrual irregularity, visual field loss, acromegaly features)</li>
              <li>Cranial nerve symptoms: drooping eyelid, facial numbness, hearing loss, swallowing difficulty, change in voice</li>
              <li>An incidental finding on MRI — a lesion found when imaging was done for another reason</li>
              <li>A previously diagnosed benign lesion showing change on follow-up imaging</li>
            </ul>

