          <!-- FAQ Section -->
          <section id="faq" class="pillar-section">
            <h2 class="pillar-section-title">Frequently Asked Questions</h2>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q1: Can a brain tumor be present with no symptoms at all?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Yes. A significant proportion of brain tumors — particularly slow-growing benign tumors such as meningiomas and low-grade gliomas — are discovered incidentally on an MRI or CT scan done for an entirely unrelated reason, such as after a minor head injury or for investigation of a sinus problem. These tumors may have been present for years without causing any symptoms. Incidentally discovered tumors still require neurological evaluation to determine whether monitoring or treatment is appropriate.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q2: Is a brain tumor headache different from a normal headache?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Brain tumor headaches tend to be progressive (worsening over time), worst in the morning, worsened by lying flat or straining, and often accompanied by nausea or neurological symptoms. They typically do not follow the episodic pattern of migraines and are not relieved by standard painkillers. However, no headache characteristic alone can diagnose or rule out a brain tumor — which is why any new, unexplained, or changing headache pattern warrants a medical evaluation.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q3: My parent has been more forgetful and irritable recently — could this be a brain tumor?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Personality change, increased irritability, and memory problems can be symptoms of a frontal or temporal lobe brain tumor — but they are also common features of many other conditions, including depression, thyroid disorders, vitamin deficiencies, and dementia. A medical evaluation is warranted if these changes are new, progressive, and unexplained by any other cause. An MRI of the brain is a simple and definitive way to rule out an intracranial cause.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q4: Can brain tumor symptoms come and go?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Some brain tumor symptoms can fluctuate — particularly seizures, which occur as intermittent episodes, and some visual or sensory symptoms. However, the underlying trend for most brain tumor symptoms is progressive worsening over time, not fluctuation and resolution. It is also worth noting that steroids (corticosteroids such as dexamethasone), when prescribed, can temporarily reduce the swelling (oedema) around a tumor and temporarily improve symptoms such as headache, weakness, and speech disturbances — giving a misleading impression that the condition is improving. This temporary steroid response should not be mistaken for recovery or a sign that treatment is no longer needed. If symptoms are coming and going but the overall trajectory is one of increasing frequency or severity, this is a significant red flag that warrants urgent evaluation.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q5: Do children present with different brain tumor symptoms than adults?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  Yes. Children with brain tumors — particularly posterior fossa tumors like medulloblastoma and pilocytic astrocytoma — often present with symptoms of hydrocephalus: morning headaches, repeated vomiting, unsteady gait, and declining school performance. Parents may notice that a child is increasingly unsteady on their feet or has developed an unusual head tilt. Pituitary tumors in children may present with growth failure or delayed puberty. Any child with unexplained progressive neurological symptoms, persistent vomiting without a GI cause, or declining coordination should be assessed by a neurologist or neurosurgeon.
                </div>
              </div>
            </div>

            <div class="pillar-faq-item">
              <div class="pillar-faq-q">
                <span>Q6: How quickly should I act if I think my symptoms might be due to a brain tumor?</span>
                <i class="fa-solid fa-chevron-down"></i>
              </div>
              <div class="pillar-faq-a">
                <div class="pillar-faq-a-content">
                  For emergency symptoms — sudden severe headache, sudden weakness or speech loss, first seizure, loss of consciousness — seek emergency care immediately. For progressive symptoms — worsening headaches, gradual weakness, cognitive changes, new seizures — schedule a consultation with a neurosurgeon within days, not weeks. An MRI of the brain can be arranged promptly and provides definitive imaging to either diagnose or exclude an intracranial lesion. Delay in evaluation does not make symptoms better — and for treatable tumors, earlier diagnosis consistently leads to better outcomes.
                </div>
              </div>
            </div>
