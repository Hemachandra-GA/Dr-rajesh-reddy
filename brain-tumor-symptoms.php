          <section id="mechanisms" class="pillar-section">
            <h2 class="pillar-section-title">Why Does a Brain Tumor Cause Symptoms?</h2>
            <p>Brain tumor symptoms arise through two distinct mechanisms. Understanding these mechanisms helps explain why the same tumor type can cause very different symptoms in different patients — and why some tumors cause severe symptoms while others are discovered incidentally with no symptoms at all.</p>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/Brain Tumor Symptoms/Common_Brain_Tumor_Symptoms.webp" alt="Common Brain Tumor Symptoms Overview" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>Mechanism 1: Raised Intracranial Pressure (ICP)</h3>
            <p>The skull is a rigid, closed box. The brain, blood, and cerebrospinal fluid (CSF) inside it exist in a precise pressure equilibrium. When a tumor grows, it adds volume to this fixed space. The brain initially compensates — compressing CSF spaces and venous blood — but once these compensatory mechanisms are exhausted, intracranial pressure rises.</p>
            <p>Raised ICP produces a characteristic set of symptoms regardless of where the tumor is located:</p>
            <ul>
              <li><strong>Headache</strong> — typically progressive, worse in the morning or when lying flat</li>
              <li><strong>Nausea and vomiting</strong> — particularly on waking or with sudden changes in head position</li>
              <li><strong>Visual disturbances</strong> — blurring of vision, or episodes of graying-out of vision (visual obscurations)</li>
              <li><strong>Papilloedema</strong> — swelling of the optic disc visible on fundoscopy, caused by pressure transmitted along the optic nerve sheath</li>
              <li><strong>Altered consciousness</strong> — drowsiness, confusion, or reduced responsiveness in severe cases</li>
            </ul>

            <h3>Mechanism 2: Focal (Location-Specific) Effects</h3>
            <p>Every region of the brain has specific functions. A tumor growing in or adjacent to a functional area disrupts those functions directly — either by invading the tissue, compressing it, or irritating it. This produces focal neurological symptoms that point specifically to the tumor's location in the brain. A motor cortex tumor causes weakness; a visual cortex tumor causes vision loss; a language area tumor causes speech difficulty.</p>
            <p>The interplay between these two mechanisms — raised ICP producing general symptoms and focal effects producing location-specific symptoms — is what makes brain tumor presentations so variable from patient to patient.</p>
          </section>

