          <section id="medulloblastoma" class="pillar-section">
            <h2 class="pillar-section-title">Medulloblastoma</h2>
            <p>Medulloblastoma is the most common malignant brain tumor in children, arising from the cerebellum. It grows rapidly and has a tendency to spread through the cerebrospinal fluid (CSF) to other parts of the brain and spinal cord (leptomeningeal spread), which is why staging with full spine MRI and CSF analysis is essential at the time of diagnosis.</p>
            <p>Treatment involves maximum safe surgical resection followed by craniospinal radiation (in children over 3 years) and chemotherapy. Molecular subtyping — including WNT, SHH, Group 3, and Group 4 subtypes — significantly influences prognosis and is increasingly guiding treatment intensity. WNT-activated medulloblastoma has an excellent prognosis; Group 3 medulloblastoma carries the worst.</p>
          </section>

          <!-- Colloid Cysts Section -->
          <section id="colloid-cysts" class="pillar-section">
            <h2 class="pillar-section-title">Colloid Cysts</h2>
            <p>Colloid cysts are benign, fluid-filled cysts that arise within the third ventricle of the brain — a small cavity through which cerebrospinal fluid flows. Although benign, they can be life-threatening: if the cyst enlarges and blocks CSF flow, it causes acute hydrocephalus (build-up of fluid and pressure within the brain) which can be rapidly fatal without intervention.</p>
            <p>Symptoms include intermittent positional headaches (that worsen with certain head positions), nausea, and in severe cases, sudden loss of consciousness. Treatment is surgical removal — either via microscopic or endoscopic approach through the ventricle — which is curative in the majority of cases.</p>
          </section>

          <!-- Metastatic Brain Tumors Section -->
          <section id="metastatic" class="pillar-section">
            <h2 class="pillar-section-title">Metastatic Brain Tumors: When Cancer Spreads to the Brain</h2>
            <p>Metastatic brain tumors — cancers that have spread from elsewhere in the body — are the most common type of brain tumor overall, outnumbering primary brain tumors by approximately 10:1. The most common primary cancers that spread to the brain include:</p>
            <ul>
              <li><strong>Lung cancer</strong> — the most frequent source of brain metastases</li>
              <li><strong>Breast cancer</strong> — particularly HER2-positive and triple-negative subtypes</li>
              <li><strong>Renal cell carcinoma</strong> (kidney cancer)</li>
              <li><strong>Melanoma</strong> — known for its propensity to cause multiple brain metastases</li>
              <li><strong>Colorectal cancer</strong></li>
            </ul>
            <p>Patients may present with a single metastasis (solitary brain metastasis) or multiple lesions. Symptoms mirror those of primary brain tumors — headaches, seizures, weakness, and cognitive changes — but may develop in the context of a known cancer diagnosis or as the first presentation of an as-yet-undiagnosed primary cancer.</p>

            <h3>Treatment of Brain Metastases</h3>
            <p>Treatment is individualised based on the number and size of metastases, the status of the systemic cancer, and the patient's overall health. Options include:</p>
            <ul>
              <li><strong>Surgical resection</strong> — for large, symptomatic single metastases causing significant mass effect</li>
              <li><strong>Stereotactic radiosurgery (SRS)</strong> — highly effective for 1–4 small metastases; can treat multiple lesions in a single session</li>
              <li><strong>Whole-brain radiotherapy (WBRT)</strong> — for multiple metastases; increasingly being replaced by SRS to avoid cognitive side effects</li>
              <li><strong>Systemic therapy</strong> — targeted therapy and immunotherapy increasingly show efficacy in brain metastases from lung cancer and melanoma</li>
            </ul>

