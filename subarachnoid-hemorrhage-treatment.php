          <section id="diagnosis" class="pillar-section">
            <h2 class="pillar-section-title">Diagnosing SAH: The Emergency Workup</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/Subarachnoid_Hemorrhage/Diagnossis_Treatment.webp" alt="Diagnosing and Treating SAH" style="width: 100%; height: auto; display: block;">
            </div>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-bottom: 12px;">CT Brain (Non-Contrast) — First Line</h3>
            <p>
              Non-contrast CT brain is the first-line investigation for suspected SAH. It is approximately 98% sensitive within the first 6 hours of symptom onset — detecting subarachnoid blood as hyperdense (white) material in the basal cisterns, sylvian fissures, and cerebral sulci. Sensitivity decreases progressively after 24 hours as blood is diluted and reabsorbed by the CSF — emphasising why immediate investigation is critical.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Lumbar Puncture — When CT Is Negative</h3>
            <p>
              If CT brain is normal but clinical suspicion of SAH remains high — particularly in patients presenting more than 6 hours after headache onset — a lumbar puncture (LP) is performed. CSF is examined for xanthochromia (yellow discolouration from haemoglobin breakdown products) and crenated Red Blood Cells, which persists for up to 2 weeks after SAH even when CT has normalised. A positive LP in the context of a thunderclap headache confirms SAH and mandates further vascular imaging.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">CT Angiography (CTA) — Identifying the Aneurysm</h3>
            <p>
              Once SAH is confirmed, urgent CTA of the cerebral vessels is performed to identify the causative aneurysm, its location, size, and morphology. Modern multi-slice CTA has sensitivity approaching 97–99% for aneurysms &ge; 3mm and provides a rapid three-dimensional roadmap for treatment planning. In most centres, CTA has replaced diagnostic-only DSA as the first-line vascular investigation in acute SAH.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Digital Subtraction Angiography (DSA) — The Gold Standard and Treatment Platform</h3>
            <p>
              DSA remains the gold standard for definitive aneurysm characterisation and is the platform on which endovascular treatment is performed. In Dr. Rajesh Reddy's practice, DSA is performed as a combined diagnostic and therapeutic procedure: the aneurysm is fully characterised with 3D rotational angiography, and — when anatomy is suitable — treated with coiling or other endovascular devices in the same sitting, minimising the window of re-bleeding risk.
            </p>
          </section>

