            <h2 class="pillar-section-title">Introduction</h2>
            <p>
              Subarachnoid hemorrhage — SAH — is among the most devastating neurological emergencies in medicine. In the seconds after an aneurysm ruptures, blood surges under arterial pressure into the subarachnoid space around the brain, causing an instantaneous, catastrophic headache and triggering a cascade of complications that can claim a patient's life or neurological function over the days and weeks that follow — even after the aneurysm itself has been treated.
            </p>
            <p>
              For patients and families who encounter SAH — either as a sudden emergency or as a diagnosis on a scan — understanding what has happened, why it is so dangerous, and what treatment involves is essential for navigating the recovery ahead. This page provides a comprehensive, plain-language guide to SAH: what it is, why aneurysms rupture, how severity is assessed, what the emergency treatment involves, what complications to expect, and what recovery looks like.
            </p>
            <p>
              <strong>Dr. Rajesh Reddy Sannareddy</strong>, Senior Consultant Endovascular Neurosurgeon in Hyderabad, manages the complete spectrum of SAH care — from emergency aneurysm clipping / coiling in the acute phase through vasospasm intervention, hydrocephalus management, and long-term neurovascular follow-up. His Fellowship in Interventional Neuroradiology (FINR) from the University Hospital, Zurich and visiting scholar experience at Barrow Neurological Institute, Phoenix give him direct exposure to the highest-volume SAH management programmes in Europe and North America.
            </p>
          </section>

          <!-- What Is Subarachnoid Hemorrhage? -->
          <section id="what-is-sah" class="pillar-section">
            <h2 class="pillar-section-title">What Is Subarachnoid Hemorrhage?</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/Subarachnoid_Hemorrhage/what_happen_during_sah.webp" alt="What Happens During SAH" style="width: 100%; height: auto; display: block;">
            </div>
            <p>
              The brain is surrounded by three protective membranes — the dura, arachnoid, and pia mater — collectively called the meninges. Between the arachnoid and pia mater lies the subarachnoid space, a fluid-filled compartment through which cerebrospinal fluid (CSF) circulates and in which the major cerebral arteries run. Subarachnoid hemorrhage occurs when blood enters this space — most commonly when a brain aneurysm ruptures and releases arterial blood under high pressure into the subarachnoid space.
            </p>
            <p>
              The consequences are immediate and severe. The sudden entry of blood causes an instantaneous, massive rise in intracranial pressure — producing the hallmark thunderclap headache — and triggers an intense inflammatory and vasoconstrictive response throughout the cerebral vasculature. Blood disperses through the CSF pathways, coating the brain surface and filling the basal cisterns, setting in motion the cascade of complications — re-bleeding, vasospasm, hydrocephalus, and brain injury — that define the clinical course of SAH.
            </p>
            
            <h3 style="font-size: 1.4rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">How Common Is SAH?</h3>
            <p>
              SAH from aneurysm rupture affects approximately 10–12 per 100,000 people per year globally — approximately 6,000–8,000 new cases in India annually. It predominantly affects adults between 40 and 60 years of age, with women affected slightly more often than men. Despite advances in treatment, the overall mortality from SAH remains approximately 30–40% at 30 days, with approximately half of survivors experiencing long-term neurological or cognitive disability.
            </p>
          </section>

          <!-- Causes of Subarachnoid Hemorrhage -->
          <section id="causes" class="pillar-section">
            <h2 class="pillar-section-title">Causes of Subarachnoid Hemorrhage</h2>
            <p>
              The vast majority of non-traumatic SAH — approximately 85% — is caused by rupture of an intracranial aneurysm. The remaining causes include:
            </p>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li style="margin-bottom: 10px;"><strong>Non-aneurysmal perimesencephalic SAH (~10%)</strong> — a benign variant where blood is confined to the region around the midbrain (perimesencephalic cisterns); no aneurysm is found on imaging; excellent prognosis with low risk of rebleeding</li>
              <li style="margin-bottom: 10px;"><strong>Arteriovenous malformation (AVM) rupture (~3–5%)</strong> — tangles of abnormal blood vessels that bleed more commonly in younger patients</li>
              <li style="margin-bottom: 10px;"><strong>Cerebral venous thrombosis</strong> — blockage of the brain's draining veins causing haemorrhagic infarction that can extend into the subarachnoid space</li>
              <li style="margin-bottom: 10px;"><strong>Reversible cerebral vasoconstriction syndrome (RCVS)</strong> — thunderclap headache with arterial spasm; may cause SAH without an underlying aneurysm</li>
              <li style="margin-bottom: 10px;"><strong>Trauma</strong> — head injury causing subarachnoid bleeding, particularly in the cortical sulci</li>
              <li style="margin-bottom: 10px;"><strong>Rare causes</strong> — spinal AVM, intracranial arterial dissection, cocaine or stimulant use causing vessel rupture</li>
            </ul>
            <p>
              When SAH is confirmed on CT, the immediate priority is identifying the source — typically through CT angiography (CTA) followed by digital subtraction angiography (DSA). If no aneurysm is found on initial imaging, a repeat DSA at 7–14 days is essential, as small aneurysms can be missed on first-pass imaging due to vasospasm or technical factors.
            </p>
          </section>

