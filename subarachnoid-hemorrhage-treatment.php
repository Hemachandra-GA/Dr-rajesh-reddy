    document.addEventListener('DOMContentLoaded', function () {
      // Setup FAQ Accordions
      const faqQuestions = document.querySelectorAll('.pillar-faq-q');
      faqQuestions.forEach(question => {
        question.addEventListener('click', function() {
          const answer = this.nextElementSibling;
          const icon = this.querySelector('i');
          const isOpen = this.classList.contains('faq-open');

          if (isOpen) {
            this.classList.remove('faq-open');
            answer.style.maxHeight = null;
            icon.style.transform = 'rotate(0deg)';
          } else {
            // Close all others
            document.querySelectorAll('.pillar-faq-q').forEach(q => {
              q.classList.remove('faq-open');
              q.nextElementSibling.style.maxHeight = null;
              q.querySelector('i').style.transform = 'rotate(0deg)';
            });

            // Open this one
            this.classList.add('faq-open');
            answer.style.maxHeight = answer.scrollHeight + "px";
            icon.style.transform = 'rotate(180deg)';
          }
        });
      });

      // Smooth scroll for left sidebar links and active state highlighting
      const sidebarLinks = document.querySelectorAll('.sidebar-nav-link');
      const sections = document.querySelectorAll('.pillar-section');

      sidebarLinks.forEach(link => {
        link.addEventListener('click', function (e) {
          e.preventDefault();
          const targetId = this.getAttribute('href').substring(1);
          const targetSection = document.getElementById(targetId);
          if (targetSection) {
            targetSection.scrollIntoView({ behavior: 'smooth' });
            
            // Close mobile drawer if open
            if (window.innerWidth <= 991) {
              const leftSidebar = document.querySelector('.pillar-sidebar');
              const overlay = document.getElementById('mobileFloatOverlay');
              if (leftSidebar) leftSidebar.classList.remove('mobile-open');
              if (overlay) overlay.classList.remove('active');
              document.body.style.overflow = '';
            }
          }
        });
      });

      window.addEventListener('scroll', () => {
        let current = '';
        const scrollPosition = window.scrollY + 160;

        sections.forEach(section => {
          const sectionTop = section.offsetTop;
          const sectionHeight = section.clientHeight;
          if (scrollPosition >= sectionTop && scrollPosition < (sectionTop + sectionHeight)) {
            current = section.getAttribute('id');
          }
        });

        sidebarLinks.forEach(link => {
          link.classList.remove('active');
          if (link.getAttribute('href').substring(1) === current) {
            link.classList.add('active');
          }
        });
      });
    });
