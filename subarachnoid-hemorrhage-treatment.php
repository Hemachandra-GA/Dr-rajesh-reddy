          <section id="symptoms" class="pillar-section">
            <h2 class="pillar-section-title">Symptoms of Subarachnoid Hemorrhage</h2>
            <div style="margin: 20px 0; border-radius: 8px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
              <img src="images/Subarachnoid_Hemorrhage/Recognizing_sah.webp" alt="Recognizing SAH Symptoms" style="width: 100%; height: auto; display: block;">
            </div>
            
            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-bottom: 12px;">The Thunderclap Headache — The Cardinal Symptom</h3>
            <p>
              The hallmark of aneurysmal SAH is the <strong>thunderclap headache</strong> — a sudden, explosive headache of maximal severity that reaches its peak within 1–2 seconds of onset. Patients consistently describe it in vivid terms: 'a gun going off in my head,' 'the worst pain of my life,' 'like an explosion behind my eyes.' This instantaneous maximal onset — not the severity alone — is the defining feature. A headache that builds over minutes to hours is unlikely to be SAH; one that is maximal at the very first moment is an emergency until proven otherwise.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Associated Symptoms</h3>
            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li style="margin-bottom: 10px;"><strong>Neck stiffness (meningism):</strong> Develops within 3–6 hours of bleeding as subarachnoid blood irritates the meninges. Patients resist neck flexion, and the Kernig and Brudzinski signs may be positive on examination.</li>
              <li style="margin-bottom: 10px;"><strong>Nausea and vomiting:</strong> Often projectile, occurring within seconds to minutes of the headache — from the sudden rise in intracranial pressure.</li>
              <li style="margin-bottom: 10px;"><strong>Photophobia and phonophobia:</strong> Extreme sensitivity to light and sound from meningeal irritation — similar to severe migraine, but in the context of a thunderclap headache.</li>
              <li style="margin-bottom: 10px;"><strong>Loss of consciousness:</strong> Occurs at the time of rupture in approximately 45–50% of patients — caused by the sudden spike in ICP transiently stopping cerebral perfusion. Duration ranges from seconds (brief syncope) to prolonged coma in severe bleeds.</li>
              <li style="margin-bottom: 10px;"><strong>Seizures:</strong> Occur in 10–20% of SAH patients at or shortly after rupture.</li>
              <li style="margin-bottom: 10px;"><strong>Focal neurological deficit:</strong> Depending on the aneurysm location and extent of haemorrhage — weakness, speech difficulty, or cranial nerve palsies.</li>
              <li style="margin-bottom: 10px;"><strong>Sentinel headache (warning bleed):</strong> In approximately 20–50% of cases, a milder headache — representing a minor leak — precedes the major SAH by days to weeks. This sentinel headache is the most important missed diagnosis in emergency medicine.</li>
            </ul>

            <div style="background-color: #fff8e6; border-left: 4px solid #d32f2f; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              <strong>EMERGENCY:</strong> A sudden severe headache reaching maximum intensity within seconds — with or without vomiting, neck stiffness, or loss of consciousness — must be treated as SAH until proven otherwise. Call emergency services immediately. Do not drive to hospital. Every minute without treatment after aneurysm rupture increases the risk of re-bleeding and death.
            </div>
          </section>

