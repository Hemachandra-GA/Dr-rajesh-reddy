            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 32px; margin-bottom: 12px;">Vasospasm — The Delayed Danger</h3>
            <p>
              Cerebral vasospasm — progressive narrowing of the cerebral arteries in response to blood breakdown products in the subarachnoid space — is the leading cause of death and disability in SAH patients who survive the initial rupture. It typically develops between days 4–14 after bleeding, peaking around day 7–10, and can cause delayed cerebral ischaemia (DCI) — effectively a stroke — even in patients whose aneurysm has been successfully treated.
            </p>
            <p>
              Medical management includes oral nimodipine (started on admission and continued for 21 days), maintenance of adequate blood pressure and fluid balance (euvolaemia), and transcranial Doppler (TCD) monitoring — which tracks blood flow velocities in the cerebral arteries as a surrogate for vasospasm severity.
            </p>
            <p>
              When vasospasm becomes symptomatic — the patient develops new neurological deficits despite optimal medical management — endovascular rescue therapy is performed: intra-arterial infusion of vasodilators (Nimodipine, Verapamil, Milrinone) directly into the spastic vessel through a microcatheter, or balloon angioplasty of severely narrowed arterial segments. Dr. Rajesh Reddy's endovascular expertise is directly applicable to this often-overlooked but critically important aspect of SAH management.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Hydrocephalus</h3>
            <p>
              Blood in the subarachnoid space obstructs the arachnoid granulations that reabsorb CSF, causing communicating hydrocephalus. Acute hydrocephalus — developing within the first 24–72 hours — is managed with an external ventricular drain (EVD), a bedside procedure placing a small catheter into the lateral ventricle to relieve pressure. Approximately 15–20% of SAH patients develop chronic hydrocephalus requiring a permanent ventriculoperitoneal (VP) shunt, typically inserted 3–6 weeks after the bleed once the CSF has cleared of blood products.
            </p>

            <h3 style="font-size: 1.3rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Cardiac and Systemic Complications</h3>
            <p>
              SAH triggers a massive catecholamine surge that affects multiple organ systems. ECG changes — T-wave inversions, QT prolongation, ST changes — are seen in up to 90% of SAH patients and do not indicate primary cardiac disease. Neurogenic stunned myocardium — transient left ventricular dysfunction — occurs in 10–15% and may require inotropic support. Neurogenic pulmonary oedema can develop suddenly. Hyponatraemia from cerebral salt wasting or SIADH is among the most common and clinically significant systemic complications, requiring careful electrolyte management to avoid exacerbating cerebral oedema.
            </p>
