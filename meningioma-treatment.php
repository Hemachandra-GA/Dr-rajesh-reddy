                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <td><strong>Grade I</strong></td>
                    <td>Complete removal including dural attachment and any involved bone</td>
                    <td>~9%</td>
                  </tr>
                  <tr>
                    <td><strong>Grade II</strong></td>
                    <td>Complete tumor removal; dural attachment cauterised (coagulated)</td>
                    <td>~19%</td>
                  </tr>
                  <tr>
