            <h2 class="pillar-section-title">Active Surveillance: When Watching Is the Right Choice</h2>
            <p>Not every meningioma needs immediate treatment. Current evidence and international guidelines support active surveillance (also called watch-and-wait) for:</p>
            <ul>
              <li>Small meningiomas (typically &lt; 3 cm) that are asymptomatic and discovered incidentally</li>
              <li>Elderly patients or those with significant comorbidities for whom the risks of surgery outweigh the benefits</li>
              <li>Tumors in surgically challenging locations (e.g., cavernous sinus) where surgery carries high cranial nerve risk and the tumor is not causing symptoms</li>
              <li>Patients who decline intervention after informed counselling</li>
            </ul>
            <p>During active surveillance, MRI is performed at regular intervals — typically at 3 months after diagnosis, then annually for several years, and less frequently thereafter if the tumor shows no growth. Studies show that approximately 50–60% of small, incidentally discovered meningiomas show no significant growth over 5 years. However, tumors that do show growth — or that develop new symptoms — are reassessed for intervention.</p>
            <p>Active surveillance is not passive neglect — it is a deliberate, evidence-based strategy for meningiomas that do not require immediate treatment. Regular follow-up imaging is essential. If a tumor shows growth or new symptoms develop, the treatment plan is revised accordingly.</p>
          </section>

          <!-- Radiosurgery Section -->
          <section id="radiosurgery" class="pillar-section">
            <h2 class="pillar-section-title">Stereotactic Radiosurgery: Treating Meningioma Without Open Surgery</h2>
            <p>Stereotactic radiosurgery (SRS) — delivered by platforms such as Gamma Knife, CyberKnife, or linear accelerator-based systems — is one of the most important advances in meningioma management. Despite the name, it is not conventional surgery. It uses multiple highly focused beams of radiation that converge precisely on the tumor, delivering a high dose to the target while sparing surrounding tissue. There is no incision, no anaesthesia (or only mild sedation), and no hospital admission in most cases.</p>

            <h3>When Is SRS the Right Choice for Meningioma?</h3>
            <ul>
              <li>Small to medium-sized meningiomas — typically less than 3 cm in maximum diameter — in patients who have no significant pressure-related symptoms. Where a tumor under 3 cm is causing symptoms from mass effect (visual loss, focal weakness, seizures), surgery is generally preferable to SRS even within this size range, as SRS does not provide immediate decompression</li>
              <li>Tumors in surgically inaccessible locations — particularly cavernous sinus, petroclival, and posterior fossa meningiomas where open surgery carries significant cranial nerve risk</li>
              <li>Residual or recurrent tumor after previous surgery</li>
              <li>Elderly patients or those with medical comorbidities who are not good surgical candidates</li>
              <li>Patients who prefer a non-surgical approach and whose tumor characteristics are suitable</li>
            </ul>

            <h3>How Effective Is SRS for Meningioma?</h3>
            <p>For WHO Grade I meningiomas treated with SRS, long-term tumour control rates (defined as no growth or shrinkage on imaging) are excellent: approximately <strong>90–95% at 5 years</strong> and <strong>85–90% at 10 years</strong>. Many tumors shrink after SRS, though this response is gradual — occurring over months to years. SRS does not remove the tumor; it stops it from growing by damaging the DNA of rapidly dividing tumor cells.</p>
            <p>Cranial nerve preservation rates after SRS for cavernous sinus meningiomas are generally superior to open surgery — which is one of the main reasons SRS is preferred for tumors in this location when the tumor is of an appropriate size.</p>

            <h3>Radiation for Grade II and III Meningiomas</h3>
            <p>For atypical (Grade II) and anaplastic (Grade III) meningiomas, post-operative radiation is an important part of the treatment plan. These higher-grade tumors have significantly higher recurrence rates even after complete resection, and adjuvant radiation — using standard fractionated external beam radiotherapy or SRS for smaller residual volumes — is recommended. The decision on radiation modality and framing is made in the multidisciplinary tumour board, tailored to the extent of resection, tumor grade, and the patient's overall condition.</p>

            <h3>Fractionated Stereotactic Radiotherapy (FSRT)</h3>
            <p>For larger meningiomas that are too big for single-session SRS, or for tumors very close to critical structures (optic nerves, brainstem), fractionated stereotactic radiotherapy delivers the radiation dose in multiple smaller sessions (typically 25–30 fractions over 5–6 weeks). This allows a higher total dose to be given safely to larger targets near sensitive structures.</p>


          </section>

          <!-- Microsurgery Section -->
          <section id="microsurgery" class="pillar-section">
            <h2 class="pillar-section-title">Microsurgical Meningioma Resection: When Surgery Is the Answer</h2>
            <p>For symptomatic meningiomas, large tumors, tumors showing rapid growth, or cases where a histological diagnosis is required, microsurgical resection is the definitive treatment. The goal is Simpson Grade I or II resection — complete removal of the tumor including its dural attachment — which carries the lowest recurrence risk.</p>

            <h3>The Simpson Grading System: Measuring Completeness of Resection</h3>
            <p>The extent of meningioma resection is described using the Simpson grading system. The grade achieved directly correlates with the risk of recurrence:</p>

            <div class="pillar-table-wrapper">
              <table class="pillar-table">
                <thead>
                  <tr>
                    <th>Simpson Grade</th>
                    <th>Extent of Resection</th>
