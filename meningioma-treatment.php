          <section id="symptoms" class="pillar-section">
            <h2 class="pillar-section-title">Meningioma Symptoms: From Incidental to Severe</h2>
            <p>Meningioma symptoms depend entirely on the tumor's size and location. Many meningiomas cause no symptoms at all and are found by chance. When symptoms do occur, they reflect the compression of adjacent brain tissue, cranial nerves, or major venous sinuses:</p>

            <h3>General Symptoms From Raised Intracranial Pressure</h3>
            <ul>
              <li><strong>Progressive headaches</strong> — typically dull, pressure-like, worsening over weeks to months</li>
              <li><strong>Nausea and vomiting</strong> — particularly in the morning</li>
              <li><strong>Visual blurring or papilloedema</strong> on fundoscopic examination</li>
            </ul>

            <h3>Location-Specific Symptoms</h3>
            <p><strong>Convexity meningioma:</strong> Seizures (often the only symptom for years), progressive weakness or numbness on one side of the body.</p>
            <p><strong>Parasagittal meningioma:</strong> Leg weakness — bilateral if the tumor involves both sides of the superior sagittal sinus; bladder urgency in some cases.</p>
            <p><strong>Sphenoid wing meningioma:</strong> Progressive visual loss in one eye, protrusion of the eyeball (proptosis), or headache behind the eye.</p>
            <p><strong>Olfactory groove meningioma:</strong> Loss of smell (anosmia) — often not noticed by the patient — followed by personality change and frontal lobe syndrome as the tumor enlarges.</p>
            <p><strong>Cavernous sinus meningioma:</strong> Drooping of the eyelid (ptosis), double vision, facial pain or numbness — from compression of cranial nerves III, IV, V, and VI.</p>
            <p><strong>Posterior fossa meningioma:</strong> Hearing loss, tinnitus, facial weakness or numbness, balance disturbance — from cranial nerve involvement.</p>
            <p><strong>Suprasellar meningioma:</strong> Progressive visual loss and visual field defects (typically bitemporal) from compression of the optic chiasm; headache behind the eyes; hormonal disturbances if the pituitary stalk is involved. Often misdiagnosed as a pituitary tumor — MRI characterisation is essential to distinguish the two.</p>
            <p><strong>Foramen magnum meningioma:</strong> Neck pain and suboccipital headache; progressive weakness and numbness starting in the arms and spreading to the legs; difficulty with fine hand movements; balance and gait disturbance. These tumors are notoriously difficult to diagnose early as their symptoms mimic cervical spine disease — any patient with progressive upper and lower limb neurological findings should have MRI of both the cervical spine and the posterior fossa.</p>


