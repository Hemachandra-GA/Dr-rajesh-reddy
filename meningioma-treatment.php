            <p style="margin-top: 20px;">Achieving Simpson Grade I resection is the surgical ideal, but is not always possible when the tumor involves a major venous sinus, cranial nerves, or critical arteries. In these cases, intentional subtotal resection (Simpson Grade IV) combined with post-operative SRS for the residual tumor may offer the best balance of tumour control and safety.</p>

            <h3>Pre-operative Embolisation: Reducing Surgical Risk for Vascular Meningiomas</h3>
            <p>Meningiomas — particularly skull base tumors — have a rich blood supply from dural arteries. Large, highly vascular tumors can cause significant blood loss during surgery, increasing operative risk. Pre-operative embolisation addresses this by occluding the tumor's feeding arteries 24–48 hours before surgery. Performed through a small arterial access point in the groin under X-ray guidance, embolisation significantly reduces intraoperative bleeding and can make a complex tumour resection substantially safer.</p>
            <p><strong>Emerging Role in Tumour Growth Control:</strong> Latest studies have shown that in a select group of patients — particularly those with small asymptomatic meningiomas who are not candidates for surgery or SRS — standalone embolisation (without subsequent surgery) can prevent tumour growth by devascularising the tumour and depriving it of its blood supply. The mechanism is similar to SRS: the goal is tumour growth arrest rather than immediate removal. This is an evolving area and patient selection for standalone embolisation is discussed on a case-by-case basis at Dr. Rajesh Reddy's multidisciplinary tumour board.</p>
            <p>Dr. Rajesh Reddy's fellowship training in Interventional Neuroradiology at the University Hospital, Zurich — and his endovascular expertise — allows him to perform pre-operative meningioma embolisation himself, providing seamless integration between the embolisation and surgical phases of treatment. This is a significant advantage over centres where these two procedures are performed by different specialists.</p>

            <h3>Neuronavigation and Intraoperative Monitoring</h3>
            <p>All meningioma surgeries performed by Dr. Rajesh Reddy utilise neuronavigation — a real-time 3D GPS-like imaging system that tracks the surgeon's instruments relative to the patient's pre-operative MRI throughout the procedure. For tumors near cranial nerves — particularly in the skull base — intraoperative neurophysiological monitoring (cranial nerve EMG, auditory evoked potentials) provides real-time feedback on nerve function, allowing the surgeon to adjust the dissection before a deficit occurs rather than after.</p>
          </section>

          <!-- Atypical & Malignant Section -->
          <section id="atypical-malignant" class="pillar-section">
            <h2 class="pillar-section-title">Atypical and Malignant Meningiomas (WHO Grade II and III)</h2>
            <p>Approximately 15–20% of meningiomas are atypical (WHO Grade II) or malignant (WHO Grade III). These tumors have higher rates of recurrence after surgery and require a more aggressive treatment approach:</p>
            <p><strong>WHO Grade II (Atypical) Meningioma:</strong> Higher mitotic activity than Grade I. Recurrence risk after gross total resection is approximately 30–40% at 5 years. Post-operative radiotherapy is increasingly recommended even after complete resection, particularly for tumors in locations prone to recurrence.</p>
            <p><strong>WHO Grade III (Malignant) Meningioma:</strong> Rare (approximately 1–3% of all meningiomas) but behaves aggressively — invading brain tissue and recurring despite surgery and radiation. Requires maximum surgical resection followed by adjuvant radiotherapy. Chemotherapy has limited efficacy; clinical trial participation should be considered.</p>
            <p>The management of atypical and malignant meningiomas is determined in a tumour board meeting involving neurosurgery, radiation oncology, and medical oncology, with treatment plans tailored to the individual patient's tumor grade, location, extent of resection, and performance status.</p>
          </section>

          <!-- Recovery Section -->
          <section id="recovery" class="pillar-section">
            <h2 class="pillar-section-title">Recovery After Meningioma Treatment</h2>

            <h3>After Microsurgical Resection</h3>
            <ul>
              <li><strong>Hospital stay:</strong> typically 3–7 days depending on tumor size, location, and any post-operative neurological changes</li>
              <li>ICU monitoring for the first 24–48 hours; neurological observations every 2–4 hours</li>
              <li>Post-operative MRI within 24–72 hours to assess extent of resection</li>
              <li>Steroids tapered over 1–2 weeks to manage brain swelling</li>
              <li>Most patients with convexity meningiomas return to normal activities within 4–6 weeks</li>
              <li>Skull base meningioma patients may have a longer recovery depending on cranial nerve involvement</li>
            </ul>

            <h3>After Stereotactic Radiosurgery</h3>
            <ul>
              <li><strong>Day procedure</strong> — patients go home the same day or the following morning</li>
              <li>Mild headache and fatigue in the first 1–2 weeks; managed with steroids and analgesics</li>
              <li>First follow-up MRI at 3–6 months; then annually</li>
              <li>Tumour response (shrinkage or stabilisation) develops gradually over months to years</li>
              <li>Return to normal activities within days of the procedure</li>
            </ul>

            <h3>After Active Surveillance</h3>
            <ul>
              <li>Regular MRI appointments as scheduled — typically at 3 months, then annually</li>
              <li>Any new or worsening symptoms should prompt an earlier review</li>
              <li>Lifestyle is unrestricted — meningioma surveillance does not require activity limitation</li>
            </ul>


          </section>

