            <h2 class="pillar-section-title">Diagnosing a Meningioma</h2>
            <p>Meningiomas have a characteristic appearance on MRI that experienced neurosurgeons recognise readily. Key diagnostic features include:</p>

            <h3>MRI with Contrast — The Gold Standard</h3>
            <p>Meningiomas show intense, homogeneous enhancement with gadolinium contrast on MRI. The <strong>'dural tail sign'</strong> — a linear enhancement of the dura adjacent to the tumor — is highly suggestive of meningioma. MRI also defines the tumor's relationship to adjacent brain, venous sinuses, cranial nerves, and major arteries — all critical for surgical planning.</p>

            <h3>CT Scan</h3>
            <p>CT is useful for assessing bony involvement — meningiomas can cause hyperostosis (thickening and remodelling) of the adjacent skull, which is visible on CT but not on MRI. CT angiography maps the tumor's blood supply and its relationship to major vessels — essential planning information for vascular meningiomas.</p>

            <h3>Cerebral Angiography</h3>
            <p>For highly vascular meningiomas — particularly skull base tumors supplied by meningeal and dural arteries — formal cerebral angiography (DSA) is performed to map the tumor's vascularity in detail. This is also the procedure through which pre-operative embolisation is performed, if indicated.</p>

            <h3>Is a Biopsy Needed Before Treatment?</h3>
            <p>For most meningiomas, the MRI appearance is so characteristic — a dural-based, homogeneously enhancing mass with a dural tail — that a pre-operative tissue biopsy is not required and has no role. The diagnosis is confirmed histologically when the tumor is surgically removed. Treatment decisions (surgery vs. SRS vs. observation) are made on the basis of imaging characteristics, clinical symptoms, and patient factors — not biopsy.</p>
