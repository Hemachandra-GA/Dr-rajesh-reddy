                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Surgical duration depends heavily on the tumor's size, type, and location, and on which technique is
                    used. A straightforward endoscopic pituitary adenoma removal may take 2–3 hours. A microsurgical
                    resection of a moderate-sized meningioma may take 4–6 hours. An awake craniotomy for a glioma near
                    the speech area, with full intraoperative mapping, skull base tumors, and vestibular schwannomas may
                    take 6–10 hours. Dr. Rajesh Reddy will provide a realistic estimate for your specific case after
                    reviewing your MRI and discussing the planned surgical approach.
