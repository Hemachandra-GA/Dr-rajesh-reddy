            <h3 style="font-size: 1.5rem; font-weight: 700; margin-top: 2rem; margin-bottom: 1rem;">What Is a Brain
              Tumor?</h3>
            <p>A brain tumor is an abnormal mass of cells that grows within the brain or the structures surrounding it —
              including the meninges (the protective membranes encasing the brain), the cranial nerves, the pituitary
              gland, and the skull base. Tumors can arise from the brain tissue itself, or they can spread to the brain
              from cancers in other parts of the body.</p>
            <p>It is important to understand from the outset that not all brain tumors are cancers, and not all brain
              tumors are immediately life-threatening. The prognosis and treatment pathway depend heavily on the type,
              grade, size, and location of the tumor.</p>

            <div style="margin-top: 32px; text-align: center;">
