            <h3 style="font-size: 1.5rem; font-weight: 700; margin-top: 2rem; margin-bottom: 1rem;">Radiation Therapy
              (Radiotherapy)</h3>
            <p>Standard of care for GBM and other high-grade tumors following surgery. Typically delivered as
              fractionated external beam radiotherapy over 6 weeks. Stereotactic radiosurgery (SRS) — highly focused
              single or few-fraction radiation — may be used for smaller residual tumors, metastases, or recurrent
              disease.</p>

            <h3 style="font-size: 1.5rem; font-weight: 700; margin-top: 2rem; margin-bottom: 1rem;">Chemotherapy</h3>
            <p>Temozolomide (TMZ) is the standard chemotherapy agent for GBM, administered concurrently with radiation
              and then as adjuvant treatment. MGMT promoter methylation — a molecular marker tested on the surgical
              specimen — predicts response to TMZ and helps personalise chemotherapy decisions.</p>

            <h3 style="font-size: 1.5rem; font-weight: 700; margin-top: 2rem; margin-bottom: 1rem;">Tumour Treating
              Fields (TTFields)</h3>
            <p>A relatively newer treatment modality that uses alternating electric fields delivered via scalp
              electrodes to disrupt tumor cell division. Used in combination with adjuvant TMZ for GBM, TTFields have
              been shown to improve progression-free and overall survival.</p>

            <h3 style="font-size: 1.5rem; font-weight: 700; margin-top: 2rem; margin-bottom: 1rem;">Targeted Therapy and
              Immunotherapy</h3>
            <p>For select patients with specific molecular targets (BRAF mutation, IDH mutation), targeted therapeutic
              agents are available. Immunotherapy is an active area of clinical research for brain tumors and may be
              accessible through clinical trial participation. Dr. Rajesh Reddy works closely with neuro-oncologists to
              discuss emerging treatment options for eligible patients.</p>

