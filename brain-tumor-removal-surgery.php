            <h3
              style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">
              Primary vs. Secondary (Metastatic) Brain Tumors</h3>
            <p><strong>Primary brain tumors</strong> originate in the brain itself. They can arise from neurons, glial
              cells (the
              supportive cells of the brain), meninges, cranial nerves, or the pituitary gland. Examples include
              gliomas, meningiomas, pituitary adenomas, medulloblastomas, and acoustic neuromas.</p>
            <p><strong>Secondary (metastatic) brain tumors</strong> originate from cancer cells that have spread from
              elsewhere in the
              body — commonly from the lung, breast, kidney, colon, or skin (melanoma). Metastatic brain tumors are
              actually more common than primary brain tumors and may present as single or multiple lesions.</p>

            <h3
              style="font-size: 1.1rem; font-weight: 700; color: #0066cc; margin-top: 1.5rem; margin-bottom: 0.75rem;">
              Benign vs. Malignant Brain Tumors</h3>
            <p><strong>Benign tumors</strong> are non-cancerous. They grow slowly, have well-defined borders, and do not
              invade
              surrounding brain tissue. However, benign does not mean harmless — even a benign tumor can cause serious
              neurological problems by pressing on critical brain structures. Meningiomas, pituitary adenomas, and
              acoustic neuromas are common benign brain tumors.</p>
            <p><strong>Malignant tumors</strong> are cancerous. They grow more rapidly, often invade adjacent brain
              tissue, and can be
              life-threatening. Glioblastoma multiforme (GBM) is the most aggressive primary brain tumor and carries a
              poor prognosis without prompt, multimodal treatment. Surgical resection is a key first step in managing
              malignant brain tumors.</p>

