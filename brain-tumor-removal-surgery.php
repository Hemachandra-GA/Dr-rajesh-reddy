                <div class="pillar-faq-q">
                  How do I know if my headache could be a brain tumor?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    The vast majority of headaches — even severe or chronic ones — are not caused by brain tumors. Brain
                    tumor headaches typically have specific characteristics: they are progressive over days to weeks,
                    often worse in the morning or when lying down, and are accompanied by other symptoms such as nausea,
                    vision changes, or neurological weakness. A headache that is new in onset, progressively worsening,
                    or associated with any neurological symptom warrants a medical evaluation and, in most cases, an MRI
                    of the brain.
                  </div>
