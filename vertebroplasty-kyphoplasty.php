          <!-- Section 8: Step-by-Step Procedure -->
          <section id="step-by-step" class="pillar-section">
            <h2>The Procedure: Step-by-Step</h2>

            <h3>1. Pre-Procedure Preparation</h3>
            <p>Routine blood investigations including coagulation profile and renal function; current medications reviewed — blood thinners (warfarin, clopidogrel, rivaroxaban) are held for the appropriate washout period before the procedure; nil by mouth for 4–6 hours if general anaesthesia or deep sedation is planned; consent discussion covering procedure risks, cement leakage, adjacent fracture risk, and the possibility of incomplete pain relief.</p>

            <h3>2. Positioning and Access</h3>
            <p>The patient is positioned prone on the operating table. For vertebroplasty, local anaesthetic is infiltrated into the skin, soft tissues, and the periosteum of the pedicle through which the needle will pass. For kyphoplasty or in anxious patients, intravenous sedation (monitored anaesthesia care) or general anaesthesia is used. Two approaches are available: transpedicular (the standard approach — through the pedicle on one or both sides) and extrapedicular (a lateral approach used for upper thoracic vertebrae where the pedicles are small).</p>

            <h3>3. Needle Placement</h3>
            <p>Under continuous fluoroscopic guidance — with anteroposterior (AP) and lateral X-ray views confirming needle position at each step — the trocar is advanced through the pedicle and positioned in the anterior one-third to one-half of the vertebral body. Correct positioning is confirmed before any cement or balloon is introduced. CT guidance is used in cases where fluoroscopic anatomy is unclear or the pedicle is particularly narrow.</p>

            <h3>4. Balloon Inflation (Kyphoplasty Only)</h3>
            <p>For kyphoplasty, the inflatable bone tamp is inserted through the working cannula and positioned within the vertebral body. The balloon is gradually inflated using a contrast-filled syringe under fluoroscopic monitoring — the height restoration and balloon position are assessed in real time. Inflation continues until: the endplate begins to lift (height is being restored); the balloon reaches the cortical margin of the vertebral body; or the maximum safe inflation volume is reached. The balloon is then deflated and removed.</p>

            <h3>5. Cement Injection</h3>
            <p>PMMA cement is mixed and monitored for viscosity — it must be injected at the correct consistency (neither too liquid, which risks leakage, nor too stiff, which risks inadequate filling). The cement is injected slowly under continuous fluoroscopic guidance, watching carefully for any leakage into the venous system, the disc, or the epidural space. Injection is immediately stopped if any cement approaches the posterior vertebral wall. The procedure is typically complete within 30–60 minutes.</p>

            <div class="note-box" style="background:#eff6ff; border-left:4px solid #3b82f6; padding:16px; margin:24px 0; border-radius:4px;">
              <strong>Preventing Cement Leakage:</strong> Cement leakage — the most significant procedural risk — occurs when cement enters the epidural space, the spinal canal, the venous system (pulmonary embolism risk), or the adjacent disc. Modern fluoroscopic monitoring, careful cement viscosity management, and the lower-pressure injection technique of kyphoplasty have substantially reduced leakage rates. In experienced hands, clinically significant cement leakage occurs in less than 1–2% of procedures.
            </div>
          </section>

