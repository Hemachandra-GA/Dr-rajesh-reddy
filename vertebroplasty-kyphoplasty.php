          <!-- Section 11: Osteoporosis Treatment -->
          <section id="osteoporosis-treatment" class="pillar-section">
            <h2>Osteoporosis Treatment: The Essential Next Step</h2>
            <p>Vertebroplasty and kyphoplasty stabilise the fractured vertebra but do not treat the underlying osteoporosis. Without addressing the bone fragility, the risk of adjacent vertebral fractures — which occurs in approximately 20% of patients within the first year after a treated compression fracture — remains high.</p>
            <p>All patients who undergo these procedures should receive a comprehensive osteoporosis assessment and treatment plan:</p>
            <ul class="pillar-list">
              <li><strong>DEXA scan:</strong> To quantify bone mineral density and establish a baseline for monitoring treatment response.</li>
              <li><strong>Calcium and Vitamin D3:</strong> Calcium (1,200 mg/day) and Vitamin D3 (800–2,000 IU/day) supplementation as the foundation of metabolic bone support.</li>
              <li><strong>Anti-resorptive medications:</strong> Bisphosphonates (alendronate, zoledronic acid) or denosumab reduce future vertebral fracture risk by 40–70%.</li>
              <li><strong>Anabolic bone-forming therapy:</strong> Teriparatide for severe osteoporosis, particularly valuable in patients with multiple fractures.</li>
              <li><strong>Fall prevention programme:</strong> Home safety assessment, balance training, and hip protectors for high-fall-risk patients.</li>
            </ul>
            <p>The fracture that brought the patient to vertebroplasty is often not their first — studies show that up to 60% of osteoporotic patients have had prior silent vertebral fractures. A compression fracture is a sentinel event: it signals severe systemic bone fragility that requires urgent medical therapy, not just management of the immediate injury.</p>
