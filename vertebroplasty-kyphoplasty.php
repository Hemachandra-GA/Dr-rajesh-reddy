          <section id="cancer-pathological" class="pillar-section">
            <h2>Pathological Fractures: Vertebroplasty in Cancer</h2>
            <p>Vertebral metastases — bone deposits from cancers of the breast, lung, prostate, kidney, and thyroid, as well as multiple myeloma — are a major cause of pathological compression fractures. The pain from metastatic vertebral disease can be severe and refractory to analgesics, and the associated fracture significantly impairs the patient's quality of life and functional independence.</p>
            <p>Vertebroplasty and kyphoplasty are highly effective for pain palliation in patients with pathological compression fractures from metastatic disease, where the goals are different from osteoporotic fractures:</p>
            <ul class="pillar-list">
              <li><strong>Rapid pain relief:</strong> Allowing significant reduction in opioid analgesia and improved quality of life.</li>
              <li><strong>Spine stabilisation:</strong> Preventing further collapse and progressive neurological risk.</li>
              <li><strong>Enabling radiotherapy:</strong> A stabilised vertebra allows radiotherapy to proceed to the lesion without the risk of further collapse during treatment.</li>
              <li><strong>Enabling continuation of systemic therapy:</strong> Patients who are bedridden by vertebral pain cannot receive chemotherapy safely; vertebroplasty restores mobility and allows cancer treatment to continue.</li>
            </ul>
            <p>In patients with cancer, vertebroplasty is typically combined with a multidisciplinary oncology approach — the procedure addresses the structural failure while radiotherapy, systemic therapy, and bone-modifying agents (bisphosphonates, denosumab) address the underlying disease. Dr. Rajesh Reddy works closely with oncology teams in Hyderabad to provide integrated vertebral stabilisation as part of a comprehensive cancer treatment plan.</p>
            
            <div class="note-box" style="background:#fef2f2; border-left:4px solid #ef4444; padding:16px; margin:24px 0; border-radius:4px;">
              <strong>Important Oncology Precaution:</strong> If the posterior vertebral wall is destroyed by the tumour, or if there is epidural tumour causing spinal cord compression, vertebroplasty alone is not sufficient. These cases require surgical decompression and stabilisation first, or — in select cases — image-guided tumour ablation combined with cement augmentation. Dr. Rajesh Reddy's neurosurgical expertise allows him to make this distinction and recommend the appropriate approach for each patient.
