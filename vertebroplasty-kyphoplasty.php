          <!-- Section 2: What Is a Spinal Compression Fracture? -->
          <section id="what-is-vcf" class="pillar-section">
            <h2>What Is a Spinal Compression Fracture?</h2>
            <p>A vertebral compression fracture (VCF) occurs when the vertebral body — the large, block-shaped anterior part of each vertebra that bears axial load — collapses under compressive forces. Unlike a traumatic burst fracture (where high-energy impact shatters the vertebra), a compression fracture typically involves failure of the anterior column only: the front of the vertebral body wedges downward while the posterior wall (the back of the bone adjacent to the spinal canal) remains intact.</p>
            <p>The result is a wedge-shaped deformity: the front of the vertebra becomes shorter than the back, tilting the spine forward and contributing to thoracic kyphosis (the hunched posture associated with osteoporosis). When multiple levels fracture over time, the cumulative kyphosis can become significant — reducing height by several centimetres, compressing the abdominal cavity, impairing lung function, and causing chronic pain.</p>
          </section>

          <!-- Section 3: Who Gets Compression Fractures? -->
          <section id="who-gets-fractures" class="pillar-section">
            <h2>Who Gets Compression Fractures?</h2>
            <p>Osteoporosis is by far the most common underlying cause. It is estimated that osteoporotic vertebral fractures affect approximately 1.4 million people worldwide each year, making them the most common osteoporotic fracture — more common than hip or wrist fractures. In India, the scale of the problem is large but substantially underdiagnosed: many patients accept back pain and height loss as an inevitable part of ageing rather than recognising these as the sequelae of vertebral fractures.</p>
            <p>Primary risk groups include:</p>
            <ul class="pillar-list">
              <li><strong>Post-menopausal women:</strong> Oestrogen withdrawal accelerates bone resorption, and the majority of osteoporotic compression fractures occur in this group.</li>
              <li><strong>Elderly men:</strong> Testosterone decline and age-related bone loss lead to increasing fracture risk after age 70.</li>
              <li><strong>Patients on long-term corticosteroids:</strong> Glucocorticoid-induced osteoporosis is the most common secondary cause of compression fractures.</li>
              <li><strong>Cancer patients:</strong> Vertebral metastases weaken bone and cause pathological fractures at loads that would not injure normal vertebrae.</li>
              <li><strong>Patients with multiple myeloma:</strong> Diffuse bone involvement makes multiple simultaneous vertebral fractures common.</li>
              <li><strong>Metabolic bone diseases:</strong> Patients with hyperparathyroidism, renal osteodystrophy, or osteomalacia.</li>
            </ul>
          </section>

