            <p>A spinal compression fracture can reduce a previously active, independent person to near-immobility within hours. The sudden, sharp back pain — often following a seemingly minor event such as bending forward, lifting a light object, or even coughing — is the presenting symptom of a vertebral body that has collapsed under loads it can no longer withstand. In osteoporotic patients, that threshold has been progressively lowered over years of silent bone loss, and the fracture is the point at which the bone simply gives way.</p>
            <p>For decades, the only treatment options were bed rest, pain medication, and a brace — a conservative programme that offered gradual pain relief but did nothing to address the structural failure of the vertebra, the progressive kyphotic deformity (the forward stooping posture that follows multiple compression fractures), or the prolonged period of immobility that significantly worsens the osteoporosis itself. For elderly patients, extended bed rest carries its own serious risks: pneumonia, deep vein thrombosis, pressure ulcers, deconditioning, and accelerated bone loss.</p>
