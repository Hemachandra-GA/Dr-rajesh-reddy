          <section id="vertebroplasty-procedure" class="pillar-section">
            <h2>Vertebroplasty: The Procedure Explained</h2>
            <p>Vertebroplasty was first performed in France in 1984 for the treatment of a painful vertebral haemangioma, with the initial clinical report published in 1987 by Galibert et al. (Galibert and colleagues). It was subsequently adopted for osteoporotic compression fractures in the 1990s and has since become one of the most widely performed minimally invasive spine procedures worldwide.</p>
            
            <h3>How Vertebroplasty Works</h3>
            <p>Under fluoroscopic (real-time X-ray) or CT guidance, with the patient positioned prone (face down), a hollow needle — a trocar — is advanced through the pedicle of the fractured vertebra (the bony bridge connecting the back of the vertebra to its body) and positioned within the collapsed vertebral body. This transpedicular approach keeps the needle safely away from the spinal canal.</p>
            <p>Once the needle tip is correctly positioned within the fractured bone, polymethylmethacrylate (PMMA) bone cement — the same acrylic cement used in hip and knee arthroplasty — is mixed to a toothpaste-like consistency and injected under fluoroscopic guidance. The cement flows into the trabecular spaces of the fractured vertebra, fills the fracture lines, and polymerises (hardens) within minutes, rigidly stabilising the fracture.</p>
            <p>The mechanism of pain relief is twofold: mechanical stabilisation of the fracture eliminates the micro-motion at the fracture site that generates pain with every breath and movement; and the exothermic reaction of cement polymerisation may also ablate pain-sensitive nerve endings within the fractured bone. The result is typically rapid — many patients report significant pain reduction within hours of the procedure.</p>
            
            <div class="note-box" style="background:#fefce8; border-left:4px solid #ca8a04; padding:16px; margin:24px 0; border-radius:4px;">
              <strong>ANATOMICAL SAFETY CHECK:</strong> A key requirement for vertebroplasty is that the posterior vertebral wall must be intact. If the fracture has involved the back wall of the vertebral body (as in a burst fracture), cement injected under pressure can retropulse into the spinal canal, compressing the spinal cord or cauda equina. Dr. Rajesh Reddy reviews CT and MRI imaging carefully before every procedure to confirm posterior wall integrity.
            </div>
          </section>

          <!-- Section 5: Balloon Kyphoplasty -->
          <section id="kyphoplasty-procedure" class="pillar-section">
            <h2>Kyphoplasty (Balloon Kyphoplasty): Restoring Vertebral Height</h2>
            <p>Kyphoplasty adds a critical additional step to the vertebroplasty technique: before cement injection, an inflatable bone tamp (a small balloon) is inserted into the fractured vertebra and gradually inflated. The expanding balloon compacts the surrounding cancellous bone, creates a cavity within the vertebral body, and — most importantly — can restore some of the lost vertebral height by pushing the collapsed endplates back toward their original position.</p>
            <p>Once the desired height restoration is achieved (or the balloon reaches its maximum safe inflation volume), the balloon is deflated and removed, leaving a well-defined cavity within the bone. Cement is then injected at low pressure to fill this cavity — the contained, pre-formed space means cement fills under lower pressure than vertebroplasty, reducing the risk of cement leakage.</p>

            <h3>The Height Restoration Advantage</h3>
            <p>In acute fractures — those treated within 6 weeks of the injury — kyphoplasty can restore 30–60% of the lost vertebral height on average. This is clinically significant for several reasons:</p>
            <ul class="pillar-list">
              <li><strong>Kyphotic deformity is reduced:</strong> The patient's posture improves and the progressive forward stooping of the thoracic spine is partially corrected.</li>
              <li><strong>Adjacent segment stress is reduced:</strong> A kyphotic deformity concentrates mechanical stress on the vertebrae immediately above and below the fractured level, increasing the risk of adjacent fractures; height restoration reduces this.</li>
              <li><strong>Thoracic and abdominal capacity improves:</strong> Lung and abdominal function may improve in patients with severe thoracic kyphosis, for whom the deformity was compressing the thoracic cavity.</li>
            </ul>
            <p>In subacute or chronic fractures, the fractured bone has begun to heal in its collapsed position and height restoration becomes progressively less achievable. This is why early intervention — in the acute phase of pain — offers the best combination of pain relief and height restoration.</p>
