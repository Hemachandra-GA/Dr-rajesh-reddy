            <h2 class="pillar-section-title">What Is Endovascular Coiling?</h2>

            <p>
              Endovascular coiling — formally called Guglielmi Detachable Coil (GDC) embolisation,
              after its inventor Dr. Guido Guglielmi — is a minimally invasive procedure that treats
              brain aneurysms by filling the aneurysm sac with soft platinum coils from within the
              bloodstream. The coils disrupt blood flow inside the aneurysm, promoting clot formation
              that progressively seals it from the parent artery circulation.
            </p>

            <p>
             The procedure is performed in a specialised neurointerventional suite — a hybrid operating and imaging room equipped with biplane digital subtraction angiography (DSA), advanced 3D imaging, and fluoroscopic guidance. The entire procedure is performed through a small puncture in the femoral artery in the groin — the same access point used for a cardiac catheterisation. There is no incision in the scalp, no removal of skull bone, and no manipulation of brain tissue.
            </p>

            <div style="background-color: #f8fbff; border-left: 4px solid #0066cc; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              <strong>Key principle:</strong>Endovascular coiling is not 'less effective' than open surgery — it is a different route to the same destination: permanent exclusion of the aneurysm from the circulation. For the majority of saccular aneurysms, it achieves equivalent or better outcomes than open surgery with substantially lower procedural burden.
            </div>

