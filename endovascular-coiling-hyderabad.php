            <h2 class="pillar-section-title">Introduction</h2>

            <p>
Brain aneurysm surgery once meant one thing: open skull surgery, a craniotomy under general anaesthesia, careful dissection to the base of the brain, and application of a titanium clip across the aneurysm neck. That open approach remains important and effective for specific aneurysm types — but for the majority of brain aneurysms encountered in clinical practice today, a fundamentally different route exists. Endovascular coiling reaches the aneurysm from inside the bloodstream — through a small puncture in the groin — without a single incision in the scalp, without removing any bone, and without touching the brain itself.
            </p>

            <p>
           Endovascular coiling has transformed the treatment of brain aneurysms. For patients with ruptured aneurysms causing subarachnoid haemorrhage, the landmark ISAT trial demonstrated that coiling produces significantly better neurological outcomes than clipping for aneurysms suitable for both techniques. For patients with incidentally discovered unruptured aneurysms, coiling offers definitive treatment with a hospital stay of 1–3 days and return to normal activity within 1–2 weeks.
            </p>

