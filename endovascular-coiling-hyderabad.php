          <section id="risks" class="pillar-section">
            <h2 class="pillar-section-title">Risks of Endovascular Coiling: An Honest Assessment</h2>

            <p>
            Endovascular coiling is a safe procedure when performed in expert hands, with complication rates that compare favourably to open surgical alternatives. Patients deserve a clear and honest understanding of the specific risks involved.
            </p>

            <h3>Thromboembolic Complications</h3>
            <p>
            The most common serious complication of endovascular coiling is thrombus (clot) formation on the coils or catheters, which can embolise to distal cerebral arteries causing ischaemic stroke. The risk is approximately 3–5% overall, with the majority being minor or clinically silent. Heparin anticoagulation during the procedure significantly reduces this risk. For procedures requiring stents, pre-procedural dual antiplatelet therapy is the primary preventive measure.
            </p>

            <h3>Aneurysm Perforation</h3>
            <p>
             Perforation of the aneurysm wall during coil delivery — caused by the guidewire or coil perforating the thin aneurysm dome — can cause intraprocedural haemorrhage. The risk is approximately 1–2%. If perforation occurs, the immediate management is to rapidly complete coiling to seal the perforation from within, while simultaneously managing the rise in intracranial pressure. An experienced operator can manage most perforations without catastrophic outcome.
            </p>

            <h3>Coil Herniation</h3>
            <p>
             A coil loop prolapsing into the parent artery during delivery can cause thrombosis or distal embolisation. This is managed by retrieving the offending coil with a micrograsper, repositioning, or — if deployed — inflating a balloon to push it back into the sac or deploying a stent across the neck. Balloon and stent-assisted techniques specifically address this risk for wide-neck aneurysms.
            </p>

            <h3>Groin Haematoma</h3>
            <p>
             A haematoma at the femoral access site occurs in approximately 2–5% of cases, usually resolving with compression and bed rest. Rarely, it requires surgical drainage. Vascular closure devices have significantly reduced this complication compared to manual compression alone.
            </p>

            <h3>Recanalisation</h3>
            <p>
            As discussed above, approximately 15–20% of coiled aneurysms show recanalisation at 5 years — requiring surveillance imaging and possible retreatment. This is not a complication of the initial procedure but a known limitation of coiling biology that mandates long-term follow-up.
            </p>
            
              <div style="background-color: #f8fbff; border-left: 4px solid #0066cc; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              Overall, the risk of a permanent major neurological complication from elective endovascular coiling of an unruptured aneurysm is approximately 1–3% in experienced centres — significantly lower than the equivalent risk of open surgical clipping for the same aneurysm. For ruptured aneurysms, the risk of the procedure must be weighed against the near-certain catastrophe of rebleeding without treatment.
              </div>
          </section>

