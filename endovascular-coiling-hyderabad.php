          <section id="follow-up" class="pillar-section">
            <h2 class="pillar-section-title">Follow-Up After Coiling: Why Surveillance Is Non-Negotiable</h2>

            <p>
              Unlike surgical clipping — where a correctly placed clip provides an immediately verifiable, durable mechanical seal — coiling depends on progressive thrombosis of the aneurysm sac. The coil mass can compact over time, potentially allowing recanalisation. Follow-up imaging is therefore mandatory, not optional.
            </p>

            <h3>6-Month DSA, MRA or CTA:</h3>
            <p>
             The first post-procedure surveillance imaging. Confirms whether complete occlusion has been maintained or whether recanalisation has occurred. DSA remains the gold standard; high-resolution MRA at 3T or CTA is an acceptable alternative for stable, small aneurysms.
            </p>

            <h3>18-Month DSA, MRA or CTA:</h3>
            <p>
              Second surveillance. The majority of clinically significant recanalisation occurs within the first 18 months. A stable result at 18 months significantly reduces the probability of late recanalisation.
            </p>

            <h3>Annual MRA or CTA thereafter:</h3>
            <p>
             For coiled aneurysms that are stable at 18 months, annual or biennial MRA surveillance is recommended indefinitely — particularly for large aneurysms, those treated with stent assistance, and younger patients who have many decades of follow-up ahead.
            </p>
 <div style="background-color: #f8fbff; border-left: 4px solid #0066cc; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
             If follow-up imaging shows recanalisation or a neck remnant that is growing, retreatment with further coiling, flow diversion, or — in selected cases — surgical clipping is recommended before the aneurysm returns to its pre-treatment configuration. Early retreatment of a recanalised aneurysm is a low-risk, elective procedure. Waiting until rebleeding occurs is not an option.
             </div>
           
          </section>

