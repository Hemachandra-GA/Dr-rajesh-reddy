            <h3>Balloon-Assisted Coiling (BAC) — The Remodelling Technique</h3>
            <p>
             BAC uses a compliant balloon catheter positioned across the aneurysm neck alongside the microcatheter. During coil delivery, the balloon is briefly inflated to cover the neck — preventing coils from prolapsing into the parent artery. Between coils, the balloon is deflated to restore blood flow. This technique allows tighter packing of wide-neck aneurysms without the need for a permanent stent implant and without requiring dual antiplatelet therapy.
            </p>

            <h3>Stent-Assisted Coiling (SAC)</h3>
            <p>
            When balloon assistance is insufficient, a low-profile braided or laser-cut microstent is deployed across the aneurysm neck before coiling. The stent provides a permanent scaffold — its struts prevent coil herniation into the parent artery and alter the haemodynamic environment at the aneurysm neck, promoting progressive thrombosis. The stent remains permanently in the parent artery. Dual antiplatelet therapy (aspirin + clopidogrel or Ticagrelor) is required for 3–6 months to prevent stent thrombosis, after which aspirin alone is continued indefinitely.
            </p>

            <h3>The WEB Device — Intrasaccular Flow Disruption</h3>
            <p>
             The WEB (Woven Endo Bridge) device is a self-expanding nitinol mesh sphere deployed entirely within the aneurysm sac through a single microcatheter. Unlike stent-assisted coiling — where the stent is deployed in the parent artery — the WEB sits completely within the aneurysm and requires no stent in the circulation. This eliminates the need for clopidogrel; aspirin alone is sufficient. The WEB is particularly well-suited to wide-neck bifurcation aneurysms at the MCA trifurcation, basilar tip, and anterior communicating artery — locations where stent placement would require multiple stents or complex navigation. Contour, Artisse, Seal are the other Intrasaccular flow disrupters.
            </p>

