            <h2 class="pillar-section-title">The Endovascular Coiling Procedure: Step by Step</h2>

            <figure style="margin: 28px 0; text-align: center;">
              <img
                src="images/Endovascular coiling/the_coiliing_procedure.webp"
                alt="The Endovascular Coiling Procedure Step by Step"
                style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
