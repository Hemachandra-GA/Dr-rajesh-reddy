            <h3>Step 1: Pre-Procedure Preparation</h3>
            <p>
            Before the procedure, patients undergo a dedicated Digital Subtraction Angiography (DSA) with 3D rotational imaging to precisely characterise the aneurysm — its exact size, neck width, dome shape, relationship to parent and branch arteries, and the optimal working projection for treatment. This roadmap is essential for safe and complete coil delivery.
            </p>

            <p>
            For elective (unruptured) aneurysm coiling, patients requiring stent-assisted coiling or flow diversion are pre-loaded with dual antiplatelet therapy (aspirin 150 mg plus clopidogrel 75 mg or Ticagrelor 180 mg/day) for 5–7 days before the procedure to prevent stent thrombosis. For emergency SAH cases, antiplatelet therapy is initiated on the day of procedure if stent assisted coiling or Flow diversion therapy is preferred over microsurgical clipping.
            </p>

            <h3>Step 2: Femoral Access and Guide Catheter Placement</h3>
            <p>
             Under general anaesthesia, the right (or occasionally left) femoral artery is accessed via a small puncture using a modified Seldinger technique. A short introducer sheath (typically 6 French, approximately 2 mm diameter) is placed in the femoral artery. A guide catheter — a flexible tube approximately 2 mm in outer diameter — is then navigated under fluoroscopic guidance from the femoral artery, through the iliac arteries and aorta, and into the internal carotid or vertebral artery supplying the aneurysm. This process takes 10–20 minutes in experienced hands.
            </p>

            <h3>Step 3: Microcatheter Navigation into the Aneurysm</h3>
            <p>
            Through the guide catheter, a microcatheter — a highly flexible, steerable tube approximately 1.5 mm in outer diameter — is navigated using a microwire guide into the target aneurysm sac. This requires precise, real-time fluoroscopic guidance and is the most technically demanding part of the procedure. The microcatheter tip must be positioned optimally within the aneurysm sac — not too deep (risking perforation) and not too shallow (risking coil herniation into the parent artery). Correct positioning is confirmed under fluoroscopic road map guidance.
            </p>

            <h3>Step 4: Coil Delivery and Packing</h3>
            <p>
              With the microcatheter in position, platinum coils are delivered one by one into the
              aneurysm sac. Each coil is detachable and is released only after confirming that it is
              correctly positioned and not herniated into the parent artery. If positioning is
              unsatisfactory, the coil can be retrieved and repositioned before detachment.
            </p>

            <p>
              The first coil, called the <strong>framing coil</strong>, is the largest — it forms a basket within the aneurysm, conforming to its shape and defining the working space. Subsequent coils (filling and finishing coils) are progressively smaller and softer, packing the interior of the basket until no further coils can be introduced safely. The goal is maximum packing density — typically > 25–30% of the aneurysm volume — to minimise recanalisation risk.
            </p>

            <h3>Step 5: Final Angiogram and Closure</h3>
            <p>
           After coiling is complete, a final DSA run confirms the degree of aneurysm occlusion, patency of the parent artery, and absence of thromboembolic complications. Occlusion is classified using the Raymond-Roy scale: complete occlusion (no contrast entering the sac), neck remnant (coils at the neck level with no dome filling), or residual aneurysm (contrast entering the dome). The aim is always complete or near-complete occlusion.
            </p>

            <p>
           The femoral access site is closed using a vascular closure device or manual compression. The patient wakes from anaesthesia and is transferred to the neurosurgical ward or ICU depending on clinical status. The groin puncture site requires pressure dressing and 4–6 hours of bed rest to prevent haematoma.
            </p>
          </section>

