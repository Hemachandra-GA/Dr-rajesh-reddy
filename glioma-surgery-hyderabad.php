            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">What Is a Glioma?</h3>

            <p>Gliomas are primary brain tumors — tumors that arise from within the brain itself rather than spreading from elsewhere in the body. They originate from glial cells, which are the brain's non-neuronal supportive cells. Glial cells provide structural support, nourishment, and insulation to neurons, and include several subtypes: astrocytes, oligodendrocytes, and ependymal cells. Tumors arising from each of these cell types carry different names, behaviours, and prognoses.</p>

            <p>Gliomas account for approximately 80% of all malignant primary brain tumors and are among the most challenging tumors in all of oncology — not because surgery cannot remove them, but because their tendency to infiltrate surrounding normal brain tissue means that complete eradication is rarely possible. The goal of glioma surgery is <strong>maximum safe resection</strong> — removing as much tumor as possible while preserving the neurological function that determines a patient's quality of life.</p>

          
