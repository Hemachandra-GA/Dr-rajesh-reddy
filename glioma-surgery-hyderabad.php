            <h2 class="pillar-section-title">Recovery After Glioma Surgery</h2>

            <p>Recovery after glioma surgery varies depending on the tumor grade, location, extent of resection, and any post-operative neurological changes. Here is what patients can typically expect:</p>



            <h3>Immediate Post-Operative Period (Days 1–5)</h3>

            <ul>

              <li>Monitoring in a dedicated neurosurgical ICU for the first 24–48 hours</li>

              <li>Neurological assessment every few hours to detect and respond to any early complications</li>

              <li>Steroids (dexamethasone) to control brain swelling — typically tapered over 1–2 weeks</li>

              <li>Anti-seizure medication continued or initiated as appropriate</li>

              <li>Early mobilisation — most patients are sitting up within 24 hours and walking within 48 hours</li>

            </ul>



            <h3>Weeks 2–6</h3>

            <ul>

              <li>Return home typically after 5–7 days for uncomplicated cases</li>

              <li>Fatigue is the most common complaint — rest is important but progressive activity is encouraged</li>

              <li>Wound healing monitored; sutures or staples removed at 10–14 days</li>

              <li>Post-operative contrast MRI performed at 24–72 hours and again at 3–4 weeks to assess resection extent and plan adjuvant treatment — earlier re-imaging is essential for gliomas as treatment planning cannot be delayed</li>

              <li>Oncology referral and treatment planning meeting initiated during this period for malignant gliomas</li>

            </ul>



            <h3>3 Months and Beyond</h3>

            <ul>

              <li>Malignant glioma patients continue with radiation and chemotherapy; regular MRI every 2–3 months</li>

              <li>Low-grade glioma patients typically return to normal activities within 6–8 weeks</li>

              <li>Neuropsychological rehabilitation if cognitive or language deficits persist</li>

              <li>Seizure management reviewed and anti-epileptic medications adjusted based on post-operative seizure control</li>

            </ul>

          
