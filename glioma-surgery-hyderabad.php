            <h2 class="pillar-section-title">Diagnosing a Glioma: The Workup Before Surgery</h2>

            <p>Before surgery is recommended, Dr. Rajesh Reddy conducts a thorough pre-operative evaluation to characterise the tumor precisely and plan the safest, most effective surgical approach.</p>



            <h3>MRI Brain with Contrast — The Essential First Step</h3>

            <p>MRI is the gold standard for glioma diagnosis and surgical planning. Gliomas have characteristic MRI appearances: low-grade gliomas typically appear as non-enhancing lesions with T2/FLAIR signal change, while high-grade gliomas show ring-like contrast enhancement around a necrotic core. The MRI defines the tumor's size, location, relationship to eloquent brain areas, and degree of surrounding oedema (swelling).</p>



            <h3>Functional MRI (fMRI)</h3>

            <p>For gliomas near language or motor areas, functional MRI maps the precise location of these eloquent regions relative to the tumor. This information is essential for planning whether an awake craniotomy is needed and for defining safe surgical corridors. fMRI data is loaded into the neuronavigation system and used in real time during surgery.</p>



            <h3>Diffusion Tensor Imaging (DTI) and Tractography</h3>

            <p>DTI maps the brain's white matter fibre tracts — including the corticospinal tract (motor), arcuate fasciculus (language), and optic radiations (vision). By overlaying DTI tractography on the surgical plan, Dr. Rajesh Reddy identifies which critical pathways run through or adjacent to the glioma, and plans resection boundaries accordingly. This is a key component of connectomics-informed surgical planning — protecting not just individual eloquent areas but the networks that connect them.</p>



            <h3>MR Spectroscopy</h3>

            <p>MR spectroscopy analyses the biochemical profile of the tumor and surrounding tissue. It helps differentiate high-grade from low-grade gliomas, identify the most metabolically active (and therefore most malignant) region of the tumor to target for biopsy, and distinguish tumor recurrence from radiation-induced changes after treatment.</p>



            <h3>Stereotactic Biopsy</h3>

            <p>When a glioma is located in a region that does not permit safe resection — such as the thalamus, basal ganglia, or dominant hemisphere language areas where the risk-benefit of surgery is unfavourable — a stereotactic biopsy is performed. Using 3D image guidance, a small needle is introduced through a burr hole to obtain a tissue sample for histopathological and molecular analysis. This is a minimally invasive procedure performed under local anaesthesia with sedation in most cases.</p>

