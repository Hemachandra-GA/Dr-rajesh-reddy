              <div class="pillar-faq-q">

                <span>Q5: My glioma is in the speech area — can it still be operated on?</span>

                <i class="fa-solid fa-chevron-down"></i>

              </div>

              <div class="pillar-faq-a">

                <div class="pillar-faq-a-content">

                  Yes, in many cases. Tumors near or within the speech areas of the brain are among the most challenging but also among the most common indications for awake craniotomy. Dr. Rajesh Reddy uses direct cortical and subcortical stimulation mapping during the awake phase to identify the exact boundaries of functional speech tissue and resect the tumor right up to — but not beyond — those boundaries. Many patients with tumors in speech areas undergo awake craniotomy successfully, with preservation of language function and significant tumor removal.

                </div>

              </div>

            </div>



            <div class="pillar-faq-item">

              <div class="pillar-faq-q">

                <span>Q6: How soon after glioma surgery does radiation and chemotherapy start?</span>

                <i class="fa-solid fa-chevron-down"></i>

              </div>

              <div class="pillar-faq-a">

                <div class="pillar-faq-a-content">

                  For GBM and high-grade gliomas, radiation and chemotherapy (the Stupp protocol) typically begin 4–6 weeks after surgery — once the surgical wound has healed and the patient has recovered sufficiently to tolerate treatment. This window is used for tumour board planning, oncology consultation, and radiation planning (simulation). Starting treatment promptly after surgery is important for GBM, as the tumor typically begins regrowing during this interval.

