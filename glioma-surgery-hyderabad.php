            <h2 class="pillar-section-title">Frequently Asked Questions</h2>



            <div class="pillar-faq-item">

              <div class="pillar-faq-q">

                <span>Q1: Can a glioma be completely removed with surgery?</span>

                <i class="fa-solid fa-chevron-down"></i>

              </div>

              <div class="pillar-faq-a">

                <div class="pillar-faq-a-content">

                  For most gliomas — particularly high-grade gliomas like GBM — complete removal of all tumor cells is not surgically achievable, because glioma cells infiltrate surrounding normal brain tissue at the microscopic level beyond what imaging shows. The goal of surgery is maximum safe resection: removing as much tumor as can be done safely while preserving neurological function. For Grade I gliomas (pilocytic astrocytoma), complete surgical resection is often curative. For diffuse gliomas (Grade II–IV), surgery is followed by radiation and/or chemotherapy to manage the residual disease.

                </div>

              </div>

            </div>



            <div class="pillar-faq-item">

              <div class="pillar-faq-q">

                <span>Q2: What is the difference between a low-grade and high-grade glioma in terms of surgery?</span>

                <i class="fa-solid fa-chevron-down"></i>

              </div>

              <div class="pillar-faq-a">

                <div class="pillar-faq-a-content">

                  The surgical approach is broadly similar — craniotomy with neuronavigation and intraoperative monitoring — but the technology employed and the post-operative plan differ. For high-grade gliomas (Grade III–IV), fluorescence guidance (5-ALA / Sodium Fluorescein) is used to maximise resection of contrast-enhancing tumor, and the post-operative plan includes prompt radiation and chemotherapy. For low-grade gliomas, the emphasis is on maximum safe resection while preserving function, with adjuvant treatment reserved for high-risk cases. Awake craniotomy is more commonly needed for low-grade gliomas, which often occur in younger adults with tumors near eloquent areas.

                </div>

              </div>

            </div>



            <div class="pillar-faq-item">

              <div class="pillar-faq-q">

                <span>Q3: Is awake craniotomy safe? Will I feel pain during surgery?</span>

                <i class="fa-solid fa-chevron-down"></i>

              </div>

              <div class="pillar-faq-a">

                <div class="pillar-faq-a-content">

                  Awake craniotomy is a well-established, safe technique when performed by an experienced team. The brain itself has no pain receptors — so once the scalp and skull work is done under anaesthesia/sedation, the patient does not feel pain during the tumor resection phase. The scalp is thoroughly numbed with local anaesthetic. Most patients describe the experience as strange but manageable. Detailed pre-operative preparation and psychological counselling are provided to every patient before an awake craniotomy is performed.

                </div>

              </div>

            </div>



            <div class="pillar-faq-item">

              <div class="pillar-faq-q">

                <span>Q4: What does the 5-ALA and sodium fluorescein do? Are there side effects?</span>

                <i class="fa-solid fa-chevron-down"></i>

              </div>

              <div class="pillar-faq-a">

                <div class="pillar-faq-a-content">

                  5-ALA is an oral medicine taken before surgery that makes certain brain tumors glow under a special microscope, helping the surgeon remove the tumor more accurately. Sodium fluorescein is a dye given through a vein during surgery that also helps highlight tumor tissue. Both are generally safe. Side effects are usually mild and temporary. 5-ALA may cause mild nausea and temporary sensitivity to sunlight for about 24 hours. Sodium fluorescein may temporarily turn the skin and urine yellow and, rarely, can cause an allergic reaction.

                </div>

              </div>

            </div>



