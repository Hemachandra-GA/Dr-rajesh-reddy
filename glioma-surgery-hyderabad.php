            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Maximum Safe Resection: Why Extent of Resection Matters</h3>

            <p>The extent of resection (EOR) in glioma surgery is one of the most important determinants of outcomes — both survival and quality of life. For GBM, studies consistently show that gross total resection (complete removal of all contrast-enhancing tumor) is associated with longer overall survival and longer time to recurrence compared to subtotal resection.</p>

            <p>For low-grade gliomas, increasing EOR reduces the risk of malignant transformation and improves seizure control — even when the tumor is not immediately life-threatening. The challenge is achieving maximum EOR without causing permanent neurological deficits that would impair the patient's quality of life — which is precisely where the combination of awake craniotomy, neuronavigation, fluorescence guidance, and intraoperative monitoring becomes decisive.</p>



            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Awake Craniotomy for Gliomas in Eloquent Areas</h3>

            <p>When a glioma involves or is adjacent to the motor cortex, Broca's area (speech production), Wernicke's area (speech comprehension), or primary sensory cortex, awake craniotomy is the surgical technique of choice. The patient is kept awake and interactive during the tumor resection phase while the surgical team monitors neurological function in real time.</p>

            <p>Dr. Rajesh Reddy uses direct cortical and subcortical stimulation mapping during awake craniotomy to identify the precise boundaries of functional tissue. As resection proceeds, the patient is asked to speak, move their limbs, name objects, or count — depending on which functions are at risk. If stimulation at a particular point causes a temporary speech arrest or motor twitch, that point is marked and avoided. This technique allows glioma resection right up to the boundary of eloquent cortex without crossing it.</p>



            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">5-ALA and Sodium Fluorescein: Seeing Glioma Cells in Real Time</h3>

            <p>5-ALA (5-aminolevulinic acid) is an oral agent taken by the patient 3–4 hours before surgery. It is selectively metabolised by high-grade glioma cells into a fluorescent compound (protoporphyrin IX) that glows pink-red under violet-blue light in the operating microscope. Normal brain tissue does not fluoresce. This visual contrast allows the surgeon to identify and remove glioma tissue that would be invisible under standard white-light illumination — significantly improving the completeness of GBM resection.</p>

            <p><strong>Sodium Fluorescein — More Commonly Used in India:</strong> Sodium Fluorescein is an intravenous dye injected at the time of surgery that accumulates in areas of blood-brain barrier disruption — where high-grade glioma is present. Under a specific yellow-fluorescence filter (the YELLOW 560 filter) in the operating microscope, the glioma tissue glows bright yellow against the non-fluorescing normal brain tissue, allowing precise real-time identification of tumor margins during resection. Sodium Fluorescein is more commonly used than 5-ALA in India due to its wider availability, lower cost, and ease of administration — and is the primary fluorescence agent used by Dr. Rajesh Reddy in high-grade glioma surgery. Both agents can be used depending on the tumor and clinical context.</p>



            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Connectomics and Surgical Planning</h3>

            <p>Connectomics maps the brain's neural networks — not just where individual functional areas are located, but how they communicate through white matter pathways. By integrating connectomic data with pre-surgical fMRI and DTI, Dr. Rajesh Reddy plans surgical approaches that protect critical neural network connections alongside maximising tumor removal, giving patients the best chance of preserving complex cognitive and motor abilities after glioma surgery.</p>



            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Stereotactic Biopsy and Frameless Stereotaxy</h3>

            <p>When a glioma is located in a region that does not permit safe resection — such as the thalamus, basal ganglia, brainstem, or dominant hemisphere language areas where the risk-benefit of open surgery is unfavourable — a stereotactic biopsy is performed to obtain a tissue sample for histopathological and molecular diagnosis. This is a minimally invasive procedure performed under local anaesthesia with sedation.</p>

            <p><strong>Frameless Stereotaxy:</strong> Unlike traditional frame-based stereotactic biopsy — which requires a rigid metal frame bolted to the patient's skull — frameless stereotaxy uses neuronavigation (a surface-registration-based 3D GPS system) to guide the biopsy needle to the precise target within the brain without any frame. The patient's pre-operative MRI is loaded into the neuronavigation system and registered to the patient's head position in the operating room using surface landmarks or fiducial markers. The surgeon then uses a tracked biopsy needle holder to navigate to the target in real time, with the neuronavigation screen confirming instrument position at every step. Frameless stereotaxy is more patient-friendly, faster to set up, and allows the surgeon to adjust the biopsy trajectory intraoperatively if needed — making it the preferred approach in experienced centres.</p>

          
