            <h2 class="pillar-section-title">How Are Gliomas Classified?</h2>

            <p>Gliomas are classified by the World Health Organisation (WHO) according to two parameters: cell type of origin and grade (I–IV). The 2021 WHO update added molecular markers — particularly IDH mutation status — as a mandatory part of glioma classification, because molecular profile predicts behaviour and treatment response more accurately than histology alone.</p>

            <ul>

              <li><strong>IDH-mutant gliomas</strong> — grow more slowly, respond better to chemotherapy, and are associated with better survival. Found predominantly in younger adults.</li>

              <li><strong>IDH-wildtype gliomas</strong> — more aggressive, less chemosensitive, and associated with shorter survival even at lower histological grades. GBM is almost always IDH-wildtype.</li>

              <li><strong>1p/19q codeletion</strong> — a molecular hallmark of oligodendrogliomas, associated with the best prognosis among diffuse gliomas and high sensitivity to PCV chemotherapy.</li>

              <li><strong>MGMT promoter methylation</strong> — predicts response to temozolomide chemotherapy in GBM. Methylated tumors respond significantly better to alkylating chemotherapy.</li>

            </ul>



