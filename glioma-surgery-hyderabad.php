            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">The Stupp Protocol for GBM</h3>

            <p>The standard of care for newly diagnosed GBM following maximum safe resection is the Stupp protocol: 6 weeks of concurrent radiotherapy (60 Gy in 30 fractions) with daily oral temozolomide chemotherapy, followed by 6 cycles of adjuvant temozolomide. In patients with MGMT promoter methylation, response rates are significantly better, and some patients achieve long-term disease control well beyond the median survival figures.</p>



            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Tumour Treating Fields (TTFields)</h3>

            <p>TTFields (Optune device) use alternating electric fields delivered via scalp electrodes to disrupt glioma cell division. They are used concurrently with adjuvant temozolomide in GBM and have been shown in Phase III trials to improve both progression-free and overall survival when added to standard chemotherapy. The decision to use TTFields is made in the tumour board meeting by Dr. Rajesh Reddy alongside radiation and medical oncology specialists.</p>



            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">Treatment of Recurrent Glioma</h3>

            <p>Gliomas — particularly GBM — almost invariably recur despite optimal primary treatment. Options at recurrence include re-operation (if the tumor is resectable and the patient's condition allows), repeat stereotactic radiosurgery, bevacizumab (anti-angiogenic therapy), clinical trial enrolment, and best supportive care. Each decision is made individually in a tumour board setting, weighing expected benefit against treatment burden and the patient's wishes.</p>

          
