          <!-- Endovascular Coiling in Depth Section -->
          <section id="coiling-in-depth" class="pillar-section">
            <h2 class="pillar-section-title">Endovascular Coiling in Depth</h2>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/aneurysm-coiling-vs-clipping/endovascular_coiling.webp" alt="Endovascular Coiling Procedure" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>The Basic Technique</h3>
            <p>Under general anaesthesia, a guide catheter is placed in the internal carotid or vertebral artery through a femoral puncture. A microcatheter — a flexible, steerable tube approximately 1.5 mm in diameter — is then navigated into the aneurysm sac under biplane fluoroscopic guidance. Soft platinum coils are detached one by one into the sac, each chosen for its size and shape to match the aneurysm's dimensions. The first coil (the 'framing coil') forms a basket within the aneurysm; subsequent coils ('filling coils' and 'finishing coils') progressively pack the sac until no further coils can be introduced without herniation into the parent artery.</p>

            <h3>Advanced Coiling Techniques</h3>
            <ul>
              <li><strong>Balloon-assisted coiling:</strong> A remodelling balloon is temporarily inflated across the aneurysm neck during coil delivery — preventing coil herniation into the parent artery and allowing tighter packing of wide-neck aneurysms. The balloon is deflated after each coil and removed at the end of the procedure.</li>
              <li><strong>Stent-assisted coiling:</strong> A flexible stent [laser cut or braided] is deployed across the aneurysm neck before coiling, providing a scaffold that keeps coils within the sac. Particularly useful for wide-neck aneurysms. Requires dual antiplatelet therapy (aspirin + clopidogrel) for 3–6 months to prevent stent thrombosis.</li>
              <li><strong>Intrasaccular device (WEB, Contour, Artisse, Seal):</strong> A nitinol mesh sphere deployed entirely within the aneurysm sac — disrupting inflow without requiring a stent or dual antiplatelet therapy. Particularly suited to wide-neck bifurcation aneurysms at the MCA, basilar tip, and AComm. A single-session outpatient-equivalent procedure.</li>
            </ul>

            <h3>Recanalisation — The Main Limitation of Coiling</h3>
            <p>The most significant limitation of endovascular coiling is recanalisation — where the coil mass compacts over time as the aneurysm remodels, allowing blood to re-enter the sac. This occurs in approximately 15–20% of coiled aneurysms at 5 years and is more common in larger aneurysms, wide-neck aneurysms, and those with incomplete initial occlusion. Recanalisation does not always mean rebleeding — most recanalised aneurysms can be retreated with further coiling or flow diversion — but it does mean that mandatory follow-up angiography (DSA, CTA or MRA at 6 months and 18 months) is non-negotiable after coiling.</p>
          </section>

          <!-- Microsurgical Clipping in Depth Section -->
          <section id="clipping-in-depth" class="pillar-section">
            <h2 class="pillar-section-title">Microsurgical Clipping in Depth</h2>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/aneurysm-coiling-vs-clipping/surgical_Clipping.webp" alt="Microsurgical Aneurysm Clipping Anatomy" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>The Pterional Craniotomy — The Workhorse Approach</h3>
            <p>The vast majority of anterior circulation aneurysms — at the MCA, ICA, AComm, and PComm — are approached through a pterional craniotomy: a frontotemporal craniotomy that opens the Sylvian fissure, exposing the Circle of Willis at the skull base. This is the most commonly performed craniotomy in cerebrovascular surgery and provides excellent exposure to the majority of saccular aneurysms encountered in clinical practice.</p>
            <p>The surgeon dissects the Sylvian fissure under microscope — separating the frontal and temporal lobes along a natural anatomical plane without retracting brain tissue — until the aneurysm, its neck, and the parent and branch arteries are fully visualised. Only then is the clip applied.</p>

            <h3>Clip Selection and Application</h3>
            <p>Titanium clips are available in dozens of shapes and sizes — straight, curved, fenestrated, bayonet, right-angle, miniature — each designed for specific anatomical situations. The surgeon trials one or more clips before final application, checking under the microscope that the clip spans the entire neck without incorporating any adjacent arteries or perforating vessels.</p>
            <p>Intraoperative ICG fluorescence angiography is then performed: indocyanine green dye injected intravenously fluoresces under infrared light in the microscope, showing real-time blood flow through all vessels. A correctly placed clip shows no flow in the aneurysm sac (confirming occlusion) and unobstructed flow through all parent and branch arteries (confirming preservation). This step dramatically reduces the risk of inadvertent vessel compromise or incomplete clipping before wound closure.</p>

            <h3>Temporary Clipping — Managing Intraoperative Rupture</h3>
            <p>In complex aneurysms, the surgeon may apply a temporary clip to the parent artery before clipping the aneurysm — momentarily stopping flow to the aneurysm to reduce wall tension and make the final clip application safer. Temporary clips are removed within minutes of aneurysm clipping; the brain tolerates short periods (typically &lt; 10 minutes) of temporary occlusion with minimal risk when performed under neuroprotective anaesthesia conditions.</p>

            <h3>Why Clipping Is More Durable</h3>
            <p>The titanium clip, once placed correctly, creates an immediate, mechanical, permanent seal of the aneurysm neck that does not depend on the body's clotting mechanism. Unlike coil masses — which can compact and recanalize over years — a well-placed clip does not change over time. The 10-year retreatment rate after surgical clipping for completely clipped aneurysms is below 2%, compared to 15–20% after coiling. For young patients who will live for decades after treatment, this durability is a significant advantage.</p>
          </section>

          <!-- Flow Diversion Section -->
          <section id="flow-diversion" class="pillar-section">
            <h2 class="pillar-section-title">When Neither Coiling Nor Clipping Is the Answer: Flow Diversion</h2>
            <p>For a subset of aneurysms — large and giant aneurysms, fusiform aneurysms, wide-neck aneurysms where coiling has failed, and paraclinoid ICA aneurysms — neither conventional coiling nor surgical clipping provides the safest or most effective treatment. Flow diversion devices — principally the Pipeline Embolisation Device (PED), SILK, Surpass, Derivo, P64 and the FRED (Flow Re-Direction Endoluminal Device) — have transformed outcomes for this challenging group.</p>
            <p>A flow diverter is a dense mesh stent deployed across the aneurysm neck within the parent artery. It redirects blood flow away from the aneurysm sac, causing progressive thrombosis over weeks to months, while simultaneously scaffolding the parent artery and forming a new smooth arterial wall that permanently excludes the aneurysm. Complete occlusion rates of 85–93% at 12 months make flow diversion the most effective treatment for complex aneurysms that cannot be reliably treated by coiling or clipping alone.</p>
            <p>Flow diversion is not a substitute for coiling or clipping in straightforward aneurysms — it is a specialised tool for cases that would previously have been untreatable or required complex bypass surgery. Dr Rajesh Reddy’s exposure to complex cerebrovascular procedures at University Hospital, Zurich, Barrow Neurological Institute, Phoenix and University Hospital, Okayama in addition to training at high volume centres in Hyderabad provides the necessary knowledge, skill, judgement and precision in helping choose between microsurgical clipping, endovascular coiling, or, clinicoradiological follow, in selected cases.</p>
          </section>

