          <section id="anatomy" class="pillar-section">
            <h2>The Cervical Spine: A Brief Anatomy</h2>
            <p>Understanding cervical fracture management requires a basic grasp of cervical anatomy. The cervical spine has two anatomically and functionally distinct regions:</p>
            
            <h3>Upper Cervical Spine (Occiput–C1–C2)</h3>
            <p>The craniocervical junction and the first two cervical vertebrae — the atlas (C1) and axis (C2) — form a unique functional unit that provides the majority of cervical rotation (C1–C2, approximately 50°) and flexion-extension (occiput–C1, approximately 25°). The atlas is a ring without a vertebral body; the axis has the odontoid process (dens) projecting upward into the ring of the atlas, held in place by the transverse ligament. Instability at this junction — from fracture, ligamentous injury, or congenital anomaly — risks compression of the upper cervical cord and brainstem.</p>
            
            <h3>Subaxial Cervical Spine (C3–C7)</h3>
            <p>C3 through C7 have conventional vertebral bodies, discs, facet joints, and posterior elements. The subaxial cervical canal is narrower than the upper cervical region, and the cord is more vulnerable to compression from displaced bone or disc material. The brachial plexus nerve roots — which supply the arms — exit at C5–T1, so subaxial injuries commonly cause arm weakness and radiculopathy in addition to or instead of cord injury.</p>
          </section>

