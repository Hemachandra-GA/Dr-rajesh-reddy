          <section id="upper-cervical" class="pillar-section">
            <h2>Upper Cervical Injuries: C1 and C2</h2>

            <h3>Jefferson Fracture (C1 Burst Fracture)</h3>
            <p>A Jefferson fracture results from an axial load on the top of the head — classically from diving into shallow water or a fall onto the crown. The ring of C1 bursts outward at its weakest points, typically in 2–4 places. On an open-mouth odontoid X-ray, the lateral masses of C1 are seen overhanging the superior articular surface of C2 (the 'rule of Spence'). The critical determinant of stability and neurological risk is the integrity of the transverse atlantal ligament — which holds the dens against the anterior arch of C1.</p>
            <ul class="pillar-list">
              <li><strong>Transverse ligament intact:</strong> The fracture is relatively stable. A halo vest for 8–12 weeks allows healing in the majority of cases with good outcome. Neurological deficit is uncommon.</li>
              <li><strong>Transverse ligament torn (atlantoaxial instability):</strong> The fracture is highly unstable. The dens can migrate posteriorly and compress the upper cervical cord or medulla. Posterior C1–C2 fusion is required to stabilise the craniocervical junction.</li>
            </ul>

            <h3>Odontoid Fractures (C2 Dens Fractures)</h3>
            <p>Odontoid fractures are among the most common cervical fractures in the elderly — often from a low-energy fall in a patient with osteoporosis. They are classified by Anderson and D'Alonzo into three types:</p>
            <ul class="pillar-list">
              <li><strong>Type I:</strong> Fracture of the tip of the dens — stable; treated with a rigid collar.</li>
              <li><strong>Type II:</strong> Fracture at the base of the dens — the most common and most challenging type. High non-union rate with conservative treatment (up to 60–70% in displaced fractures). Surgical treatment is generally preferred: odontoid screw fixation (anterior approach, preserves rotation) or posterior C1–C2 fusion (more reliable, but sacrifices rotation).</li>
              <li><strong>Type III:</strong> Fracture extends through the body of C2 — generally good healing potential with a halo vest or collar. Surgery for significant displacement.</li>
            </ul>
            <p>Type II odontoid fractures in elderly patients present a particular dilemma: the non-union rate is high with conservative treatment, but surgical risk is elevated due to age and comorbidities. Dr. Rajesh Reddy individualises this decision — weighing bone quality, fracture displacement, patient functional status, and the relative risks of halo immobilisation (aspiration pneumonia, falls) versus posterior fusion under general anaesthesia.</p>

            <h3>Hangman's Fracture (Traumatic Spondylolisthesis of C2)</h3>
            <p>The hangman's fracture — bilateral fractures through the pedicles (pars interarticularis) of C2 — is caused by hyperextension and axial load, classically in motor vehicle accidents and diving injuries. Despite its dramatic name, patients with hangman's fractures are often neurologically intact: the bilateral pedicle fractures actually widen the spinal canal at C2, paradoxically decompressing the cord at the moment of injury.</p>
            <p>Management depends on the degree of angulation and translation at C2–C3:</p>
            <ul class="pillar-list">
              <li>Minimal displacement: rigid cervical collar for 12 weeks — excellent healing in most cases</li>
              <li>Moderate displacement with disc disruption at C2–C3: halo vest or anterior C2–C3 ACDF</li>
              <li>Severe displacement or instability: posterior C2–C3 or C1–C3 fusion</li>
            </ul>
          </section>

          <section id="subaxial-cervical" class="pillar-section">
            <h2>Subaxial Cervical Fractures (C3–C7)</h2>

            <h3>Compression Fractures</h3>
            <p>Simple anterior compression fractures of the subaxial cervical spine — where only the anterior column is involved — are stable injuries that can typically be managed with a rigid collar for 6–8 weeks. The fracture involves wedging of the anterior vertebral body with the posterior wall intact. Neurological deficit is uncommon. Serial X-rays at 6 and 12 weeks confirm healing.</p>

            <h3>Burst Fractures</h3>
            <p>A cervical burst fracture involves both the anterior and middle columns — the posterior vertebral wall comminutes and fragments may retropulse into the spinal canal, compressing the cord. The injury typically results from an axial load combined with flexion. Neurological deficit ranges from a central cord syndrome (disproportionate arm weakness) to complete cord injury, depending on the degree of canal compromise.</p>
            <p>Surgical treatment is mandatory for burst fractures with neurological deficit or significant canal compromise (> 50%). Anterior cervical corpectomy and fusion (ACCF) is the standard approach — the fractured vertebral body is removed, the canal directly decompressed, and a titanium mesh cage with anterior plate and screws restores height and alignment.</p>

            <h3>Flexion-Teardrop Fracture</h3>
            <p>The flexion-teardrop fracture is one of the most serious cervical injuries — a small triangular fragment avulsed from the anteroinferior corner of a vertebral body associated with severe posterior ligamentous disruption and cord injury. It typically produces an anterior cord syndrome: complete motor paralysis and loss of pain/temperature sensation below the level, with preserved proprioception and vibration. Emergency surgical decompression and stabilisation is required.</p>

            <h3>Facet Fractures and Dislocations</h3>
            <p>Unilateral facet dislocation (jumped facet) typically causes a nerve root injury at the level of dislocation — arm pain, weakness, and numbness — but incomplete cord injury. Bilateral facet dislocation causes complete cervical cord injury in the majority of cases. Both require urgent closed reduction (where safe) followed by surgical stabilisation.</p>
            <p>MRI before any reduction attempt is essential to rule out an associated disc herniation — a herniated disc anterior to the cord can be pushed further into the cord during reduction, worsening the injury. If a herniated disc is present, anterior decompression before reduction is performed.</p>
            <p>The sequence matters: MRI before reduction, then anterior discectomy if disc herniation is present, then reduction and posterior stabilisation. Attempting closed reduction without first excluding a herniated disc in the presence of cord injury is a preventable cause of neurological deterioration.</p>
          </section>

