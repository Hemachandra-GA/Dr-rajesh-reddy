          <section id="vertebral-artery" class="pillar-section">
            <h2>Vertebral Artery Injury in Cervical Fractures</h2>
            <p>Vertebral artery injury (VAI) occurs in approximately 20–30% of cervical fractures involving the transverse foramen — the bony canal through which the vertebral artery passes at each cervical level. VAI is most commonly associated with fractures involving C3–C6 transverse foramen, unilateral facet dislocations, and severe fracture-dislocations.</p>
            <p>Most VAIs are clinically silent — the contralateral vertebral artery provides sufficient collateral flow. However, a minority cause posterior circulation stroke (vertebrobasilar ischaemia) — presenting as dizziness, diplopia, nystagmus, ataxia, or Wallenberg syndrome in the days after injury. All cervical fractures involving the transverse foramen should have CT angiography of the neck vessels to identify VAI. Anticoagulation or antiplatelet therapy may be recommended for high-risk VAIs.</p>
          </section>

