            <p>The cervical spine — the seven vertebrae between the base of the skull and the upper chest — is the most mobile, and most vulnerable, segment of the spinal column. It houses the cervical spinal cord within a relatively narrow canal, and its injuries carry the highest neurological stakes of any spinal fracture. A displaced cervical fracture at or above C4 can sever the connection between the brain and the phrenic nerve — causing immediate respiratory arrest. A fracture-dislocation at C5–C6 can leave a previously healthy person unable to move their arms or legs.</p>
            <p>Yet the cervical spine's range of injuries is wide. At one end, a clay-shoveller's fracture of a spinous process requires nothing more than a soft collar and pain relief. At the other, a teardrop fracture-dislocation in a road traffic accident requires emergency surgical decompression and stabilisation within hours. Between these extremes lie odontoid fractures, Jefferson fractures, hangman's fractures, burst fractures, and subaxial fracture-dislocations — each with its own biomechanical characteristics, neurological risk, and treatment requirements.</p>
