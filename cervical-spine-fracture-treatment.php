          <section id="faq" class="pillar-section">
            <h2>Frequently Asked Questions</h2>
            <div class="faq-accordion">
              <div class="faq-item">
                <button class="faq-question">I was in an accident and have neck pain — do I have a cervical fracture?</button>
                <div class="faq-answer">
                  <p>Neck pain after a significant trauma — road traffic accident, fall from height, diving, or sports injury — must be treated as a potential cervical fracture until imaging proves otherwise. Attend the nearest emergency department immediately. Do not attempt to assess neck movement or remove any collar that has been placed. A CT scan of the cervical spine (and MRI if there is any neurological symptom) will definitively identify or exclude a fracture. Most people with post-traumatic neck pain do not have a fracture — but the consequences of a missed unstable cervical fracture are severe enough that imaging is mandatory after any significant mechanism.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">What is an odontoid fracture and does it always need surgery?</button>
                <div class="faq-answer">
                  <p>The odontoid process (dens) is a peg-like projection of the second cervical vertebra (C2) that fits into the ring of C1 — held in place by the transverse ligament. An odontoid fracture disrupts this joint. Type I (tip fracture) and Type III (through C2 body) fractures generally heal with collar or halo immobilisation. Type II fractures (base of dens) are the most problematic — they have a high non-union rate with conservative treatment (up to 60–70% in displaced cases in younger patients) and typically require surgical fixation. In elderly patients with poor bone quality, the decision between surgery and prolonged immobilisation is carefully individualised.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">Can a cervical fracture heal without surgery?</button>
                <div class="faq-answer">
                  <p>Many cervical fractures — particularly stable compression fractures, clay-shoveller's fractures, Type I and III odontoid fractures, and minimally displaced hangman's fractures — heal reliably with collar or halo vest immobilisation over 8–12 weeks. Surgery is required when: the fracture is unstable; there is neurological deficit from cord or root compression; conservative treatment has failed or the fracture is not uniting; or the degree of deformity is unacceptable. Dr. Rajesh Reddy will advise on the least invasive approach that achieves stability and neurological protection for your specific injury.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">What is ACDF and will I be able to move my neck normally afterwards?</button>
                <div class="faq-answer">
                  <p>ACDF (Anterior Cervical Discectomy and Fusion) is a surgical procedure performed through a small incision on the side of the neck — the damaged disc and any bony fragments are removed, a cage or bone graft is placed in the disc space, and a plate and screws are used to hold the construct while fusion occurs. After a one or two-level fusion, most patients retain very good neck range of motion — the remaining mobile levels compensate well. After three or more levels fused, some reduction in range of motion is expected. Physiotherapy after collar removal helps restore the motion available.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">How long do I have to wear a cervical collar after surgery?</button>
                <div class="faq-answer">
                  <p>After ACDF or anterior cervical corpectomy, a soft cervical collar is typically worn for 4–6 weeks. After posterior cervical fusion, a rigid collar is usually required for 6–12 weeks depending on the number of levels fused and the underlying injury. The collar is worn to protect the fusion while bone healing occurs — removing it early risks non-union. Dr. Rajesh Reddy will confirm the collar-wearing schedule at each post-operative review and adjust based on X-ray evidence of fusion progress.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">I was told I have C1–C2 instability — what does that mean?</button>
                <div class="faq-answer">
                  <p>Atlantoaxial instability refers to abnormal movement between C1 (atlas) and C2 (axis) — either from a fracture of the odontoid, rupture of the transverse ligament, or a combination. The dens can move posteriorly toward the spinal cord with neck movement, risking cord compression and potentially causing sudden tetraplegia or even death with a fall or minor trauma. The standard treatment for symptomatic atlantoaxial instability is posterior C1–C2 fusion — a procedure that permanently stabilises the C1–C2 joint. The trade-off is loss of approximately 50% of cervical rotation (which occurs mainly at C1–C2), but most patients adapt well and function normally for daily activities.</p>
                </div>
              </div>
