          <section id="technology" class="pillar-section">
            <h2 class="pillar-section-title">The Technology Behind Minimally Invasive Brain Surgery</h2>
            <p>Minimally invasive neurosurgery is made possible by a convergence of technologies that together compensate for the reduced visual field and working space of small access corridors:</p>

            <h3 style="font-size: 1.15rem; font-weight: 700; color: #1d1d1f; margin-top: 20px; margin-bottom: 8px;">High-Definition Endoscopy</h3>
            <p>Modern 4K endoscopes provide a magnified, panoramic, high-resolution view of the surgical field through an access corridor as small as 4 mm. Angled endoscopes (30°, 45°, 70°) allow the surgeon to look around corners within the surgical cavity — visualising structures that would be out of sight in a standard straight-line view. This visualisation quality often exceeds what the operating microscope provides through a traditional craniotomy.</p>

            <h3 style="font-size: 1.15rem; font-weight: 700; color: #1d1d1f; margin-top: 20px; margin-bottom: 8px;">Neuronavigation</h3>
            <p>Neuronavigation systems (StealthStation, BrainLab) provide real-time, 3D GPS-like guidance by registering the patient's pre-operative MRI or CT scan to their actual head position on the operating table. The surgeon can see a continuously updated display of instrument position relative to the tumor, critical structures, and planned surgical corridors — with sub-millimetre accuracy. This is particularly important in minimally invasive surgery, where the reduced visual field makes spatial orientation more demanding.</p>

            <h3 style="font-size: 1.15rem; font-weight: 700; color: #1d1d1f; margin-top: 20px; margin-bottom: 8px;">Diffusion Tensor Imaging (DTI) and Connectomics Integration</h3>
            <p>DTI tractography maps the brain's white matter pathways and is loaded into the neuronavigation system for use during minimally invasive resection. Connectomics — the mapping of neural networks — provides an additional layer, ensuring that not just individual functional areas but the critical connections between them are protected. This integration is particularly valuable in keyhole surgery near eloquent cortex, where the surgical margins are tighter.</p>

            <h3 style="font-size: 1.15rem; font-weight: 700; color: #1d1d1f; margin-top: 20px; margin-bottom: 8px;">Fluorescence Guidance</h3>
            <p>5-ALA and Sodium Fluorescein allow high-grade glioma cells to be visually identified during resection — compensating for the reduced visual field of keyhole surgery by making the tumor-brain boundary visible under specific light wavelengths. This technology has been shown to significantly improve the extent of GBM resection in multiple international studies.</p>

            <h3 style="font-size: 1.15rem; font-weight: 700; color: #1d1d1f; margin-top: 20px; margin-bottom: 8px;">Intraoperative Neurophysiological Monitoring (IONM)</h3>
            <p>Motor evoked potentials (MEPs), somatosensory evoked potentials (SSEPs), and cranial nerve monitoring provide continuous, real-time assessment of neurological function during minimally invasive resection — providing a safety net that is particularly valuable when working through a small corridor near functional brain areas or cranial nerves.</p>
          </section>

