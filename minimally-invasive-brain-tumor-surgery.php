            <h3 style="font-size: 1.3rem; margin-top: 36px; margin-bottom: 16px;">Each Technique in Depth</h3>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">1. Endoscopic Keyhole Craniotomy</h4>
            <p>The keyhole craniotomy replaces the large bone flap of traditional open surgery with a precisely placed mini-craniotomy of 2–3 cm. A high-definition endoscope or operating microscope is introduced through this small opening, providing magnified visualisation of the tumor and surrounding structures. Advanced angled endoscopes (30°, 45°, 70°) allow the surgeon to look around corners within the surgical cavity — accessing tumor tissue that would require much larger openings in traditional surgery.</p>
            <p>Neuronavigation provides real-time GPS guidance throughout, ensuring that the small craniotomy is placed in exactly the optimal position for the specific tumor. Blood loss is substantially reduced, and the scalp incision heals to a small, often barely visible scar.</p>
            <p><em>Best for:</em> Small to medium metastases, superficial gliomas, and select skull base tumors accessible via supraorbital or retrosigmoid approaches.</p>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">2. Supraorbital Keyhole Craniotomy (Eyebrow Approach)</h4>
            <p>The supraorbital keyhole craniotomy is one of the most elegant minimally invasive approaches in neurosurgery. A 3–4 cm incision is placed within the natural crease of the eyebrow — virtually invisible when healed. A small 2 cm craniotomy is made in the orbital rim, providing direct access to the anterior skull base, the region above the pituitary, the optic nerves, and the frontal lobes.</p>
            <p>This approach is particularly valuable for tumors at the anterior skull base — olfactory groove meningiomas, tuberculum sellae meningiomas, and craniopharyngiomas — that would otherwise require a large frontal craniotomy with significant brain retraction. Patients often remark that they cannot find the scar within weeks of surgery.</p>
            <p><em>Best for:</em> Anterior skull base tumors, olfactory groove meningiomas, small frontal lobe tumors, and select suprasellar tumors not accessible via the transsphenoidal route.</p>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">3. Endoscopic Transsphenoidal Surgery (Through the Nose)</h4>
            <p>The most impactful minimally invasive advance in neurosurgery of the past two decades, the endoscopic transsphenoidal approach removes pituitary tumors — and increasingly, other skull base tumors — entirely through the patient's nostrils. No scalp incision. No craniotomy. No visible change to the patient's appearance whatsoever.</p>
            <p>A 4mm high-definition endoscope is introduced through one nostril, navigated through the sphenoid sinus to the sella turcica (the bony housing of the pituitary gland), and the tumor is removed under direct endoscopic visualisation. The approach has been extended to reach tumors beyond the sella — craniopharyngiomas, clival chordomas, and some cavernous sinus tumors — using the expanded endoscopic endonasal approach (EEEA).</p>
            <p><em>Best for:</em> All pituitary adenomas (micro and macro), craniopharyngiomas, clival tumors, and select cavernous sinus lesions.</p>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">4. Endoscopic Transventricular Surgery</h4>
            <p>The brain's ventricular system — a network of fluid-filled cavities within the brain — provides a natural corridor to tumors growing within or adjacent to the ventricles. A rigid endoscope is navigated through a small burr hole into the ventricle, allowing tumors to be visualised, biopsied, or removed under direct camera guidance.</p>
            <p>Colloid cysts of the third ventricle — which can cause sudden, life-threatening hydrocephalus — are ideally suited to endoscopic resection. The endoscope navigates through the lateral ventricle into the third ventricle, where the cyst is opened, drained, and its wall removed — all through a single burr hole, with no brain retraction and minimal recovery time.</p>
            <p><em>Best for:</em> Colloid cysts, intraventricular meningiomas, small ependymomas, and ventricular tumors causing hydrocephalus.</p>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">5. Retrosigmoid / Retromastoid Keyhole Approach</h4>
            <p>The retrosigmoid keyhole approach accesses the posterior fossa — the region behind the brainstem — through a 3 cm incision and mini-craniotomy behind the ear, hidden within the natural hairline. This corridor provides excellent access to vestibular schwannomas (acoustic neuromas), posterior fossa meningiomas, and tumors along the trigeminal or facial nerve.</p>
            <p>The goal in vestibular schwannoma surgery via this approach is maximum tumor removal while preserving facial nerve function and, where possible, residual hearing. For tumors under 2.5–3 cm, the combination of keyhole microsurgery for larger tumors and stereotactic radiosurgery for smaller ones provides a full treatment spectrum.</p>
            <p><em>Best for:</em> Vestibular schwannomas, posterior fossa meningiomas, trigeminal schwannomas, epidermoid cysts, and petroclival tumors.</p>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">6. Stereotactic Radiosurgery (SRS) — Surgery Without a Scalpel</h4>
            <p>Stereotactic radiosurgery is the ultimate expression of minimally invasive brain tumor treatment — no incision, no anaesthesia, no hospital admission, and no recovery period. Multiple precisely focused radiation beams converge on the tumor from different angles, delivering a high dose of radiation to destroy tumor cells while sparing surrounding brain tissue.</p>
            <p>SRS is not conventional radiotherapy — it delivers a very high dose in a single session (or occasionally 2–5 fractions for larger tumors) with sub-millimetre targeting accuracy. The result is effective tumor control — the tumor shrinks or stabilises over months — for a range of tumor types.</p>
            <p><em>Best for:</em> Meningiomas &lt; 3 cm (particularly cavernous sinus), acoustic neuromas &lt; 3 cm, brain metastases (1–4 lesions), and residual or recurrent tumor after surgical resection.</p>

            <h4 style="font-size: 1.1rem; margin-top: 20px; margin-bottom: 8px;">7. Fluorescence-Guided Minimally Invasive Resection</h4>
            <p>When minimally invasive keyhole surgery is used for high-grade gliomas, 5-ALA or Sodium Fluorescein fluorescence guidance compensates for the reduced surgical field by making tumor tissue visually distinct from normal brain — glowing pink or yellow-green respectively under specific light filters. This allows the surgeon to maximise tumor removal through the small keyhole opening by precisely identifying tumor margins that would otherwise require a larger exposure to see reliably.</p>
            <p><em>Best for:</em> High-grade gliomas (GBM, Grade III) where a keyhole approach is planned and maximum resection is the goal.</p>
          </section>

