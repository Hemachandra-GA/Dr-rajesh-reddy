            <h2 class="pillar-section-title">Introduction & What Is Awake Craniotomy?</h2>
            <p>Of all the procedures in neurosurgery, awake craniotomy is perhaps the one that patients find most
              difficult to comprehend. Brain surgery while you are awake? Talking to the surgeon while your skull is
              open? It sounds like something from science fiction — yet awake craniotomy is a well-established,
              routinely performed technique at centres of neurosurgical excellence around the world, and for many
              patients with brain tumors near critical functional areas, it is the procedure that makes the difference
              between preserving speech and motor function, or losing it.</p>

            <p>This page is written specifically for patients who have been told they may need an awake craniotomy — and
              for their families. It answers the questions patients most urgently want answered: Why do I need to be
              awake? Will it hurt? What will I be asked to do? What if I panic? What are the risks? How is it different
              from regular brain surgery? The goal is to replace uncertainty and fear with understanding and confidence.
            </p>

            <p><strong>Dr. Rajesh Reddy Sannareddy</strong>, Senior Consultant Neurosurgeon in Hyderabad, performs awake
              craniotomy with a dedicated multidisciplinary team including a neuroanaesthesiologist, a
              neurophysiologist, and a speech-language therapist — the three pillars that make awake craniotomy both
              safe and effective. His training at the University Hospital, Zurich and visiting scholar experience at
              Barrow Neurological Institute, Phoenix give him deep exposure to awake craniotomy technique and
              intraoperative brain mapping in complex eloquent-area tumors.</p>

            <h3 style="font-size: 1.3rem; margin-top: 28px; margin-bottom: 12px;">What Is Awake Craniotomy and Why Is It
              Done?</h3>
            <p>Awake craniotomy is a type of brain surgery in which the patient is kept awake and interactive during the
              phase of the operation when the brain tumor is being removed. This allows the surgical team to monitor
              neurological function in real time — ensuring that critical brain areas responsible for speech, language,
              movement, vision, and cognition are preserved while the tumor is resected.</p>

            <h3>Why the Brain Can Be Operated on While the Patient Is Awake</h3>
            <p>The brain itself has no pain receptors. Once the scalp is numbed with local anaesthetic and the skull is
              opened — both of which are done while the patient is asleep or deeply sedated — the brain can be touched,
              stimulated, and operated on without causing pain. This fundamental neurological fact is what makes awake
              craniotomy possible.</p>
            <p>The scalp, skull, and dura (the brain's outer covering) do contain pain-sensitive nerve fibres, which is
              why those phases of the operation are carried out under general anaesthesia or sedation. The awake phase
              occurs only during the period of brain mapping and tumor resection — when the brain itself is being
              accessed.</p>

            <h3>When Is Awake Craniotomy Recommended?</h3>
            <p>Awake craniotomy is indicated when a brain tumor is located in or adjacent to eloquent cortex — the areas
              of the brain that control functions that would severely impact the patient's quality of life if damaged.
              These include:</p>
            <ul>
              <li><strong>Primary motor cortex</strong> — controls voluntary movement of the opposite side of the body
              </li>
              <li><strong>Broca's area</strong> — controls speech production (in the dominant hemisphere, usually left)
              </li>
              <li><strong>Wernicke's area</strong> — controls speech comprehension and language processing</li>
              <li><strong>Primary sensory cortex</strong> — processes touch, pain, and positional sensation</li>
              <li><strong>Supplementary motor area (SMA)</strong> — involved in planning and initiating movement</li>
              <li><strong>Optic radiations</strong> — white matter tracts carrying visual information from the eyes to
                visual cortex</li>
              <li><strong>Subcortical language pathways</strong> — including the arcuate fasciculus connecting Broca's
                and Wernicke's areas</li>
            </ul>
            <p>These areas are most commonly at risk in gliomas — particularly low-grade gliomas, which often occur in
              young adults with tumors in the dominant frontal or temporal lobe. Awake craniotomy is also used for
              select metastases and cavernomas in eloquent locations.</p>
            <p>The core principle of awake craniotomy is simple: you cannot fully protect what you cannot see. Pre-operative fMRI and DTI provide an estimate of where functional areas are — but intraoperative brain mapping during awake craniotomy provides the definitive, real-time map. This is why awake craniotomy consistently achieves greater tumor resection with lower rates of permanent neurological deficit compared to asleep surgery for eloquent-area tumors.</p>

