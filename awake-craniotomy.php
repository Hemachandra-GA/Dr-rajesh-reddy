            <ul>
              <li>Most patients with uncomplicated awake craniotomy are fit for discharge by day 4–5.</li>
              <li>Speech and motor function typically begin to improve from day 2–3 as swelling reduces.</li>
              <li>Speech therapy assessment before discharge — and outpatient speech therapy arranged if needed.</li>
