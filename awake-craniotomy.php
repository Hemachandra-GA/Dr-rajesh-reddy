            <h2 class="pillar-section-title">The Three Phases of Awake Craniotomy</h2>
            <p>Awake craniotomy is not an operation in which the patient is awake the entire time. It is structured into
              three distinct phases:</p>

            <div class="pillar-table-wrapper">
              <table class="pillar-table">
                <thead>
                  <tr>
                    <th>Phase</th>
                    <th>Anaesthesia State</th>
                    <th>What Happens</th>
                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <td><strong>Phase 1 — Opening</strong></td>
                    <td>Asleep (general anaesthesia or deep sedation)</td>
                    <td>Scalp incision, craniotomy (bone flap removal), and dural opening performed while patient is
                      fully anaesthetised and comfortable</td>
                  </tr>
                  <tr>
                    <td><strong>Phase 2 — Mapping & Resection</strong></td>
                    <td>Awake and interactive</td>
                    <td>Patient is gently woken. Cortical and subcortical stimulation mapping performed. Patient speaks,
                      names objects, moves limbs, or counts while surgeon maps functional boundaries and resects the
                      tumor</td>
                  </tr>
                  <tr>
                    <td><strong>Phase 3 — Closure</strong></td>
                    <td>Asleep again or sedated</td>
                    <td>Dura closed, bone flap replaced and secured with titanium plates, scalp closed. Patient
                      re-sedated for comfort during this phase</td>
                  </tr>
                </tbody>
              </table>
            </div>

