            <h2 class="pillar-section-title">Risks of Awake Craniotomy: An Honest Assessment</h2>
            <p>Awake craniotomy is generally safe when performed by an experienced team with dedicated neuroanaesthesia support. However, patients deserve a clear understanding of its specific risks:</p>

            <h3>Procedure-Specific Risks</h3>
            <p><strong>Intraoperative seizure (3–8%):</strong> Direct electrical stimulation can occasionally trigger a
              seizure during mapping. This is managed immediately by irrigating the brain surface with cold saline —
              which terminates the seizure within seconds — and pausing stimulation. The patient is given intravenous anti-epileptic medication if needed. This is a known and manageable complication, not an emergency.</p>
            <p><strong>Patient conversion (2–5%):</strong> In approximately 2–5% of cases, the patient becomes too anxious, fatigued, or distressed to continue cooperating with mapping tasks. In this situation, the surgeon converts to a standard asleep craniotomy and proceeds with available pre-operative imaging data.</p>
            <p><strong>Temporary neurological deficit:</strong> Most patients experience some temporary worsening of the function that was mapped — speech may be slightly more effortful, or limb movement slightly weaker — in the first few days after surgery. This almost always resolves within weeks as post-operative swelling subsides and the brain adapts.</p>
            <p><strong>Permanent neurological deficit (2–5%):</strong> The risk of permanent, significant neurological
              deficit after awake craniotomy in experienced hands is approximately 2–5% — significantly lower than the equivalent risk with asleep surgery for the same tumour location.</p>
            <p><strong>Anxiety and psychological distress:</strong> Some patients find the awake phase more distressing than anticipated. Thorough pre-operative preparation significantly reduces — though cannot entirely eliminate — this risk.</p>

            <h3>General Surgical Risks</h3>
            <ul>
              <li><strong>Bleeding</strong> — intracranial haemorrhage during or after surgery</li>
              <li><strong>Infection</strong> — wound or intracranial infection</li>
              <li><strong>CSF leak</strong> — uncommon</li>
              <li><strong>Anaesthetic complications</strong> — rare with dedicated neuroanaesthesia</li>
              <li><strong>Deep vein thrombosis</strong> — preventable with compression stockings and early mobilisation</li>
