              <li>Return to desk work typically possible within 4–6 weeks for most patients.</li>
              <li>For glioma patients: oncology referral and radiation/chemotherapy planning initiated at the 4–6 week mark.</li>
            </ul>

            <h3>3–6 Months</h3>
            <ul>
              <li>Most functional deficits from awake craniotomy — particularly language — continue to improve for up to 6 months as the brain reorganises.</li>
              <li>Neuropsychological reassessment at 3 months to track recovery and guide rehabilitation.</li>
              <li>Return to full professional and social activities for most patients.</li>
