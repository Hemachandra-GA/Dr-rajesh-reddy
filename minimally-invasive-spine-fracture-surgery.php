              <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 22px;">
                <h3 style="color: #0066cc; margin-top: 0; font-size: 1.15rem;"><i class="fa-solid fa-cube" style="margin-right: 8px;"></i> Intraoperative CT Navigation (O-arm / Cone-beam CT)</h3>
                <p style="margin: 0; line-height: 1.6; color: #475569;">Three-dimensional intraoperative navigation takes fluoroscopy a step further — a cone-beam CT scan is performed with the patient on the operating table, and the resulting three-dimensional image is registered to the patient's anatomy in real time. The surgeon's instruments appear on the navigation screen as a virtual overlay on the patient's own CT scan, allowing screw placement to be planned and confirmed in three dimensions before making any bony entry. Navigation reduces screw malposition rates to below 2% in experienced centres — compared with 5–15% for fluoroscopy-guided freehand placement — and is particularly valuable at the cervicothoracic junction and in patients with abnormal anatomy.</p>
              </div>

              <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 22px;">
                <h3 style="color: #0066cc; margin-top: 0; font-size: 1.15rem;"><i class="fa-solid fa-wave-square" style="margin-right: 8px;"></i> Intraoperative Neurophysiological Monitoring (IONM)</h3>
                <p style="margin: 0; line-height: 1.6; color: #475569;">Even in MIS procedures, nerve roots and the spinal cord are at risk. Continuous intraoperative neurophysiological monitoring — somatosensory evoked potentials (SSEPs) and motor evoked potentials (MEPs) — provides real-time feedback on the functional integrity of the neural elements throughout the procedure. A significant change in signal alerts the surgeon to modify or stop the current step before a permanent neurological deficit occurs. IONM is used routinely by Dr. Rajesh Reddy for MIS procedures near the spinal cord and for complex thoracolumbar fixations.</p>
              </div>
            </div>
          </section>

