          <section id="percutaneous-fixation" class="pillar-section">
            <h2>Percutaneous Pedicle Screw Fixation: The Workhorse of MIS Fracture Surgery</h2>
            <p>For traumatic thoracolumbar fractures that require stabilisation — burst fractures, flexion-distraction injuries, fracture-dislocations without major neurological compromise — percutaneous pedicle screw fixation is the most commonly performed MIS procedure. It achieves the same mechanical goal as open posterior fixation (immobilising the fractured segment to allow healing) through four to six stab incisions of 1–2 cm each, with no muscle retraction and no direct exposure of the bony spine.</p>
            
            <h3 style="font-size: 1.2rem; margin-top: 24px;">The Step-by-Step Surgical Technique:</h3>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li><strong>Positioning:</strong> Patient positioned prone on a radiolucent frame; biplanar fluoroscopy confirms fracture alignment and anatomical landmarks.</li>
              <li><strong>Jamshidi Access:</strong> Jamshidi needle advanced through the pedicle under biplanar fluoroscopic guidance; guide wire accurately placed through the needle into the vertebral body.</li>
              <li><strong>Serial Dilation:</strong> Sequential dilators passed over the guide wire to gently separate muscle fibers; cannulated pedicle screw inserted smoothly through the dilator set.</li>
              <li><strong>Construct Assembly:</strong> Steps repeated at each instrumented level — typically one level above and one level below the fractured vertebra.</li>
              <li><strong>Subfascial Rod Insertion:</strong> Connecting rod passed percutaneously through the screw tulips using a specialised subfascial rod-passing device, then locked securely with set screws.</li>
              <li><strong>Closure:</strong> Fascial and skin closure completed with small absorbable sutures; no wound drain required in most cases.</li>
            </ul>
            <p>Patients are typically mobilised the same evening or the following morning. The instrumentation can be removed at 12–18 months once the fracture has healed, also percutaneously, if the patient wishes.</p>
