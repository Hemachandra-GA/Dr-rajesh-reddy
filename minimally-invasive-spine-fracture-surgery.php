              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>Will I need general anaesthesia for balloon kyphoplasty?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Vertebroplasty is typically performed under sedation with local anaesthesia, while kyphoplasty is commonly performed under general anaesthesia. The choice depends on the patient's medical fitness, procedural requirements, and the number of levels treated. Most patients recover within a few hours.</p>
                </div>
              </div>

              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>How long will the screws stay in my spine?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Pedicle screws used in percutaneous fixation are titanium alloy and are MRI-compatible. They do not set off airport metal detectors. For most traumatic fractures in younger patients, the screws can be removed once the fracture has fully healed — typically at 12–18 months — through the original small incisions, in a 30-minute procedure. For older patients, those with osteoporotic bone, or those with instrumented fusion, the hardware is generally left permanently. Retained titanium hardware is safe and does not cause long-term problems in the vast majority of patients.</p>
                </div>
              </div>

              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>I was told my fracture is 'stable' — do I still need surgery?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Many stable vertebral fractures — particularly osteoporotic compression fractures — do not require surgery and can be managed with a short period of rest, analgesics, and a back brace. Surgery (kyphoplasty or vertebroplasty) is considered when: pain is severe and not controlled by conservative measures after 4–6 weeks; the fracture is progressive (losing further height); the kyphotic deformity is significant; or the fracture is causing neurological symptoms. An X-ray taken lying down and standing can identify dynamic instability not visible on a single view. Dr. Rajesh Reddy will review your imaging and advise whether the fracture pattern warrants intervention.</p>
                </div>
              </div>

              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>Can MIS be used for fractures caused by cancer?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Yes. Metastatic spine fractures are one of the most important indications for MIS techniques — particularly because cancer patients are often medically unfit for open surgery and need to minimise the interval between spine intervention and the continuation of systemic cancer treatment. Kyphoplasty or vertebroplasty provides pain relief and mechanical stability in metastatic vertebral fractures. Percutaneous fixation can stabilise impending or actual pathological fractures in patients with good expected survival. The choice of technique is individualised and made in collaboration with the patient's oncologist.</p>
                </div>
              </div>

              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>What are the risks of cement leakage in kyphoplasty?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Cement extravasation — leakage of PMMA bone cement outside the vertebral body — is the most discussed risk of augmentation procedures. With kyphoplasty, the balloon-created cavity allows cement to be injected at lower pressure, reducing extravasation rates to approximately 5–10% compared with 20–40% for vertebroplasty. The vast majority of extravasation events are small and clinically silent — detected on post-procedural imaging but not causing symptoms. Symptomatic extravasation (cement migrating into the spinal canal or venous system) is rare in experienced hands. Real-time fluoroscopic monitoring during injection, using high-viscosity cement, and stopping injection at the first sign of leakage are the primary preventive measures.</p>
                </div>
