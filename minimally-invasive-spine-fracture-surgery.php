          <section id="kyphoplasty-vertebroplasty" class="pillar-section">
            <h2>Balloon Kyphoplasty and Vertebroplasty for Compression Fractures</h2>
            <p>Vertebral compression fractures — the most common fracture type in patients over 60 — compress the front (anterior) column of the vertebra, producing a wedge-shaped deformity, height loss, and often severe axial back pain. When conservative management (rest, analgesia, bracing) fails to control pain, or when the fracture is progressive, cement augmentation procedures are highly effective.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">How Balloon Kyphoplasty Works</h3>
            <p>In kyphoplasty, a working cannula is placed into the collapsed vertebra through a transpedicular approach — through the pedicle, which is the bony bridge between the posterior arch and the vertebral body — under fluoroscopic guidance. A deflated balloon tamp is advanced through the cannula into the fractured bone. The balloon is slowly inflated under pressure, compacting the cancellous bone of the vertebral body and — in recently fractured vertebrae — partially restoring the lost vertebral height. The cavity created by the balloon is then filled with polymethylmethacrylate (PMMA) bone cement, which sets within minutes to provide immediate mechanical stability.</p>
            <p>The procedure is performed bilaterally (through both pedicles) at the fractured level. Duration is typically 45–75 minutes. Most patients notice a substantial reduction in pain within 24–48 hours.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">Vertebroplasty vs. Kyphoplasty: Which Is Used When?</h3>
            <p>Vertebroplasty injects cement directly without balloon pre-treatment. It is faster and less expensive, but provides less height restoration and operates at higher injection pressure — which slightly increases the risk of cement extravasation. Kyphoplasty's balloon-created low-pressure cavity significantly reduces extravasation risk and allows better height restoration in acute fractures. Dr. Rajesh Reddy uses kyphoplasty as the preferred technique for acute osteoporotic fractures with height loss, and vertebroplasty selectively for chronic fractures or metastatic lesions where height restoration is less critical.</p>
          </section>

