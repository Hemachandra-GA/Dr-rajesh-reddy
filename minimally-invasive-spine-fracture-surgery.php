          <!-- Section 2: What Makes a Spine Surgery 'Minimally Invasive'? -->
          <section id="what-makes-mis" class="pillar-section">
            <h2>What Makes a Spine Surgery 'Minimally Invasive'?</h2>
            <p>The term minimally invasive spine surgery describes a group of techniques that share a common anatomical strategy: accessing the spine while causing the least possible damage to the muscles, ligaments, and soft tissues that surround it. In conventional open spine surgery, these soft tissues are stripped away from the bony spine and retracted to give the surgeon a direct view. In MIS, they are instead dilated — gently separated along their natural fibre planes — using progressively larger tubular dilators until a working channel is established.</p>
            <p>Through this tube — typically 18 to 22 mm in diameter — the surgeon operates using a microscope, an endoscope, or fluoroscopic guidance, depending on the procedure. The paraspinal muscles are never cut; they spring back to their original position when the tube is removed. The bone, disc, and nerve structures are addressed as needed, and the instruments are withdrawn.</p>
            <p>The price of this tissue preservation is a steeper technical learning curve and the need for high-quality intraoperative imaging — fluoroscopy or three-dimensional navigation — to compensate for the reduced direct visualisation. In experienced hands, however, MIS procedures are as safe and reliable as their open equivalents, with a substantially better recovery profile.</p>
          </section>

