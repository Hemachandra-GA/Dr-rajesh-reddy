          <section id="osteoporotic-fractures" class="pillar-section">
            <h2>Osteoporotic Spine Fractures: A Specific Focus</h2>
            <p>Osteoporosis — a systemic condition of low bone mass and structural deterioration of bone tissue — affects an estimated 200 million people worldwide and is the leading cause of vertebral compression fractures in patients over 50. In India, the burden is substantial: estimates suggest that 46 million women over 50 have osteoporosis or osteopenia, and vertebral fractures are significantly underdiagnosed because many are attributed to 'normal ageing' without specific investigation.</p>

            <h3>Why Osteoporotic Fractures Are Underdiagnosed</h3>
            <p>The majority of osteoporotic vertebral fractures — estimated at 70% — are not brought to medical attention. Patients often attribute their pain to arthritis or muscle strain; many fractures are identified incidentally on imaging performed for another indication. This underdiagnosis has serious consequences: each vertebral fracture increases the risk of a subsequent fracture fivefold in the following year — a phenomenon known as the 'fracture cascade'. A patient who suffers one osteoporotic vertebral fracture without receiving anti-osteoporosis treatment is highly likely to suffer further fractures, progressive kyphosis, height loss, and functional decline.</p>

            <h3>The Fracture Liaison Service Principle</h3>
            <p>Best-practice management of osteoporotic fractures goes beyond treating the immediate fracture — it involves identifying and treating the osteoporosis to prevent the next fracture. Dr. Rajesh Reddy's management of osteoporotic vertebral fractures therefore includes:</p>
            <ul class="pillar-bullets">
              <li>DEXA scan to quantify bone mineral density (T-score) and confirm osteoporosis.</li>
              <li>Investigation for secondary causes — vitamin D deficiency, calcium malabsorption, hyperparathyroidism, thyroid disease, hypogonadism, and steroid use.</li>
              <li>Anti-osteoporosis pharmacotherapy — bisphosphonates, denosumab, teriparatide, or romosozumab for severe or refractory cases.</li>
              <li>Calcium and vitamin D supplementation as standard adjunct.</li>
              <li>Falls prevention programme — physiotherapy, environmental modification, and review of medications that increase fall risk.</li>
            </ul>
