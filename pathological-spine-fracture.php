          <section id="what-is-pathological-fracture" class="pillar-section">
            <h2>What Is a Pathological Fracture?</h2>
            <p>A pathological fracture is a fracture that occurs through bone that has been weakened by an underlying pathological process — as opposed to a traumatic fracture, which occurs through previously normal bone subjected to a force exceeding its structural limit. The distinction matters clinically because:</p>
            <ul class="pillar-bullets">
              <li>The fracture may occur with minimal or no trauma — sometimes spontaneously.</li>
              <li>The fractured bone does not heal normally without addressing the underlying cause.</li>
              <li>Multiple vertebral levels may be affected simultaneously or sequentially.</li>
              <li>Treatment must address both the mechanical failure and the underlying disease.</li>
              <li>Prognosis depends heavily on the nature and stage of the underlying condition.</li>
            </ul>
            <p>The spine is the most common site of pathological fracture in the body. This is partly because vertebrae are composed largely of cancellous (spongy) bone — the trabecular architecture of which is highly vulnerable to both the trabecular thinning of osteoporosis and the osteolytic destruction of metastatic disease — and partly because the axial skeleton bears the body's gravitational load throughout the day.</p>
          </section>

