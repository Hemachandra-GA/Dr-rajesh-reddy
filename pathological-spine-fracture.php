            <h2>Frequently Asked Questions</h2>
            <div class="faq-accordion">
              <div class="faq-item">
                <button class="faq-question">I have osteoporosis and my back pain is getting worse. Could I have a fracture?</button>
                <div class="faq-answer">
                  <p>Yes — back pain in a person with osteoporosis should be taken seriously, even without a history of a fall or injury. Osteoporotic vertebral fractures can occur with minimal provocation — lifting a bag, twisting suddenly, or even just sitting up from a chair. The key symptoms that should prompt an MRI are pain that is worse on standing and moving, pain at a specific spinal level that is tender to pressure, or any neurological symptoms such as leg weakness or numbness. An X-ray may show the fracture, but MRI is more sensitive for detecting recent fractures and ruling out malignancy as a cause.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">I have cancer and am experiencing new back pain. Is this a spine fracture?</button>
                <div class="faq-answer">
                  <p>New back pain in a patient with a known cancer history should be investigated urgently, as spinal metastases are common in many cancer types — particularly lung, breast, prostate, kidney, and thyroid cancer. The pain may be from bone involvement, a fracture, or early spinal cord compression. MRI of the whole spine is the preferred investigation. Early diagnosis and treatment of spinal metastases — before neurological deficit occurs — is associated with much better outcomes, including the ability to walk. Please do not delay seeking assessment.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">What is the difference between kyphoplasty for osteoporosis and surgery for cancer fractures?</button>
                <div class="faq-answer">
                  <p>Kyphoplasty and vertebroplasty are cement augmentation procedures — they stabilise the fractured vertebra by filling it with bone cement. They are highly effective for osteoporotic fractures and for select metastatic fractures where the goal is pain relief and mechanical stabilisation. They do not remove tumour or provide decompression of the spinal cord. Cancer fractures with neurological compromise or significant spinal cord compression require surgical decompression and fixation — a much more involved procedure. The choice between the two depends on the neurological status, the degree of instability (SINS score), and the overall oncological situation.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">How long does recovery take after kyphoplasty for an osteoporotic fracture?</button>
                <div class="faq-answer">
                  <p>Kyphoplasty is typically performed as a day procedure or with one night in hospital. Most patients notice a significant reduction in pain within 24–48 hours — often described as dramatic. Light activity can resume within a few days; return to normal daily activities typically occurs within 1–2 weeks. The treated vertebra is permanently stabilised by the cement, so the fracture does not recur. However, adjacent vertebrae remain at risk of fracture if the osteoporosis is not treated — which is why medical treatment of the osteoporosis is just as important as the procedural intervention.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">Can spinal cord compression from cancer be reversed?</button>
                <div class="faq-answer">
                  <p>Yes, in many cases — but the outcome depends critically on how quickly it is identified and treated. Patients with mild neurological symptoms who receive prompt decompression and radiotherapy have the best chance of neurological recovery. Patients who have been completely paralysed for more than 24–48 hours before decompression have a much lower chance of meaningful recovery. This is why spinal cord compression from cancer is a medical emergency — any patient with cancer who develops leg weakness, difficulty walking, or bladder dysfunction should seek emergency assessment without delay.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">Is spine surgery safe in patients with advanced cancer?</button>
                <div class="faq-answer">
                  <p>It depends on the patient's overall condition, performance status, and expected survival. For patients with good performance status and reasonable expected survival, spine surgery — particularly minimally invasive stabilisation or separation surgery — is well-tolerated and significantly improves quality of life by relieving pain and preserving neurological function. For patients with end-stage disease, multiple organ involvement, or very poor performance status, the risks of surgery may outweigh the benefits, and palliative management with pain medication, bracing, and radiotherapy may be the most appropriate approach.</p>
                </div>
              </div>
