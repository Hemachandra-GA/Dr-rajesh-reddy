          <section id="symptoms" class="pillar-section">
            <h2>Recognising a Pathological Spine Fracture: Symptoms and Red Flags</h2>
            <p>Pathological vertebral fractures often present differently from traumatic fractures, and a high index of suspicion is essential — particularly in patients with known risk factors.</p>

            <h3>Symptoms</h3>
            <ul class="pillar-bullets">
              <li>Sudden-onset severe back or neck pain, often without a significant injury.</li>
              <li>Progressive back pain that worsens over days to weeks — unlike mechanical back pain, which is typically episodic.</li>
              <li>Pain that is worse at rest or at night — a classic feature of bone pain from malignancy, unlike degenerative pain which is worse with activity.</li>
              <li>Neurological symptoms — leg weakness, numbness, difficulty walking, or bladder/bowel dysfunction — suggesting spinal cord or nerve root compression.</li>
              <li>Height loss and increasing thoracic kyphosis (dowager's hump) in elderly women — suggesting multiple osteoporotic compression fractures.</li>
              <li>Constitutional symptoms in oncological fractures — weight loss, fatigue, loss of appetite — suggesting active malignancy.</li>
            </ul>

            <h3>Red Flags That Should Prompt Urgent Assessment</h3>
            <p>Any patient over 50 presenting with new-onset back pain and no clear mechanical cause, any patient with a known cancer history developing new spinal pain, and any patient with progressive neurological symptoms should be assessed urgently with MRI of the spine. A 'simple' vertebral fracture on X-ray in a middle-aged or elderly patient without a significant fall is a pathological fracture until proven otherwise.</p>
          </section>

          <section id="diagnosis" class="pillar-section">
            <h2>Diagnosis: What Imaging Is Needed?</h2>
            <ul class="pillar-bullets">
              <li><strong>Plain X-ray:</strong> First-line; detects vertebral height loss, endplate fractures, and deformity. Insensitive for early metastatic disease.</li>
              <li><strong>MRI spine:</strong> The gold standard for pathological fractures — identifies bone marrow infiltration, epidural compression, cord signal change, and distinguishes acute from chronic fractures. Whole-spine MRI is essential when malignancy is suspected.</li>
              <li><strong>CT spine:</strong> Better than MRI for assessing bony architecture — pedicle integrity, cortical destruction, and fracture morphology for surgical planning.</li>
              <li><strong>Bone scan (99mTc scintigraphy) / PET-CT:</strong> Detects additional skeletal metastases; PET-CT is superior for staging and detecting metabolically active disease.</li>
              <li><strong>DEXA scan:</strong> Measures bone mineral density (BMD) and is essential for diagnosing osteoporosis and monitoring treatment response.</li>
              <li><strong>Biopsy:</strong> Required when the primary tumour is unknown; CT-guided percutaneous biopsy of the vertebral lesion provides tissue diagnosis.</li>
            </ul>
