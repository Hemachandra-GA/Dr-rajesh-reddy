          <section id="noms" class="pillar-section">
            <h2>The NOMS Framework: Decision-Making for Spinal Metastases</h2>
            <p>For metastatic spine fractures specifically, the Neurological-Oncological-Mechanical-Systemic (NOMS) framework — developed at Memorial Sloan Kettering Cancer Center — provides the most comprehensive decision-making structure. It integrates four domains:</p>
            <ul class="pillar-bullets">
              <li><strong>Neurological (N):</strong> Is there spinal cord or nerve root compression? High-grade epidural compression causing myelopathy requires emergency surgical decompression; low-grade compression may be managed with radiotherapy alone.</li>
              <li><strong>Oncological (O):</strong> How radiosensitive is the tumour? Highly radiosensitive tumours respond to conventional radiotherapy; radioresistant tumours require high-dose stereotactic radiotherapy (SBRT) or surgical resection.</li>
              <li><strong>Mechanical (M):</strong> Is the spine mechanically stable? SINS score guides this assessment — instability requires surgical fixation regardless of neurological or oncological status.</li>
              <li><strong>Systemic (S):</strong> What is the patient's overall health, performance status, and systemic disease burden? A patient with poor performance status may not be a surgical candidate.</li>
            </ul>
            <p>Dr. Rajesh Reddy applies the NOMS framework in collaboration with the patient's oncologist, radiation oncologist, and palliative care team in a multidisciplinary tumour board setting. This ensures that each patient receives a coherent, integrated treatment plan rather than a series of disconnected interventions.</p>
