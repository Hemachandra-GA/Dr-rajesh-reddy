          <section id="faq" class="pillar-section">
            <h2>Frequently Asked Questions</h2>
            <div class="faq-accordion">
              <div class="faq-item">
                <button class="faq-question">I have a burst fracture at L1 with no weakness — do I need surgery?</button>
                <div class="faq-answer">
                  <p>Not necessarily, but it depends on several factors that go beyond the simple presence of a burst fracture. The TLICS scoring system considers three things: the fracture morphology (burst = 2 points), the integrity of the posterior ligamentous complex on MRI (if disrupted = 3 points), and your neurological status (intact = 0 points). An isolated burst fracture with an intact PLC and no neurological deficit typically scores 2 — well within the conservative management range. If the PLC is disrupted or there is significant canal compromise, the score rises and surgery becomes the recommended option. Dr. Rajesh Reddy will review your CT and MRI and calculate a personalised assessment.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">What is the posterior ligamentous complex and why does it matter so much?</button>
                <div class="faq-answer">
                  <p>The posterior ligamentous complex (PLC) is a set of ligaments running along the back of the spine — the supraspinous ligament, interspinous ligament, ligamentum flavum, and facet joint capsules. Together they act as a tension band that prevents the spine from collapsing forward. If the PLC is intact after a burst fracture, the spine retains its ability to resist flexion forces and conservative management is feasible. If the PLC is torn — visible on MRI as bright signal on STIR sequences — the spine has lost its posterior tension band and will progressively collapse forward under daily loads, regardless of how good the brace is. This is why PLC assessment on MRI is the most important single imaging finding in the surgery vs. brace decision.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">How long will I have to wear the brace?</button>
                <div class="faq-answer">
                  <p>For most thoracolumbar compression or burst fractures managed conservatively, the TLSO brace is worn continuously (whenever upright) for 8–12 weeks. At the 6-week X-ray review, if the fracture is healing and alignment is maintained, the brace duration may be confirmed or the weaning process started. If X-rays show progressive kyphosis or height loss, the brace duration is extended and surgical options are reconsidered. After brace removal, a structured physiotherapy programme begins to restore core strength and spinal stability.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">What is a Chance fracture and is it different from a burst fracture?</button>
                <div class="faq-answer">
                  <p>A Chance fracture is caused by forward flexion over a fulcrum — classically a lap seat belt in a frontal collision. Rather than compressing the vertebra under axial load (like a burst fracture), a Chance fracture splits the vertebra horizontally through distraction of the posterior elements. In purely bony Chance fractures (bone splits through the pedicles and body), healing with a hyperextension brace is often excellent. In ligamentous Chance fractures (the posterior ligamentous complex tears rather than bone breaking), surgical posterior fusion is required as soft tissue does not heal reliably with immobilisation. Associated bowel and abdominal injuries are common and must be sought in any patient with a Chance fracture.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">Can I walk after a thoracolumbar fracture?</button>
                <div class="faq-answer">
                  <p>Yes — in the majority of cases. Patients with neurologically intact thoracolumbar fractures — whether managed conservatively or surgically — are mobilised (encouraged to walk with supervision) within 1–2 days of injury or surgery. Walking with the brace is an important part of recovery and helps prevent the deconditioning and complications of bed rest. The key restriction is avoiding bending, twisting, and lifting rather than walking itself. Patients with neurological deficits have a more complex mobilisation programme managed in coordination with physiotherapy and rehabilitation specialists.</p>
                </div>
              </div>
              <div class="faq-item">
                <button class="faq-question">When can I go back to work after a thoracolumbar fracture?</button>
                <div class="faq-answer">
                  <p>This depends on the treatment approach and the nature of your work. For conservative management: desk-based work is typically possible from week 6–8 within the brace; manual or physically demanding work requires 3–6 months of recovery after brace removal. After minimally invasive surgical fixation: desk work from week 4–6; physical work 3–6 months. After open surgery: desk work 6–8 weeks; physical work 6–12 months. All return-to-work plans are individualised based on fracture healing on X-ray, neurological recovery, and the specific physical demands of the job.</p>
                </div>
              </div>
            </div>
