            <h2>Surgical Treatment: Minimally Invasive vs. Open</h2>
            <figure style="margin: 28px 0;">
              <img src="images/Thoracolumbar_spine_fracture_treatment/treatment_options_for_thoraclumbar_fracture.webp" alt="Surgical treatment options including percutaneous MISS fixation and open decompression" style="width: 100%; height: auto; display: block; border-radius: 12px;">
              <figcaption style="margin-top: 8px; color: #64748b; font-size: 0.9rem;">Modern neurosurgical instrumentation allows percutaneous screw placement with minimal muscle disruption, or direct open decompression when cord relief is vital.</figcaption>
            </figure>

            <h3>Percutaneous Minimally Invasive Spine Surgery (MISS)</h3>
            <p>For neurologically intact patients with unstable thoracolumbar fractures, percutaneous pedicle screw fixation has become the surgical approach of choice at experienced centres. Through four small incisions (each approximately 1.5 cm), pedicle screws are placed above and below the fracture under fluoroscopic or CT navigation guidance, connected by percutaneous rods that span and stabilise the fracture. The paraspinal muscles are not stripped from the spine — they are dilated rather than cut, preserving muscle function and dramatically reducing post-operative pain.</p>
            <p>The advantages over open surgery are substantial:</p>
            <ul class="pillar-list">
              <li><strong>Blood loss:</strong> 100–300 mL versus 500–1500 mL for open fixation</li>
              <li><strong>Operating time:</strong> 60–90 minutes versus 2–4 hours</li>
              <li><strong>Hospital stay:</strong> 2–4 days versus 5–7 days</li>
              <li><strong>Post-operative pain:</strong> significantly less; simple analgesics usually sufficient</li>
              <li><strong>Return to activity:</strong> 4–6 weeks versus 8–12 weeks</li>
              <li><strong>Infection risk:</strong> lower with smaller incisions</li>
            </ul>
            <p>MISS does not decompress the spinal canal directly — it relies on <em>ligamentotaxis</em> (indirect reduction through distraction across the fracture via the posterior tension band) to reduce retropulsed fragments. For neurologically intact patients with &lt; 50% canal compromise, this indirect reduction is typically sufficient. For patients with neurological deficit and direct canal compromise, open decompression is required.</p>

            <h3>Open Decompression and Instrumented Fusion</h3>
            <p>Open posterior surgery is indicated when: direct decompression of the spinal canal is required (neurological deficit from retropulsed bone); the fracture involves multi-level instability; or the deformity is severe enough to require direct reduction and reconstruction. Through a midline incision, the paraspinal muscles are retracted to expose the posterior spine — laminectomy removes the posterior arch, decompressing the canal, and pedicle screws above and below provide rigid fixation.</p>
            <p>For severe burst fractures where the anterior column has lost &gt; 50% of height and the vertebral body cannot be reconstructed posteriorly alone, an anterior corpectomy and cage reconstruction is added — either as a same-day combined procedure or as a staged anterior approach 2–5 days later.</p>

            <h3>Implant Removal Considerations</h3>
            <p>Percutaneous pedicle screws are typically left permanently in neurologically intact patients — there is no clinical benefit to removal and it would require a second procedure. In selected younger patients where screws are causing adjacent segment stress or instrument-related symptoms, removal can be considered after confirmed fusion (typically 12–18 months). Dr. Rajesh Reddy will advise on the implant strategy appropriate to each patient's age, injury, and functional demands.</p>
