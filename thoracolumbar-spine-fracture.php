          <section id="types-of-fractures" class="pillar-section">
            <h2>Types of Thoracolumbar Fractures</h2>

            <h3>Compression Fracture</h3>
            <p>The most common thoracolumbar fracture — particularly in osteoporotic patients. The anterior column is compressed, producing a wedge-shaped loss of vertebral height. The middle column (posterior vertebral wall) is intact, making the fracture stable. Neurological deficit is rare unless multiple levels are affected and cumulative kyphosis becomes significant. Most compression fractures are managed conservatively with a TLSO brace and early mobilisation.</p>

            <h3>Burst Fracture</h3>
            <p>A burst fracture involves failure of both the anterior and middle columns — the vertebral body comminutes under axial load, and fragments of the posterior vertebral wall retropulse into the spinal canal. Canal compromise ranges from minimal to complete occlusion. The critical clinical questions are: is the posterior ligamentous complex (PLC) intact, is the patient neurologically intact, and what is the degree of canal compromise? These three factors — along with the fracture morphology score — determine the TLICS score and the treatment recommendation.</p>
            <p>Burst fractures of L1 are the single most common surgically treated thoracolumbar injury in young adults. They typically result from falls from height (construction workers, roofers) or road traffic accidents, and often occur in isolation or as part of polytrauma.</p>

            <h3>Chance Fracture (Flexion-Distraction)</h3>
            <p>The Chance fracture is a horizontal splitting of the vertebra through bone, disc, or a combination — caused by the spine flexing sharply over a fulcrum (classically a lap seat belt in a forward collision). The injury distracts the posterior elements (spinous process, lamina, facets) while compressing the anterior column. In purely bony Chance fractures, healing with a hyperextension brace is often possible. In ligamentous Chance fractures — where the posterior ligamentous complex is torn — surgical posterior fusion is required. Associated abdominal visceral injuries are common with seat-belt Chance fractures and should be actively sought.</p>

            <h3>Fracture-Dislocation</h3>
            <p>The most severe thoracolumbar injury — a fracture with translation or rotation of one vertebra over another, disrupting all three columns. Neurological deficit is common and may be complete. Emergency surgical stabilisation is required to restore alignment, decompress the neural elements, and prevent further injury. These injuries are typically associated with high-energy polytrauma.</p>

