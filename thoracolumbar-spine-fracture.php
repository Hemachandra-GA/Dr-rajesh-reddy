          <!-- Section 6: Conservative Brace Treatment -->
          <section id="conservative-treatment" class="pillar-section">
            <h2>Conservative Treatment: Brace Management in Detail</h2>
            <p>For thoracolumbar fractures that meet conservative management criteria — stable injury, neurologically intact, TLICS ≤ 3 — a thoracolumbar sacral orthosis (TLSO) brace is the primary treatment. Conservative management does not mean no treatment — it requires a structured programme of bracing, monitoring, and rehabilitation.</p>

            <h3>The TLSO Brace</h3>
            <p>A custom-fitted TLSO brace extends from the mid-thorax to the pelvis, limiting flexion and rotation at the thoracolumbar junction while allowing the patient to mobilise. It is worn for 8–12 weeks, during which the fracture heals and the anterior column reconstitutes. Key points for patients:</p>
            <ul class="pillar-list">
              <li>The brace must be worn whenever upright — walking, sitting, standing — for the full prescribed duration</li>
              <li>It may be removed for lying flat, bathing (with care), and skin inspection</li>
              <li>Skin care under the brace is important — check for pressure areas daily</li>
              <li>Do not attempt to lift anything heavier than 2–3 kg while in the brace</li>
              <li>Sleep on a firm mattress; use the log-roll technique for getting in and out of bed</li>
            </ul>

            <h3>Monitoring During Conservative Treatment</h3>
            <p>Conservative management requires close follow-up — it is not a passive process. Serial X-rays at 2 weeks, 6 weeks, and 12 weeks assess:</p>
            <ul class="pillar-list">
              <li><strong>Progressive kyphosis</strong> — if regional kyphosis increases by &gt; 5° between appointments, the fracture is failing to maintain alignment and surgical intervention should be reconsidered.</li>
              <li><strong>Vertebral height restoration or loss</strong> — some remodelling occurs during healing; progressive height loss indicates instability.</li>
              <li><strong>Any new neurological symptoms</strong> — any new weakness, numbness, or bladder/bowel change during conservative management is an indication for emergency imaging and surgical reassessment.</li>
            </ul>

            <div class="note-box" style="background:#fefce8; border-left:4px solid #ca8a04; padding:16px; margin:24px 0; border-radius:4px;">
              <strong>CRITICAL REMINDER:</strong> Conservative management of a thoracolumbar fracture is not 'doing nothing.' It requires a structured brace programme, serial X-ray monitoring, and a clear threshold for switching to surgical management if the fracture fails to maintain alignment. Patients who disappear to follow-up after being prescribed a brace are at risk of progressive deformity that becomes much more difficult to correct surgically months later.
            </div>
          </section>

