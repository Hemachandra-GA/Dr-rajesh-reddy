          <section id="anatomy-vulnerability" class="pillar-section">
            <h2>The Thoracolumbar Junction: Why T11–L2 Is So Vulnerable</h2>
            <p>The thoracolumbar junction represents a biomechanical transition between two very different spinal segments:</p>
            <ul class="pillar-list">
              <li><strong>The thoracic spine (T1–T10)</strong> is inherently rigid — the rib cage provides circumferential bracing that limits flexion, extension, and rotation, making this segment resistant to fracture under most everyday loads.</li>
              <li><strong>The lumbar spine (L1–L5)</strong> is mobile but supported by large paraspinal muscles and wide vertebral bodies built for load bearing.</li>
              <li><strong>The junction (T11–L2)</strong> has neither the rib cage protection of the upper thoracic spine nor the muscular support of the mid-lumbar spine — it is the hinge point where the two systems meet.</li>
            </ul>
            <p>During the axial loading and forward flexion of a high-energy impact — a fall from a roof, a motorcycle accident, a collapsing structure — this junction absorbs the concentrated mechanical energy of the entire spinal column above it. The result is a fracture pattern ranging from simple anterior compression to catastrophic multi-column burst fractures with spinal canal compromise.</p>
            <div class="note-box" style="background:#f0f7ff; border-left:4px solid #0066cc; padding:16px; margin:24px 0; border-radius:4px;">
              <strong>Neurological Anatomy Note:</strong> The spinal cord typically ends at L1–L2 as the conus medullaris. Fractures at or above L1 risk injury to the conus, producing a mixed picture of upper and lower motor neurone signs. Fractures below L2 involve the cauda equina — the bundle of lumbar and sacral nerve roots — where recovery potential is generally better than cord injuries, as peripheral nerves regenerate more reliably than central cord tissue.
            </div>
          </section>

