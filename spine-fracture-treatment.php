            <h3>Conservative Treatment: When Surgery Is Not Needed</h3>
            <p>A significant proportion of spinal fractures — particularly stable compression fractures in the elderly and minor cervical fractures in younger patients — can be managed without surgery. Conservative treatment is appropriate when: the fracture is stable (involves only the anterior column); there is no neurological deficit; the patient has good bone quality and healing potential; and the degree of deformity is acceptable.</p>
            
            <h4>Bracing and Immobilisation</h4>
            <ul class="pillar-list">
              <li><strong>Cervical collar (soft or rigid):</strong> Used for minor cervical fractures without instability — such as isolated spinous process fractures or minor compression fractures. A rigid Philadelphia collar or Miami J collar provides more support than a soft collar.</li>
              <li><strong>TLSO (Thoracolumbar Sacral Orthosis):</strong> A custom-moulded or prefabricated brace that limits thoracolumbar flexion and rotation. Used for stable thoracolumbar compression fractures or as post-operative support after surgical fixation.</li>
              <li><strong>Halo vest:</strong> A halo ring bolted to the skull and attached to a rigid vest — provides rigid immobilisation of the entire cervical spine. Used for unstable upper cervical fractures (Type II odontoid fractures in elderly, Jefferson fractures) where surgery carries high risk. Significant patient discomfort; now used less frequently with improvements in minimally invasive cervical fixation.</li>
            </ul>

            <h3>Vertebroplasty and Kyphoplasty</h3>
            <p>For osteoporotic and pathological compression fractures that are causing severe pain but have not caused neurological compression, vertebroplasty and kyphoplasty offer rapid, minimally invasive pain relief:</p>
            <ul class="pillar-list">
              <li><strong>Vertebroplasty:</strong> bone cement (PMMA) injected percutaneously through a needle under fluoroscopic guidance directly into the fractured vertebral body — stabilises the fracture, reduces pain in approximately 80–90% of patients within 24–48 hours</li>
              <li><strong>Kyphoplasty:</strong> a balloon is first inflated inside the fractured vertebra to restore height, then deflated and the cavity filled with cement — achieves better height restoration than vertebroplasty and reduces cement leak risk</li>
              <li>Both are day or overnight procedures performed under local anaesthesia with sedation or light general anaesthesia</li>
              <li>Not appropriate where there is epidural extension of cement risk, significant spinal canal compromise, or where the fracture is acute and unstable beyond compression</li>
            </ul>
            <p>Vertebroplasty and kyphoplasty are highly effective for pain from osteoporotic compression fractures — but they do not treat the underlying osteoporosis. All patients with osteoporotic fractures should be assessed and treated for osteoporosis (bisphosphonates, calcium, vitamin D, DEXA scan) to prevent future vertebral collapse.</p>

            <h3>Surgical Treatment: Stabilisation, Decompression, and Reconstruction</h3>
            <p>Surgery for spinal fractures aims to achieve three goals — in order of priority: (1) protect or recover neurological function through decompression, (2) restore and maintain spinal alignment, and (3) stabilise the spine to allow early mobilisation and prevent progressive deformity. The surgical approach — anterior, posterior, or combined — depends on where the pathology lies and what needs to be done to achieve these goals.</p>

            <h4>Minimally Invasive Spine Surgery (MISS) for Spinal Fractures</h4>
            <p>The development of percutaneous pedicle screw fixation has transformed the surgical management of thoracolumbar fractures in neurologically intact patients. Rather than making a large midline incision and stripping paravertebral muscles from the spine — as in traditional open fixation — percutaneous screws are placed through small skin punctures (typically 4 x 1.5 cm incisions) under fluoroscopic or CT-navigation guidance, connected by rods passed through subcutaneous tunnels.</p>
            <p>The advantages over open fixation are substantial: dramatically reduced blood loss, shorter operating time, minimal muscle damage, significantly less post-operative pain, shorter hospital stay (typically 2–4 days versus 5–7 for open), and faster return to activity. For neurologically intact patients with unstable thoracolumbar burst fractures or compression fractures causing progressive kyphosis, percutaneous fixation is now the preferred approach at experienced centres.</p>

            <h4>Anterior Cervical Decompression and Fusion (ACDF)</h4>
            <p>For cervical burst fractures or fracture-dislocations where bone or disc material is compressing the cord from the front, anterior decompression provides the most direct relief of cord compression. Through a small incision on the side of the neck, the surgeon removes the fractured vertebral body (corpectomy) or the damaged disc and posterior fragments, places a cage or bone graft to restore height, and fixes the construct with an anterior plate and screws. This approach directly removes the compressive pathology without manipulating the already-injured cord.</p>

            <h4>Posterior Decompression and Instrumented Fusion</h4>
            <p>When the primary instability is posterior — fracture-dislocations, facet joint fractures, posterior ligamentous disruption — a posterior approach with pedicle screw-rod fixation corrects the dislocation, restores alignment, and decompresses the canal through laminectomy or foraminotomy. Posterior fixation provides multi-level stability across the fracture — typically 2 levels above and 2 below the fracture — through large-diameter pedicle screws connected by rigid rods.</p>

            <h4>Combined Anterior-Posterior Surgery</h4>
            <p>Complex fractures — particularly thoracolumbar burst fractures with severe comminution, loss of anterior column height > 50%, or associated posterior ligamentous disruption — require anterior column reconstruction (corpectomy and cage) combined with posterior instrumented fusion for complete stability. These combined procedures are performed in a single operation at experienced centres or as staged procedures 2–5 days apart, depending on the patient's overall condition.</p>

            <h4>Emergent Surgical Decompression</h4>
            <p>When a patient has an incomplete spinal cord injury (ASIA B–D) and imaging shows reducible cord compression — from a displaced fracture fragment, herniated disc, or extradural haematoma — emergent surgical decompression within 8–24 hours of injury has been shown to improve neurological outcomes. The STASCIS trial demonstrated that early (< 24 hours) decompression for cervical SCI was associated with significantly better 6-month neurological outcomes compared to delayed decompression. Dr. Rajesh Reddy accepts emergency spinal cord decompression cases transferred from across the region.</p>

            <h3>Pathological Spine Fractures: Cancer, Myeloma, and Osteoporosis</h3>
            <p>A significant proportion of spinal fractures in adults over 50 are pathological — caused by weakening of the vertebral body by an underlying disease process rather than by trauma alone. The most common causes are:</p>
            <ul class="pillar-list">
              <li><strong>Metastatic cancer</strong> — breast, prostate, lung, kidney, and thyroid cancers frequently metastasise to the spine, causing vertebral collapse and potential cord compression (metastatic epidural spinal cord compression, MESCC)</li>
              <li><strong>Multiple myeloma</strong> — a plasma cell malignancy that causes diffuse lytic bone disease; spinal fractures and cord compression are common presenting features</li>
              <li><strong>Osteoporosis</strong> — age-related bone loss; even minor falls or coughing can cause vertebral compression fractures in severely osteoporotic bone</li>
              <li><strong>Spinal infection (discitis/osteomyelitis)</strong> — bacterial or tuberculous infection destroys vertebral bone and disc, causing progressive kyphosis and potential cord compression</li>
            </ul>

            <h4>Metastatic Epidural Spinal Cord Compression (MESCC)</h4>
            <p>MESCC is a neurosurgical emergency. When metastatic disease or pathological fracture compresses the spinal cord, the patient may develop rapidly progressive weakness, sensory loss, and loss of bladder/bowel function — a window of hours to days exists before the deficit becomes permanent. The PATCHELL trial demonstrated that circumferential decompressive surgery followed by radiotherapy produced significantly better ambulatory outcomes than radiotherapy alone for selected patients with MESCC. Dr. Rajesh Reddy provides emergency assessment and surgical decompression for MESCC cases from across Telangana and Andhra Pradesh.</p>
