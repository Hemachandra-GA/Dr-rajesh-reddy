          <section id="what-is-spine-fracture" class="pillar-section">
            <h2>What Is a Spine Fracture?</h2>
            <img src="images/spine-fracture-treatment/what_is_spain_fracture.webp" alt="What Is a Spine Fracture?" style="width: 100%; border-radius: 8px; margin-bottom: 20px;">
            <p>The spine is a column of 33 vertebrae stacked from the skull to the pelvis, connected by intervertebral discs, ligaments, and facet joints. Each vertebra consists of a body (the weight-bearing anterior block), a posterior arch (protecting the spinal cord within the spinal canal), and bony processes for muscle attachment and articulation with adjacent vertebrae. A spine fracture occurs when one or more of these structures breaks — from traumatic force, pathological weakening, or a combination of both.</p>
            <p>The critical question with any spinal fracture is not just whether the bone is broken, but whether the fracture is stable or unstable, and whether the spinal cord, nerve roots, or cauda equina are at risk. A stable fracture — one that does not threaten to shift further and compress neural structures — may be managed without surgery. An unstable fracture — one that is likely to displace or has already caused neurological compromise — requires surgical stabilisation, decompression, or both.</p>
            
            <h3>The Three-Column Model of Spinal Stability</h3>
            <p>Denis's three-column model provides a practical framework for assessing spinal fracture stability. The spine is divided into three longitudinal columns:</p>
            <ul class="pillar-list">
              <li><strong>Anterior column:</strong> anterior two-thirds of the vertebral body and the anterior longitudinal ligament</li>
              <li><strong>Middle column:</strong> posterior one-third of the vertebral body, posterior wall, and posterior longitudinal ligament</li>
              <li><strong>Posterior column:</strong> pedicles, facet joints, laminae, spinous processes, and posterior ligamentous complex</li>
            </ul>
            <p>A fracture involving two or more columns is considered unstable and typically requires surgical treatment. Compression fractures involving only the anterior column are generally stable; burst fractures involving the anterior and middle columns with retropulsion of bone into the spinal canal are unstable and carry neurological risk.</p>
          </section>

