            <h2>Recovery After Spine Fracture Treatment</h2>
            <img src="images/spine-fracture-treatment/Recovery_and_rehabilitation-1.webp" alt="Recovery After Spine Fracture Treatment" style="width: 100%; border-radius: 8px; margin-bottom: 20px;">
            
            <h3>After Conservative Management (Bracing)</h3>
            <ul class="pillar-list">
              <li><strong>Immobilisation period:</strong> 6–12 weeks depending on fracture type and location</li>
              <li>Serial X-rays at 6 weeks and 12 weeks to confirm healing and absence of progressive deformity</li>
              <li>Physiotherapy commences from week 2–4 — initially gentle core activation and mobilisation within brace</li>
