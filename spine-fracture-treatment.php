          <section id="spine-fractures-by-region" class="pillar-section">
            <h2>Spine Fractures by Region</h2>

            <h3>Cervical Spine Fractures (C1–C7)</h3>
            <p>Fractures of the cervical spine — the seven vertebrae between the skull and the upper thorax — carry the highest neurological risk of any spinal injury. The cervical spinal cord lies within a relatively narrow canal, and displacement of a fractured cervical vertebra can cause tetraplegia (paralysis of all four limbs) or death from respiratory failure if the injury is at or above C4, where the phrenic nerve (which drives breathing) originates.</p>
            <p>Upper cervical injuries (C1–C2) are anatomically distinct. Jefferson fractures of C1 (burst fracture of the atlas) and odontoid fractures of C2 carry instability risk at the craniocervical junction. Hangman's fractures — bilateral pedicle fractures of C2 from hyperextension — are paradoxically often neurologically intact because the canal widens at C2. Subaxial cervical fractures (C3–C7) are more commonly associated with disc injury, cord compression, and neurological deficit.</p>
            <ul class="pillar-list">
              <li>Emergency stabilisation of the cervical spine — in a rigid collar or on a spine board — is mandatory from the scene of injury until imaging confirms stability or surgical fixation is performed</li>
              <li>MRI is essential in any cervical fracture with neurological symptoms — to assess cord signal change (oedema or contusion), disc herniation into the canal, and ligamentous injury not visible on CT</li>
              <li>High-dose methylprednisolone (within 8 hours of injury) is controversial and institution-specific; discuss with Dr. Rajesh Reddy</li>
            </ul>

            <h3>Thoracic Spine Fractures (T1–T12)</h3>
            <p>The thoracic spine is naturally more rigid than the cervical or lumbar spine — braced by the rib cage — making it more resistant to fracture but also less tolerant of displaced fractures, as the thoracic spinal canal is narrower relative to the cord. The thoracic cord has a relatively poor blood supply compared to the cervical and lumbar regions, making it more vulnerable to ischaemic injury when compressed.</p>
            <p>Thoracic fractures most commonly occur at the thoracolumbar junction (T11–L2) — the transition zone between the rigid thoracic spine and the more mobile lumbar spine, where stress concentrates during forward flexion and axial load. Burst fractures of the thoracolumbar junction are among the most common surgically treated spinal injuries in young adults following road traffic accidents and falls from height.</p>

            <h3>Lumbar Spine Fractures (L1–L5)</h3>
            <p>Lumbar fractures below L1 involve the cauda equina — the bundle of nerve roots descending from the conus medullaris — rather than the spinal cord itself. Cauda equina injury from a lumbar burst fracture may cause lower limb weakness and numbness, bladder and bowel dysfunction, and sexual dysfunction — but the potential for neurological recovery is generally better than with cord injuries, as peripheral nerve roots have greater regenerative capacity than spinal cord.</p>
            <p>L4–L5 and L5–S1 fractures — particularly in the context of pre-existing degenerative disease — may cause significant nerve root compression requiring decompression at the time of stabilisation.</p>
            <div class="note-box" style="background:#fefce8; border-left:4px solid #ca8a04; padding:16px; margin:24px 0; border-radius:4px;">
              <strong>EMERGENCY:</strong> Any patient who develops new weakness, numbness, or loss of bladder/bowel control after a spine fracture — whether minutes or hours after the injury — has a neurological emergency. Contact emergency services or the nearest neurosurgical unit immediately. The window for neurological recovery is time-critical.
            </div>

            <h3>Spinal Cord Injury: Assessing Neurological Status</h3>
            <p>When a spinal fracture has caused or may be causing spinal cord injury, a standardised neurological assessment is performed using the ASIA (American Spinal Injury Association) Impairment Scale. This scale classifies the completeness and level of the spinal cord injury, guides prognosis, and is used to track neurological recovery over time:</p>
            <div class="table-responsive-wrapper" style="overflow-x:auto;-webkit-overflow-scrolling:touch;width:100%;margin-bottom:24px;">
              <table class="pillar-table" style="min-width:500px;">
                <thead>
                  <tr>
                    <th>ASIA Grade</th>
                    <th>Classification</th>
                    <th>Clinical Description</th>
                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <td><strong>A</strong></td>
                    <td>Complete</td>
                    <td>No motor or sensory function preserved in sacral segments S4–S5</td>
                  </tr>
                  <tr>
                    <td><strong>B</strong></td>
                    <td>Sensory Incomplete</td>
                    <td>Sensory but no motor function preserved below neurological level, including S4–S5</td>
                  </tr>
                  <tr>
                    <td><strong>C</strong></td>
                    <td>Motor Incomplete</td>
                    <td>Motor function preserved below neurological level — more than half of key muscles below level have &lt; Grade 3 strength</td>
                  </tr>
                  <tr>
                    <td><strong>D</strong></td>
                    <td>Motor Incomplete</td>
                    <td>Motor function preserved below neurological level — at least half of key muscles have Grade 3 or greater strength</td>
                  </tr>
                  <tr>
                    <td><strong>E</strong></td>
                    <td>Normal</td>
                    <td>Motor and sensory function normal</td>
                  </tr>
                </tbody>
              </table>
            </div>
            <p>The distinction between complete (ASIA A) and incomplete (ASIA B–D) cord injury is the most clinically important — incomplete injuries retain some potential for neurological recovery with timely decompression and rehabilitation, while complete injuries have very limited recovery potential regardless of intervention. However, the surgical goal in both — to decompress the cord and stabilise the spine — remains the same: preventing further injury and creating the best possible environment for whatever recovery is biologically possible.</p>

            <h3>Neurogenic Shock</h3>
            <p>High thoracic or cervical spinal cord injuries can cause neurogenic shock — a combination of hypotension (low blood pressure) from loss of sympathetic tone and bradycardia (slow heart rate) from unopposed vagal activity. Neurogenic shock is distinct from haemorrhagic shock and requires vasopressors (noradrenaline) rather than aggressive fluid resuscitation to maintain spinal cord perfusion pressure. Management of neurogenic shock in the ICU — targeting mean arterial pressure > 85 mmHg for 7 days after SCI — is a critical determinant of neurological outcome.</p>
          </section>

          <section id="diagnosing" class="pillar-section">
            <h2>Diagnosing a Spine Fracture: The Workup</h2>
            <img src="images/spine-fracture-treatment/how_is_a_spine_frcture_diagosed.webp" alt="Diagnosing a Spine Fracture: The Workup" style="width: 100%; border-radius: 8px; margin-bottom: 20px;">
            
            <h3>Plain X-Rays</h3>
            <p>Anteroposterior and lateral plain X-rays of the symptomatic spinal region are the first-line investigation in the emergency setting — particularly for cervical spine clearance after trauma. They identify gross fractures, dislocations, and loss of vertebral height, but miss many fractures — particularly those involving the posterior elements or at complex anatomical sites (C1–C2, cervicocranial junction).</p>

            <h3>CT Scan — The Gold Standard for Fracture Characterisation</h3>
            <p>CT of the spine with sagittal and coronal reconstructions provides the most detailed three-dimensional picture of the bony injury — fracture pattern, degree of comminution, canal compromise from retropulsed fragments, and involvement of the posterior elements and facet joints. Thin-slice CT (1mm) is essential for upper cervical fractures. CT angiography of the neck vessels (CTA) should be performed whenever a cervical fracture involves the transverse foramen, as vertebral artery injury occurs in approximately 20–30% of such cases.</p>

            <h3>MRI — Essential for Neurological Assessment</h3>
            <p>MRI of the spine is mandatory whenever there is a neurological deficit, or whenever the extent of ligamentous injury is uncertain. It uniquely shows: spinal cord signal change (oedema on T2 — indicating cord injury and guiding prognosis), disc herniation into the canal, posterior ligamentous complex disruption (a marker of instability), haematoma, and epidural compression. STIR sequences are particularly sensitive for ligamentous and soft tissue injury.</p>

            <h3>CT Myelography</h3>
            <p>In patients who cannot undergo MRI (pacemaker, certain implants), CT myelography — injection of contrast into the CSF followed by CT — provides detailed imaging of the neural elements within the spinal canal and identifies sites of cord or root compression.</p>
          </section>

