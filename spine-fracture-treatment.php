              <li><strong>Mobilisation:</strong> walking permitted the same day or next morning</li>
              <li>Return to normal activity: 1–2 weeks; avoid heavy lifting for 4–6 weeks</li>
              <li>Osteoporosis treatment: commenced or optimised before or at the time of the procedure</li>
            </ul>

            <h3>After Minimally Invasive Fixation (MISS)</h3>
            <ul class="pillar-list">
              <li><strong>Hospital stay:</strong> 2–4 days</li>
              <li><strong>Mobilisation:</strong> walking with physiotherapy support from day 1–2</li>
              <li><strong>Brace:</strong> TLSO brace for 6–12 weeks depending on fracture type</li>
              <li>Return to desk work: 4–6 weeks; physically demanding work: 3–6 months</li>
              <li>Implant removal: generally not required; screws are typically left permanently</li>
