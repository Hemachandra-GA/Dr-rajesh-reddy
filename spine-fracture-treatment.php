            <h3>After Open Decompression and Fusion</h3>
            <ul class="pillar-list">
              <li><strong>Hospital stay:</strong> 5–7 days; longer after combined anterior-posterior procedures</li>
              <li>Mobilisation with physiotherapy: from day 1–2</li>
              <li>Post-operative brace: typically 6–12 weeks</li>
              <li>Neurological recovery: incomplete SCI — improvement may occur over 12–24 months; rehabilitation is the mainstay</li>
              <li>Return to work: 3–6 months for desk work; 6–12 months for physical work</li>
            </ul>
