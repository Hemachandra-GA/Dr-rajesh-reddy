          <section id="how-it-works" class="pillar-section">
            <h2 class="pillar-section-title">What Is Flow Diversion and How Does It Work?</h2>

            <p>
              A flow diverter is a high-porosity braided mesh stent deployed within the parent artery — the artery from which the aneurysm arises — across the aneurysm neck. Unlike conventional stents, flow diverters have very high metal surface coverage — typically 30–35% of the luminal wall — achieved by braiding dozens of fine metal wires into a mesh tube.
            </p>

            <h3 style="font-size: 1.2rem; color: #0066cc; margin-top: 20px; margin-bottom: 12px;">The Two Mechanisms of Flow Diversion</h3>

            <ol style="line-height: 1.8; color: #333; margin-bottom: 20px; padding-left: 20px;">
              <li style="margin-bottom: 12px;">
                <strong>Haemodynamic flow redirection:</strong> The high metal coverage acts as a flow barrier at the aneurysm neck. Inflow into the aneurysm sac is reduced by approximately 60–80% immediately after deployment. Blood that previously entered the sac with each heartbeat is redirected along the stent into the distal artery, no longer pushing against the aneurysm wall.
              </li>
              <li>
                <strong>Progressive aneurysm thrombosis and neointimal healing:</strong> With reduced flow in the sac, blood stagnates and progressively clots. Over weeks to months, the thrombus organises and is replaced by connective tissue. Simultaneously, endothelial cells migrate across the stent struts at the aneurysm neck, forming a new arterial wall that permanently seals the aneurysm from the circulation — a healing process, not just a mechanical blockage.
              </li>
            </ol>

            <div style="background-color: #f8fbff; border-left: 4px solid #0066cc; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              <strong>Key Principle:</strong> The key insight of flow diversion is that it treats the parent artery, not the aneurysm, with preservation of flow through the side branches in majority of cases. By remodelling the diseased arterial segment where the aneurysm arose, flow diversion achieves durable occlusion through biological healing — which is why its results for large and complex aneurysms are superior to those of conventional coiling.
            </div>

