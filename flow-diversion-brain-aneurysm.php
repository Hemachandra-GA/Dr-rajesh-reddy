          <section id="procedure" class="pillar-section">
            <h2 class="pillar-section-title">The Flow Diversion Procedure: What Happens</h2>

            <h3>Pre-Procedure: Dual Antiplatelet Preparation</h3>
            <p>
              Flow diversion requires mandatory dual antiplatelet therapy before the procedure. Aspirin 150 mg and clopidogrel 75 mg or Ticagrelor 180 mg/day are started 5–7 days before planned deployment. Platelet function testing (VerifyNow P2Y12 assay) is performed on the day of procedure in selected cases to confirm adequate clopidogrel effect — poor responders may require prasugrel or ticagrelor. Inadequate antiplatelet effect at deployment significantly increases the risk of in-stent thrombosis.
            </p>

            <h3>DSA and 3D Angiography — Sizing the Device</h3>
            <p>
              A high-quality 3D rotational DSA is essential for flow diverter sizing. The diameter and length of the device must precisely match the parent artery — too large and it will not fully appose the vessel wall; too small and it will be undersized at the neck. Device sizing software provides measurements of the parent artery diameter proximal and distal to the aneurysm, neck width, and the length of artery requiring coverage.
            </p>

            <h3>Device Deployment</h3>
            <p>
              Under general anaesthesia, a guide catheter is positioned in the internal carotid or vertebral artery. A microcatheter is navigated past the aneurysm neck into the distal parent artery. The flow diverter is deployed by slowly retracting the microcatheter — allowing the mesh to expand and conform to the arterial wall across the aneurysm neck. Correct apposition is confirmed with contrast injections and DSA. An immediately post-deployment DSA confirms neck coverage and visible flow reduction in the sac. Intraprocedural Dyna CT or Vaso CT softwares help in assessing apposition of stent to the vessel wall.
            </p>

            <h3>Adjunctive Coiling</h3>
            <p>
              For aneurysms more than 1.5 cm where spontaneous thrombosis after flow diversion alone would be slow, adjunctive coiling within the sac may be performed at the same sitting. The coils partially fill the sac and accelerate thrombosis, reducing the risk of delayed aneurysm rupture during the progressive occlusion phase and also helping to decompress the mass effect more rapidly.
            </p>

