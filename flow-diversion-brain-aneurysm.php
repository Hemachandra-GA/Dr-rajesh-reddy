          <section id="risks" class="pillar-section">
            <h2 class="pillar-section-title">Risks of Flow Diversion: An Honest Assessment</h2>

            <p>
              Flow diversion is a more complex procedure than standard coiling and carries specific risks that patients must understand:
            </p>

            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li style="margin-bottom: 10px;">
                <strong>Thromboembolic stroke:</strong> The most significant complication — approximately 3–6% across major series. Pre-procedural dual antiplatelet therapy and platelet function testing are the primary preventive measures.
              </li>
              <li style="margin-bottom: 10px;">
                <strong>Delayed aneurysm rupture:</strong> A paradoxical but rare complication (approximately 1–2%) — particularly in large and giant aneurysms — during the progressive thrombosis phase. Adjunctive coiling may reduce this risk.
              </li>
              <li style="margin-bottom: 10px;">
                <strong>Perforator artery occlusion:</strong> Small perforating arteries covered by the device mesh may rarely be affected — approximately 1–3% in published series. Modern flow diverters are designed to preserve perforator flow.
              </li>
              <li style="margin-bottom: 10px;">
                <strong>In-stent stenosis or thrombosis:</strong> Occurs in approximately 3–5% of cases. Stenosis is usually asymptomatic; acute thrombosis requires emergency endovascular management.
              </li>
              <li style="margin-bottom: 10px;">
                <strong>Incomplete occlusion:</strong> Approximately 10–15% of aneurysms do not achieve complete occlusion at 24 months — requiring assessment for supplemental coiling or a second flow diverter.
              </li>
            </ul>

            <div style="background-color: #f8fbff; border-left: 4px solid #0066cc; padding: 16px 18px; margin: 20px 0; border-radius: 4px;">
              Once complete aneurysm occlusion is confirmed on follow-up angiography, the long-term outcome is excellent — with very low rates of rebleeding and durable aneurysm exclusion. This contrasts with large aneurysms managed with coiling alone, where recanalisation and retreatment rates remain high indefinitely.
            </div>
          </section>

