              Follow-up angiography after flow diversion is not optional — it is an integral part of the treatment. Unlike a surgical clip that provides an immediately verifiable mechanical seal, flow diversion relies on progressive biological occlusion that must be confirmed on imaging. Skipping follow-up creates unacceptable uncertainty.
