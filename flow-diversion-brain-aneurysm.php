            <h3 style="font-size: 1.2rem; color: #0066cc; margin-top: 16px; margin-bottom: 12px;">Occlusion Rates</h3>
            <ul style="line-height: 1.8; color: #333; margin-bottom: 20px; padding-left: 20px;">
              <li><strong>PUFS trial (Pipeline for Uncoilable or Failed Aneurysms):</strong> 73% complete occlusion at 6 months and 86.8% at 180 days for large/giant uncoilable ICA aneurysms — the landmark study that led to FDA approval</li>
              <li><strong>IntrePED registry:</strong> 5.6% major stroke or death rate in 793 patients across 21 centres — establishing real-world safety data</li>
              <li><strong>PREMIER trial (Pipeline for ICA aneurysms 7–12 mm):</strong> 76.9% complete occlusion at 12 months — expanding Pipeline indication beyond large/giant aneurysms</li>
              <li><strong>Multiple single-centre series:</strong> 85–93% complete occlusion at 12 months for paraclinoid ICA aneurysms — the best flow diversion results reported for any anatomical location</li>
            </ul>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Sac Shrinkage After Flow Diversion</h3>
            <p>
              One of the most clinically rewarding outcomes of successful flow diversion — particularly for large and giant aneurysms causing mass effect — is progressive shrinkage of the aneurysm sac over months to years. As the organised thrombus reabsorbs and the sac collapses, symptoms from compression — visual loss, cranial nerve palsies, headache, hemiparesis — gradually improve. For giant partially thrombosed aneurysms, sac shrinkage also eliminates the embolic source responsible for TIAs and reduces seizure frequency. This shrinkage is a unique advantage of flow diversion over coiling, where the sac volume is maintained by the coil mass.
            </p>

            <h3 style="font-size: 1.2rem; color: #1d1d1f; margin-top: 24px; margin-bottom: 12px;">Transient Worsening After Flow Diversion</h3>
            <p>
              A distinctive phenomenon after flow diversion of large and giant aneurysms is transient worsening of mass effect symptoms in the weeks after treatment. As the aneurysm sac thromboses, the clot may initially swell — temporarily increasing volume and worsening compression on adjacent structures (optic nerve, cranial nerves, brainstem, or adjacent cortex). This perianeurysmal oedema is managed with short courses of oral corticosteroids and typically resolves as the thrombus organises and shrinks. Patients should be counselled that symptoms may transiently worsen before improving — this is expected and does not indicate treatment failure.
            </p>
