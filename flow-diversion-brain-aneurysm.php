            <ul style="line-height: 1.8; color: #333; padding-left: 20px;">
              <li style="margin-bottom: 10px;">
                <strong>6 months:</strong> DSA — primary assessment of aneurysm occlusion; confirms device apposition and absence of in-stent stenosis
              </li>
              <li style="margin-bottom: 10px;">
                <strong>12 months:</strong> DSA or MRA or CTA — second assessment; most aneurysms that will achieve complete occlusion have done so by this point
              </li>
              <li style="margin-bottom: 10px;">
                <strong>24 months:</strong> MRA or CTA — confirms sustained occlusion; identifies late incomplete occlusion requiring retreatment
              </li>
              <li style="margin-bottom: 10px;">
