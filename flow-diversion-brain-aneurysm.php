            <p>
              Dual antiplatelet therapy — aspirin (75–150 mg) and clopidogrel (75 mg) or Ticagrelor 180 mg/day — is required for 6 months after flow diverter deployment. After 6 months, clopidogrel is stopped and aspirin continued for at least 3–5 years or indefinitely (duration at the discretion of the treating doctor). Stopping either medication without consulting Dr. Rajesh Reddy risks in-stent thrombosis. Any planned surgical procedure during the dual antiplatelet period — including dental surgery — must be discussed in advance.
            </p>

