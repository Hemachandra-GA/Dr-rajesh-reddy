                <p class="body-lead">A minor bump on the head can look like nothing at all — no pain, no bleeding, no loss of consciousness. In older adults, though, that "nothing" can turn into something serious weeks later. It's called a chronic subdural hematoma, and it develops so slowly that by the time symptoms show up, most families have long forgotten the fall that caused it.</p>
                
                <p>That's the tricky part. This kind of brain bleed in elderly patients often looks like a stroke, dementia, or just old age catching up. Knowing what it actually looks like can mean the difference between catching it early and missing it until it's much harder to treat.</p>

                <h2>What Is a Chronic Subdural Hematoma?</h2>
                <p>Blood collects between the brain and the dura, its outer covering. A minor knock to the head can tear small veins in this space, and instead of bleeding out quickly, they leak slowly — days, sometimes weeks. As the blood pools, it starts pressing on the brain.</p>
                <p>Compare that to an acute bleed, which happens fast and gets noticed fast. A chronic one hides.</p>

                <h2>Why Are Older Adults More at Risk?</h2>
                <p>Because it is one. The bleeding starts small — small enough to cause no symptoms at all. Over the following days or weeks, it keeps adding to itself, a little more blood, a little more inflammation, a little more swelling. Pressure on the brain builds gradually, and so do the symptoms.</p>
                <p>That slow build is exactly why it gets missed.</p>

                <h2>Symptoms That Look Like a Stroke — or Dementia</h2>
                <p>This is where diagnosis gets hard — <strong>subdural hematoma symptoms</strong> overlap heavily with other neurological conditions:</p>
                <ul>
                    <li>Persistent headache</li>
                    <li>Growing confusion</li>
                    <li>Memory trouble</li>
                    <li>Changes in personality or behavior</li>
                    <li>Trouble walking</li>
                    <li>Loss of balance</li>
                    <li>Weakness on one side of the body</li>
                    <li>Slurred speech</li>
                    <li>Drowsiness</li>
                    <li>Reduced alertness</li>
                    <li>Seizures, in some cases</li>
                </ul>
                <p>Families often chalk this up to aging, or Parkinson's, or depression. Sometimes the weakness or slurred speech comes on fast enough that it genuinely looks like a stroke — and that resemblance is part of what delays the right diagnosis.</p>

                <h2>When Should Families Get Worried?</h2>
                <p>Family members usually notice the change before anyone else does — a parent who seems "off," more forgetful, unsteady on their feet.</p>
                <p>If an older adult shows any neurological symptoms after a fall or head bump, even one that seemed like nothing, get it checked. Don't wait to see if it passes.</p>
                <p>Watch for:</p>
                <ul>
                    <li>New confusion</li>
                    <li>Forgetfulness that's getting worse, not better</li>
                    <li>Trouble walking</li>
                    <li>Sudden weakness</li>
                    <li>Headaches that won't quit</li>
                    <li>Increasing sleepiness</li>
                    <li>Personality changes</li>
                    <li>Trouble speaking</li>
                </ul>
                <p>Getting evaluated early is what prevents this from turning into a real crisis.</p>

                <h2>How Is It Diagnosed?</h2>
                <p>A neurological exam comes first, followed by imaging. A CT scan is usually the fastest way to spot the blood collection, and in most cases it's all that's needed. If the picture is still unclear, an MRI can fill in the gaps.</p>
                <p>Anyone with unexplained neurological symptoms after a head injury should get imaging sooner rather than later.</p>

                <h2>Can It Be Treated?</h2>
                <p>Yes — and often quite successfully, especially when caught early.</p>
                <p><strong>Watch and wait.</strong> Very small hematomas with mild or no symptoms can sometimes just be monitored with follow-up exams and repeat scans.</p>
                <p><strong>Surgery.</strong> Larger ones, or ones pressing hard enough on the brain to cause real symptoms, usually need drainage. The standard approach is a burr hole — one or two small openings drilled into the skull to let the blood out. It sounds more alarming than it is; for a minimally invasive procedure, it tends to bring fast relief. More complex cases occasionally call for more extensive surgery.</p>
                <p><strong>Middle Meningeal Artery (MMA) Embolisation.</strong> A newer, minimally invasive option that's gaining ground, especially for hematomas that keep coming back after drainage or for patients who aren't great candidates for open surgery. A catheter is guided through the blood vessels up to the middle meningeal artery — the vessel that feeds the membrane lining the hematoma — and it's blocked off. Cutting off that blood supply starves the hematoma of what it needs to keep refilling, so the body can gradually reabsorb it. No incision on the skull, shorter recovery, and it's proving especially useful alongside surgery in patients at high risk of recurrence.</p>

                <h2>What Does Recovery Look Like?</h2>
                <p>For a lot of patients, recovery is genuinely dramatic. Confusion lifts, balance comes back, headaches fade, speech and movement return toward normal.</p>
                <p>How much and how fast depends on:</p>
                <ul>
                    <li>Age</li>
                    <li>Overall health</li>
                    <li>How large the hematoma was</li>
                    <li>How long symptoms went untreated</li>
                    <li>Whether other neurological issues are in the mix</li>
                </ul>
                <p>Catch it early, and the odds tilt strongly in the patient's favor.</p>

                <h2>Can It Be Prevented?</h2>
                <p>Not always — but the risk can be brought down:</p>
                <ul>
                    <li>Make the home safer to cut down on falls</li>
                    <li>Use a cane or walker if one's recommended</li>
                    <li>Review blood thinners with a doctor regularly</li>
                    <li>Get any head injury in an older adult checked out</li>
                    <li>Don't brush off neurological symptoms after a fall, even minor ones</li>
                </ul>
                <p>Even a bump that looks harmless is worth watching for a few weeks afterward.</p>

                <h2>A Bleed That Hides Well</h2>
                <p>Chronic subdural hematoma earns the nickname "silent bleed" honestly — it can take weeks to show itself, and by then it's easy to mistake for a stroke, dementia, or just getting older. That confusion is what delays treatment.</p>
                <p>The good news: caught early, most patients recover well. If someone in your family develops confusion, weakness, memory trouble, or a change in how they walk after even a small bump to the head, don't wait it out. Get them seen.</p>

