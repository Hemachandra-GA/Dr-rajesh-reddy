                <p class="body-lead">A stroke is a medical emergency that requires rapid triage. Every minute is critical—delayed medical care results in the loss of approximately 1.9 million brain cells per minute. Understanding stroke types, risk indicators, and the FAST diagnostic rule can save lives.</p>
                
                <h2>What is a Stroke?</h2>
                <p>A stroke occurs when the blood supply to a part of the brain is suddenly interrupted or reduced, depriving brain tissue of essential oxygen and nutrients. Within minutes, brain cells begin to die.</p>
                <p>Broadly, strokes are classified into two main clinical types:</p>
                <ul>
                    <li><strong>Ischemic Stroke:</strong> The most common form (accounting for approximately 85% of cases), caused by a blood clot obstructing an artery supplying blood to the brain.</li>
                    <li><strong>Hemorrhagic Stroke:</strong> Caused by a weakened blood vessel rupturing and bleeding into the surrounding brain parenchyma. Common triggers include untreated high blood pressure or ruptured brain aneurysms.</li>
                </ul>

