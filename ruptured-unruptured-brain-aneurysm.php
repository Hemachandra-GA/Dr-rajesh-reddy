          <section id="treatment-differences" class="pillar-section">
            <h2 class="pillar-section-title">How Treatment Differs: Ruptured vs. Unruptured</h2>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/ruptured-vs-unruptured-brain-aneurysm/Treatment_options.webp" alt="Endovascular Coiling Treatment" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>Treatment of Ruptured Aneurysm</h3>
            <p>For a ruptured aneurysm, the first priority is always to secure the aneurysm as rapidly as possible to prevent rebleeding. The two main treatment options — endovascular coiling and microsurgical clipping — are both aimed at permanently excluding the aneurysm from the circulation.</p>
            <ul>
              <li><strong>Endovascular coiling:</strong> Preferred in most ruptured aneurysm cases. The ISAT trial demonstrated significantly better neurological outcomes for coiling versus clipping in patients with ruptured aneurysms suitable for both treatments. Coiling avoids craniotomy and general anaesthesia for a prolonged open surgery in an already critically ill patient — reducing physiological stress at a vulnerable time.</li>
              <li><strong>Microsurgical clipping:</strong> Preferred when the aneurysm anatomy is not suitable for coiling (wide neck, complex morphology, incorporated branch vessels), when there is an associated intracerebral haematoma requiring surgical evacuation, or when the aneurysm is at the MCA bifurcation — where clip geometry and surgical access are often superior to catheter access.</li>
            </ul>
            <p>The choice between coiling and clipping for ruptured aneurysms is determined at the emergency multidisciplinary meeting, weighing the aneurysm anatomy on CTA, the patient's clinical grade, and the available expertise. Dr. Rajesh Reddy's ability to perform both procedures allows him to make this decision based on what is genuinely best for the patient.</p>

            <h3>Treatment of Unruptured Aneurysm</h3>
            <p>For unruptured aneurysms, the decision is more nuanced — and includes the option of observation. Treatment is not always the right answer. When treatment is indicated, the full range of options is available:</p>
            <ul>
              <li><strong>Observation:</strong> For small, low-risk aneurysms — particularly in elderly or medically unfit patients. Regular MRA surveillance (typically annually for 2 years, then every 2 years if stable) monitors for growth, which is the trigger for reassessment.</li>
              <li><strong>Endovascular coiling:</strong> First choice for most saccular aneurysms suitable for catheter access. Shorter recovery (1–3 days), no open surgery, and excellent long-term occlusion rates for appropriately selected aneurysms.</li>
              <li><strong>Flow diversion (Pipeline device / SILK / DERIVO / p64 / Surpass / FRED):</strong> Preferred for large, giant, or fusiform aneurysms where coiling is impractical. Particularly effective for paraclinoid ICA aneurysms.</li>
              <li><strong>Intrasaccular flow diversion devices (WEB, Contour, Artisse, Seal):</strong> Particularly suited to wide-neck bifurcation aneurysms (MCA, basilar tip, AComm) — a single intrasaccular device requiring no stent and no dual antiplatelet therapy.</li>
              <li><strong>Microsurgical clipping:</strong> Preferred for younger patients (&lt; 50) where the lifelong durability of clipping is advantageous; for MCA aneurysms where surgical anatomy is favourable; and for wide-neck aneurysms not suitable for catheter-based treatment.</li>
            </ul>
          </section>

