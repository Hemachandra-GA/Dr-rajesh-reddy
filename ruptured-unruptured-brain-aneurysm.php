            <h3>Outcome After Ruptured Aneurysm</h3>
            <p>The overall prognosis after aneurysm rupture and SAH depends heavily on the clinical grade at presentation (Hunt & Hess / WFNS scale):</p>
            <ul>
              <li><strong>Good-grade SAH (Hunt & Hess I–II):</strong> approximately 70–80% of patients achieve good neurological outcome with early treatment</li>
              <li><strong>Moderate-grade SAH (Hunt & Hess III):</strong> approximately 50–60% achieve good outcome; cognitive and fatigue-related symptoms often persist for months</li>
              <li><strong>Poor-grade SAH (Hunt & Hess IV–V):</strong> outcomes are guarded; approximately 20–40% achieve meaningful functional recovery; a proportion are left with significant disability or die</li>
            </ul>
            <p>Even patients who make a good physical recovery after SAH frequently experience prolonged cognitive symptoms — memory difficulties, concentration problems, fatigue, depression, and anxiety — that are not visible on imaging but significantly impact quality of life. These are now well-recognised features of post-SAH syndrome and should be proactively addressed in follow-up care.</p>
