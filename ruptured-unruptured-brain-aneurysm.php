          <section id="unruptured-evaluation" class="pillar-section">
            <h2 class="pillar-section-title">The Unruptured Aneurysm: Careful Evaluation, Not Panic</h2>
            <p>An unruptured brain aneurysm is a fundamentally different clinical situation. There is no emergency, no blood in the brain, and no immediate threat to life. What there is, is a decision to be made — and time to make it thoughtfully.</p>
            <p>The core question for every unruptured aneurysm is: <strong>does the risk of treating it outweigh the risk of leaving it?</strong> This is not a simple calculation. It requires integrating the aneurysm's size, location, shape, the patient's age and health, their individual risk factors, and the technical risks of the proposed treatment.</p>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/ruptured-vs-unruptured-brain-aneurysm/How_to_diagnosed.webp" alt="Accurate Diagnosis for Unruptured Brain Aneurysms" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>How Unruptured Aneurysms Are Discovered</h3>
            <ul>
              <li><strong>Incidental discovery:</strong> The most common scenario. An MRI or CT done for a headache, head injury, sinus symptoms, or another neurological condition reveals an aneurysm that has been present — silently — for an unknown period. This is understandably alarming for patients, but the key message is that an incidental aneurysm is not an emergency: there is time to evaluate it carefully.</li>
              <li><strong>Screening:</strong> Patients with a family history of brain aneurysm or SAH (particularly those with two or more affected first-degree relatives), or with conditions known to be associated with aneurysms (polycystic kidney disease, neurofibromatosis Type 1, connective tissue disorders), may undergo proactive screening with MRA — discovering aneurysms before they cause any symptom.</li>
              <li><strong>Symptomatic unruptured aneurysm:</strong> A minority of unruptured aneurysms cause symptoms through mass effect — compressing adjacent structures. A third nerve palsy (drooping eyelid + dilated pupil), progressive visual loss, or facial pain may indicate an enlarging aneurysm that requires more urgent evaluation, though still not the same emergency as rupture.</li>
            </ul>

            <h3>The Natural History of Unruptured Aneurysms: What Does the Evidence Say?</h3>
            <p>Several large international studies — including the International Study of Unruptured Intracranial Aneurysms (ISUIA) and the UCAS Japan study — have mapped the natural history of unruptured aneurysms. Key findings:</p>
            <ul>
              <li>Small aneurysms (&lt; 7 mm) in the anterior circulation have an annual rupture risk of approximately 0.1–0.5% — meaning most will never rupture in the patient's lifetime</li>
              <li>Aneurysms &ge; 7 mm carry significantly higher annual rupture risk — increasing sharply with size</li>
              <li>Posterior circulation aneurysms (basilar tip, PICA) rupture more frequently than anterior circulation aneurysms of the same size</li>
              <li>Irregular shape, daughter sac, or high aspect ratio are independent predictors of rupture risk, regardless of size</li>
              <li>Growth on serial imaging is the single most important indicator that an aneurysm should be treated — any documented growth warrants intervention</li>
            </ul>
            <p>A small aneurysm with low-risk features in an elderly patient may be entirely appropriate for observation. The same size aneurysm in a 35-year-old smoker with a family history of SAH and an irregular daughter sac warrants a very different conversation. Dr. Rajesh Reddy individualises every risk assessment — there is no single size or location cutoff that applies to all patients.</p>
          </section>

