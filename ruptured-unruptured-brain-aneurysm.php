          <section id="recap" class="pillar-section">
            <h2 class="pillar-section-title">A Brief Recap: What Is a Brain Aneurysm?</h2>
            <p>A brain (intracranial) aneurysm is a weakened, bulging section of a blood vessel wall within the brain — most commonly at the branching points of the large arteries forming the Circle of Willis at the base of the brain. The aneurysm is essentially a bubble formed where the muscular wall of the artery has thinned or failed, leaving only the inner and outer layers to hold back arterial blood pressure.</p>
            <p>The critical question for every aneurysm is whether it has ruptured. A ruptured aneurysm has burst — releasing blood under high pressure into the subarachnoid space surrounding the brain, causing subarachnoid hemorrhage (SAH). An unruptured aneurysm is intact — it has not yet burst, though it carries some risk of doing so in the future.</p>
            
            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/ruptured-vs-unruptured-brain-aneurysm/what_is_brain_aneurysm.webp" alt="Brain Aneurysm Anatomy" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <p>The same anatomical lesion — a brain aneurysm — produces two completely different clinical situations depending on whether it has ruptured. This is why the management of ruptured and unruptured aneurysms follows entirely different pathways, with different urgency, different treatment goals, and different outcome expectations.</p>
          </section>

