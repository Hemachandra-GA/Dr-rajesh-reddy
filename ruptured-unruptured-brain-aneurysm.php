          <section id="ruptured-emergency" class="pillar-section">
            <h2 class="pillar-section-title">The Ruptured Aneurysm: A Life-Threatening Emergency</h2>
            
            <h3>What Happens When an Aneurysm Ruptures</h3>
            <p>When an aneurysm ruptures, blood escapes from the arterial circulation under high systolic pressure into the subarachnoid space — the fluid-filled space between the brain and the arachnoid membrane. This causes an instantaneous, massive spike in intracranial pressure, which is responsible for the hallmark symptom: the thunderclap headache, reaching maximal severity within 1–2 seconds.</p>
            <p>The escaped blood spreads through the basal cisterns and across the brain surface, irritating the meninges and triggering an intense inflammatory response. The body's attempts to control the bleeding cause arterial spasm in adjacent vessels — the beginning of the vasospasm process that will threaten the brain in the days to follow. Meanwhile, if the initial haemorrhage is large enough, blood may also enter the brain itself (intracerebral haematoma) or the ventricular system (intraventricular haemorrhage), compounding the brain injury.</p>

            <div class="pillar-callout" style="background-color: #ffebee; border-left: 5px solid #d32f2f; padding: 20px; border-radius: 8px; margin: 24px 0;">
              <h4 style="color: #c62828; margin-top: 0; margin-bottom: 8px; font-size: 1.1rem;"><i class="fa-solid fa-triangle-exclamation"></i> CRITICAL WARNING: REBLEEDING DANGER</h4>
              <p style="margin: 0; color: #333;">After initial rupture, the soft clot sealing the aneurysm can give way at any moment. Rebleeding carries a mortality of 70–80%. Securing the aneurysm within 24–72 hours is vital.</p>
            </div>

            <h3>Why Rebleeding Is the Most Immediate Danger</h3>
            <p>After the initial rupture, the aneurysm is sealed by a soft clot — a temporary, fragile plug that can give way under normal arterial blood pressure. Rebleeding — a second haemorrhage before the aneurysm is surgically or endovascularly secured — is the most lethal early complication of SAH. The mortality of rebleeding is approximately 70–80%.</p>
            <p>The risk is highest in the first 24 hours (approximately 4%) and remains at 1–2% per day until the aneurysm is treated. This is why early aneurysm treatment — within 24–72 hours of rupture — is the global standard of care. Every hour of delay is a window of rebleeding risk.</p>
            <p>The most important determinants of outcome after aneurysm rupture (in order of priority) are:</p>
            <ol style="margin-left: 20px; margin-bottom: 16px;">
              <li>The initial response of an individual to the bleed, determined by level of alertness and neurological deficits (if any)</li>
              <li>Location of the aneurysmal bleed and its relationship to the surrounding functional areas of the brain</li>
              <li>How quickly the aneurysm is secured (patients treated within 24 hours have significantly lower rebleeding rates and better neurological outcomes)</li>
              <li>Medical facility at which the patient receives treatment</li>
            </ol>
          </section>

