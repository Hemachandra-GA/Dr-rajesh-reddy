          <section id="risk-factors" class="pillar-section">
            <h2 class="pillar-section-title">Modifiable Risk Factors: What You Can Do Right Now</h2>
            <p>Whether your aneurysm is ruptured or unruptured, there are modifiable risk factors that significantly influence both rupture risk and overall cerebrovascular health. Addressing these is part of the management plan regardless of the chosen treatment strategy:</p>

            <figure style="margin: 28px 0; text-align: center;">
              <img src="images/ruptured-vs-unruptured-brain-aneurysm/ruptured_vs_unruptured.webp" alt="Risk Factors for Brain Aneurysms" style="width: 100%; max-width: 860px; height: auto; border-radius: 12px; box-shadow: 0 4px 15px rgba(0,0,0,0.06); display: block; margin: 0 auto;">
            </figure>

            <h3>Blood Pressure Control</h3>
            <p>Hypertension is the single most important modifiable risk factor for brain aneurysm formation, growth, and rupture. High blood pressure exerts continuous mechanical stress on already-weakened arterial walls. Target blood pressure for aneurysm patients is typically &lt; 130/80 mmHg. If you are not already on antihypertensive medication and your blood pressure is elevated, discuss treatment with your doctor immediately — this is one of the most impactful steps you can take.</p>

            <h3>Smoking Cessation</h3>
            <p>Cigarette smoking doubles the risk of aneurysm rupture. Nicotine and the toxic compounds in cigarette smoke promote arterial wall inflammation, enzymatic degradation of the vessel wall, and reduced endothelial repair — all of which weaken the aneurysm wall. Smoking cessation is strongly recommended for all aneurysm patients, whether managed with observation or post-treatment surveillance. The risk reduction from quitting is measurable and significant.</p>

            <h3>Avoiding Exertional Triggers</h3>
            <p>Heavy lifting, vigorous straining (including during defaecation), and explosive physical exertion cause transient spikes in blood pressure and intracranial pressure that can trigger rupture. Patients with known unruptured aneurysms awaiting treatment are advised to avoid heavy exertion, heavy resistance training, and activities involving sustained breath-holding and straining. Light to moderate aerobic exercise is generally safe and beneficial for cardiovascular health.</p>

            <h3>Alcohol and Cocaine Avoidance</h3>
            <p>Chronic heavy alcohol use is associated with increased aneurysm risk. Cocaine use causes acute hypertensive surges that are a recognised trigger for aneurysm rupture. Both should be avoided entirely by patients with known aneurysms.</p>
          </section>

          <!-- Family Screening Section -->
          <section id="family-screening" class="pillar-section">
            <h2 class="pillar-section-title">Should Family Members Be Screened?</h2>
            <p>Brain aneurysms can run in families. The risk of an intracranial aneurysm in a first-degree relative of someone who has had an aneurysm or SAH is 3–7 times higher than the general population risk of approximately 2–3%.</p>

            <h3>When Screening Is Recommended</h3>
            <ul>
              <li><strong>Two or more first-degree relatives</strong> (parents, siblings, children) with confirmed brain aneurysm or SAH — screening with MRA from age 30 is recommended</li>
              <li><strong>One first-degree relative with SAH</strong> — screening may be considered from age 30–40</li>
              <li><strong>Diagnosed genetic conditions</strong> associated with aneurysms: Autosomal Dominant Polycystic Kidney Disease (ADPKD), neurofibromatosis Type 1, Ehlers-Danlos syndrome (vascular type), Marfan syndrome, Coarctation of aorta.</li>
              <li><strong>Patients who have themselves had one aneurysm</strong> — 20–30% have additional aneurysms that should be identified and assessed</li>
            </ul>

            <h3>The Screening Investigation</h3>
            <p>MRA (magnetic resonance angiography), preferably on a 3T MRI, is the standard screening tool — non-invasive, no radiation, no contrast injection, and highly sensitive for aneurysms down to 2–3 mm. If a screening MRA is positive, further characterisation with CTA or DSA follows. A negative MRA at age 30 does not provide lifelong reassurance — repeat screening at 5–10 year intervals may be appropriate for high-risk individuals.</p>
          </section>

