          <section id="treatment-window" class="pillar-section">
            <h2>The Stroke Treatment Window: Why Every Minute Counts</h2>
            <p>The phrase <em>'time is brain'</em> captures a biological reality: in a large vessel ischaemic stroke, approximately <strong>1.9 million neurons die every minute</strong> without treatment. The effective treatment window for different interventions differs:</p>
            <ul class="pillar-list">
              <li><strong>IV thrombolysis (clot-dissolving injection):</strong> 0–4.5 hours from symptom onset (standard); extended to up to 6 hours in selected patients with favourable CT perfusion mismatch profile per 2026 updated AHA/ASA and ESO guidelines. The earlier within this window, the better the outcome. 'Door-to-needle' time — from hospital arrival to treatment — is a key quality metric, with the target being under 60 minutes</li>
              <li><strong>Mechanical thrombectomy (endovascular clot removal):</strong> 0–24 hours in selected patients, based on brain perfusion imaging. For patients with a large area of brain at risk but limited irreversible damage, the window extends to 24 hours from last known well time</li>
              <li><strong>Haemorrhagic stroke — blood pressure control:</strong> Within the first few hours; rapid reduction to systolic &lt;140 mmHg within 1 hour of presentation reduces haematoma expansion in ICH</li>
            </ul>

            <div style="background: #eef7ff; border-left: 4px solid #0066cc; border-radius: 8px; padding: 20px; margin: 24px 0;">
              <h3 style="color: #0066cc; margin-top: 0; font-size: 1.1rem; display: flex; align-items: center; gap: 8px;">
                <i class="fa-solid fa-circle-info"></i> 2026 Guideline Update — BP in Acute Ischaemic Stroke
              </h3>
              <p style="margin-bottom: 0; color: #1e293b;">AHA/ASA and ESO 2026 guidelines do <strong>NOT</strong> recommend aggressive blood pressure lowering in the first 24–48 hours of acute ischaemic stroke. <strong>Permissive hypertension</strong> — allowing BP up to 220/120 mmHg in non-thrombolysed patients — is preferred to maintain perfusion of the ischaemic penumbra. Post-tPA target remains &lt;180/105 mmHg. Aggressive BP lowering risks extending the infarct by reducing pressure to the penumbral zone.</p>
            </div>

            <ul class="pillar-list">
              <li><strong>Carotid endarterectomy after TIA or minor stroke:</strong> Within 48 hours for highest-risk patients; within 2 weeks at the latest — delay significantly reduces the benefit</li>
            </ul>

            <p><strong>What to do if you suspect a stroke:</strong> Call 108 immediately. Do not wait to see if symptoms improve — TIAs and minor strokes often 'recover' temporarily before a devastating stroke occurs within hours. Do not give the patient anything to eat or drink — swallowing may be impaired. Note the exact time symptoms began — this is the most important piece of information for the emergency team.</p>
          </section>

