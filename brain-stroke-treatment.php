          <section id="cvst-overview" class="pillar-section">
            <h2>Cerebral Venous Sinus Thrombosis (CVST): The Often-Missed Stroke</h2>
            <p>Most stroke resources focus exclusively on arterial stroke. Cerebral venous sinus thrombosis (CVST) is a distinct and frequently overlooked form of stroke caused by thrombosis of the cerebral venous sinuses or cortical veins — not arterial occlusion. Because venous drainage is blocked, the brain develops venous congestion, oedema, and haemorrhagic infarction that does not follow arterial vascular territories and can appear anywhere in the brain. CVST is most common in young women — particularly during pregnancy and the postpartum period — and in patients with thrombophilia, oral contraceptive use, dehydration, infections (mastoiditis, sinusitis), or haematological disorders.</p>
            <p>The clinical presentation is protean and easily confused with migraine, encephalitis, or idiopathic intracranial hypertension: progressive headache (the most common symptom), focal neurological deficits, seizures, visual disturbance, and encephalopathy. Diagnosis is confirmed on MRI with MR venography (MRV) — conventional CT may appear normal or show only subtle signs, and CT angiography targeting arteries will miss CVST entirely.</p>
            
            <div style="background: #fff8e6; border-left: 4px solid #f59e0b; border-radius: 8px; padding: 20px; margin: 24px 0;">
              <h3 style="color: #b45309; margin-top: 0; font-size: 1.1rem; display: flex; align-items: center; gap: 8px;">
                <i class="fa-solid fa-circle-exclamation"></i> CVST Treatment Is Counterintuitive
              </h3>
              <p style="margin-bottom: 0; color: #92400e;">CVST is treated with <strong>ANTICOAGULATION</strong> (low molecular weight heparin, then warfarin or a DOAC) — <strong>NOT</strong> thrombolysis or antiplatelet therapy. This applies even when haemorrhagic infarction is present on imaging. Missing the diagnosis or treating it as arterial ischaemic stroke can be fatal. Any young patient — particularly a young woman — presenting with new severe headache and neurological symptoms should have CVST excluded with an MRV before arterial causes are assumed.</p>
            </div>
            
            <p>CVST is a topic most neurology and stroke resources under-represent. Dr. Rajesh Reddy's practice includes the full workup and management of CVST — from initial MRV diagnosis through anticoagulation and monitoring for complications. A dedicated cluster article on <a href="cerebral-venous-sinus-thrombosis" style="color: #0066cc; font-weight: 500;">CVST</a> is available in this content hub.</p>
          </section>

          <section id="stroke-prevention" class="pillar-section">
            <h2>Stroke Prevention: Before the First Stroke and After</h2>
            
            <h3>Primary Prevention</h3>
            <p>Primary prevention targets people who have never had a stroke but carry risk factors. The most impactful interventions are:</p>
            <ul class="pillar-list">
              <li><strong>Blood pressure control:</strong> Target systolic BP &lt;130 mmHg in high-risk patients; hypertension is responsible for approximately 50% of all strokes in India</li>
              <li><strong>Atrial fibrillation detection and treatment:</strong> AF is a major cause of embolic stroke; anticoagulation (DOACs or warfarin) reduces stroke risk by approximately 70% in AF patients with risk factors</li>
              <li><strong>Diabetes management:</strong> HbA1c &lt;7% target; diabetes doubles stroke risk</li>
              <li><strong>Dyslipidaemia treatment:</strong> High-intensity statin therapy reduces ischaemic stroke risk independently of cholesterol level in high-cardiovascular-risk patients</li>
              <li><strong>Tobacco cessation:</strong> Smoking approximately doubles stroke risk; risk returns to baseline within 5 years of cessation</li>
              <li><strong>Healthy weight, regular aerobic exercise, and dietary modification</strong> — particularly salt reduction for blood pressure control</li>
            </ul>

            <h3>Secondary Prevention</h3>
            <p>Secondary prevention is the treatment given after a stroke or TIA to prevent recurrence — the period of highest risk. The first 48–72 hours after a TIA or minor stroke carry a 10–15% risk of a major stroke. Secondary prevention measures include:</p>
            <ul class="pillar-list">
              <li><strong>Antiplatelet therapy</strong> (aspirin + clopidogrel for the first 21 days after a minor stroke or TIA, then single agent long-term) — reduces recurrent ischaemic stroke risk by approximately 25%</li>
              <li><strong>Anticoagulation for AF-related stroke</strong> — DOAC (apixaban, rivaroxaban) preferred over warfarin in most patients; initiated 1–2 weeks after the stroke depending on its severity</li>
              <li><strong>Statin therapy</strong> — high-intensity (atorvastatin 40–80 mg); LDL target &lt;70 mg/dL</li>
              <li><strong>Aggressive blood pressure reduction</strong> — target systolic &lt;130 mmHg in most ischaemic stroke patients</li>
              <li><strong>Carotid endarterectomy or stenting</strong> — for significant symptomatic carotid stenosis; must be performed urgently (within 2 weeks) for maximum benefit</li>
              <li><strong>Lifestyle modification</strong> — same as primary prevention but even more critical</li>
            </ul>
          </section>

