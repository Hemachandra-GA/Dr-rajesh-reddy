          <section id="what-is-brain-stroke" class="pillar-section">
            <img src="images/Brain stroke treatment/Brain_stroke.webp" alt="What Is a Brain Stroke - Anatomy and Blood Supply" style="width: 100%; border-radius: 8px; margin-bottom: 20px; display: block; object-fit: cover;" loading="lazy">
            <h2>What Is a Brain Stroke?</h2>
            <p>A stroke occurs when the blood supply to part of the brain is suddenly cut off. Brain cells begin to die within minutes of losing their blood supply — the brain consumes approximately 20% of the body's oxygen despite being only 2% of its weight, and it has no reserve energy supply. The territory of brain affected by the stroke determines the symptoms: a stroke affecting the motor cortex causes limb weakness or paralysis; a stroke affecting the speech areas causes aphasia; a stroke affecting the cerebellum causes imbalance and vertigo.</p>
            <p>Strokes are broadly divided into two categories: <strong>ischaemic strokes</strong>, in which a blood vessel is blocked by a clot, and <strong>haemorrhagic strokes</strong>, in which a blood vessel ruptures and bleeds into or around the brain. These two categories require fundamentally different treatments — clot-dissolving drugs that are life-saving in ischaemic stroke are dangerous in haemorrhagic stroke — which is why rapid brain imaging (CT scan) is performed as the very first step in emergency stroke management.</p>
          </section>

          <section id="scale-in-india" class="pillar-section">
            <h2>The Scale of the Problem in India</h2>
            <p>India has approximately 1.8 million new strokes every year — roughly one stroke every 17 seconds. The age-adjusted stroke incidence in India has been rising, and strokes are occurring in younger patients than in Western populations: approximately <strong>20% of strokes in India occur in patients under 40 years of age</strong>. Hypertension — which affects an estimated 30% of Indian adults — is the single most important modifiable risk factor for both ischaemic and haemorrhagic stroke. Other major risk factors prevalent in the Indian population include diabetes (affecting 11% of adults), dyslipidaemia, atrial fibrillation, tobacco use (smoking and smokeless tobacco), and physical inactivity.</p>
            <p>Despite this burden, stroke care in India has improved markedly. The establishment of dedicated stroke units in major centres, the availability of mechanical thrombectomy in cities like Hyderabad, and increased public awareness of FAST symptoms have all contributed to better outcomes. The challenge remains getting patients to treatment within the therapeutic window — the critical period within which treatment can save brain tissue and reduce disability.</p>
          </section>

          <section id="befast-signs" class="pillar-section">
            <h2>Recognising a Stroke: The BEFAST Signs</h2>
            <p>The classic FAST mnemonic — Face, Arms, Speech, Time — has been expanded to <strong>BEFAST</strong> to include two additional symptoms more common in posterior circulation strokes, which affect the back of the brain:</p>
            <ul class="pillar-list">
              <li><strong>B — Balance:</strong> Sudden loss of balance or coordination; stumbling or falling without explanation</li>
              <li><strong>E — Eyes:</strong> Sudden vision loss in one or both eyes; double vision; vision that cuts off on one side</li>
              <li><strong>F — Face:</strong> One side of the face drooping; uneven smile; face feels numb</li>
              <li><strong>A — Arms:</strong> One arm drifts down when both are raised; arm weakness or numbness</li>
              <li><strong>S — Speech:</strong> Slurred speech; inability to find words; not understanding what others are saying</li>
              <li><strong>T — Time:</strong> Time to call 108 immediately — note the time symptoms started; this information is critical for treatment decisions</li>
            </ul>
            <div style="background: #f8fafc; border-left: 4px solid #0066cc; padding: 16px 20px; border-radius: 6px; margin-top: 16px;">
              <p style="margin-bottom: 0; color: #1e293b;"><strong>Other stroke symptoms that people miss:</strong> sudden severe headache with no known cause ('the worst headache of my life' — a <a href="subarachnoid-hemorrhage-treatment" style="color: #0066cc;">subarachnoid haemorrhage</a> warning sign); sudden confusion; sudden difficulty swallowing; sudden severe dizziness. Any sudden neurological symptom that is new and unexplained should be treated as a stroke until proven otherwise.</p>
            </div>
          </section>

