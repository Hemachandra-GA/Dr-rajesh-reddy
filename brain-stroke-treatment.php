          <section id="stroke-young-adults" class="pillar-section">
            <h2>Stroke in Younger Adults: A Growing Concern in India</h2>
            <p>The stereotype of stroke as a disease of the elderly does not reflect the Indian reality. Dr. Rajesh Reddy regularly treats patients in their 30s and 40s — and occasionally younger — with stroke. In young adults, the causes of stroke differ from those in older patients:</p>
            <ul class="pillar-list">
              <li><strong>Cardioembolic stroke from rheumatic heart disease and atrial fibrillation</strong> — rheumatic heart disease remains far more prevalent in India than in high-income countries</li>
              <li><strong>Hypercoagulable states</strong> — antiphospholipid syndrome, protein C/S deficiency, factor V Leiden — often undiagnosed</li>
              <li><strong>Cervical artery dissection</strong> — spontaneous or following chiropractic manipulation or minor trauma; a leading cause of stroke under 45</li>
              <li><strong>Paradoxical embolism through patent foramen ovale (PFO)</strong> — a hole in the heart present in approximately 25% of the population; found in higher proportions of young stroke patients</li>
              <li><strong>Illicit drug use</strong> — cocaine, amphetamines</li>
              <li><strong>Oral contraceptive use combined with migraine with aura and smoking</strong> — a significantly elevated risk combination in young women</li>
              <li><strong>Vasculitis</strong> — central nervous system vasculitis, Takayasu's arteritis</li>
              <li><strong>Hyperhomocysteinaemia</strong> — elevated plasma homocysteine is an underappreciated but treatable risk factor for stroke in young adults; it damages the vascular endothelium and promotes thrombosis; a simple, inexpensive blood test; treated with B6, folate (B9), and B12 supplementation; should be part of the routine young-stroke workup in every patient without an obvious alternative cause</li>
            </ul>
            <p>Young stroke requires a thorough investigation protocol — not just the standard CT and ECG, but also cardiac MRI, prolonged cardiac monitoring for paroxysmal AF, coagulation screen, connective tissue disease workup, and in some cases digital subtraction angiography (DSA). Dr. Rajesh Reddy coordinates this workup and ensures the cause of the stroke — not just the event — is identified and addressed.</p>
