          <section id="faq" class="pillar-section">
            <h2>Frequently Asked Questions</h2>
            <div class="pillar-faq-accordion">
              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  What is the difference between a stroke and a brain haemorrhage?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    These terms are often confused. A brain haemorrhage is a type of stroke — specifically a haemorrhagic stroke. The broader term 'stroke' includes both ischaemic strokes (caused by a blocked blood vessel — about 80% of strokes) and haemorrhagic strokes (caused by a ruptured blood vessel — about 20%). Both are emergencies, but their treatments differ significantly, which is why a brain CT scan is performed immediately in any suspected stroke.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  Can a young, fit person have a stroke?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Yes — and it happens more often than people realise, particularly in India. Approximately 20% of strokes in India occur in people under 40. Risk factors in young adults include undiagnosed heart abnormalities (such as patent foramen ovale or rheumatic heart disease), clotting disorders, cervical artery dissection, drug use, migraines with aura combined with the contraceptive pill and smoking, and uncontrolled hypertension. Any sudden neurological symptom in a young person should be evaluated urgently for stroke.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  How much recovery can be expected after a stroke?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Recovery after stroke is highly individual — it depends on which part of the brain was affected, how much brain tissue was permanently damaged, how quickly treatment was given, and how intensively rehabilitation is pursued. Some patients make a full or near-full recovery; others have lasting deficits. The brain has a remarkable capacity for neuroplasticity — the ability to rewire and compensate for damaged areas — particularly in the first 3–6 months after stroke. Early, intensive rehabilitation makes a significant difference to functional outcomes.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  What is mechanical thrombectomy and who is eligible?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Mechanical thrombectomy is a procedure in which a catheter is passed from an artery in the groin up into the brain to physically remove a clot from a large brain artery. It is the most effective treatment for large vessel ischaemic stroke — roughly doubling the chance of a good functional outcome. Eligibility requires: a significant neurological deficit (indicating a large vessel is blocked), a CT scan confirming no haemorrhage, evidence of salvageable brain tissue on perfusion imaging, and arrival within 24 hours of last known well time. Dr. Rajesh Reddy performs thrombectomy assessments and procedures in Hyderabad.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  If someone has a TIA and gets better, do they still need to go to hospital?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Absolutely yes — a TIA is a medical emergency even though the symptoms resolve. The 48-hour stroke risk after a TIA can be as high as 10–15%, and this risk is highest in the hours immediately after the TIA. Urgent assessment, imaging, and initiation of treatment can reduce this risk by up to 80%. The recovery of symptoms does not mean the brain is safe — it means the window for prevention is open. Every TIA patient should be assessed in a stroke clinic or emergency department within 24 hours.
                  </div>
                </div>
              </div>

              <div class="pillar-faq-item">
                <div class="pillar-faq-q">
                  Can a stroke recur after treatment?
                  <i class="fa-solid fa-chevron-down"></i>
                </div>
                <div class="pillar-faq-a">
                  <div class="pillar-faq-a-content">
                    Yes — recurrent stroke is a significant risk, particularly in the first year after the initial event. The risk of recurrence is approximately 10% in the first year without secondary prevention treatment, falling to about 4–5% per year with appropriate treatment. Secondary prevention — antiplatelet or anticoagulant therapy, statins, blood pressure treatment, and modification of risk factors — dramatically reduces this risk. This is why adherence to medication and regular follow-up are as important as the acute treatment.
                  </div>
                </div>
              </div>
