<script>
  // Self-contained accordion & tab filter — uses pfaq- classes only, no conflict with main.js
  document.addEventListener('DOMContentLoaded', function () {
    var items = document.querySelectorAll('.pfaq-item');
    var tabs  = document.querySelectorAll('.pfaq-tab');

    // Accordion
    items.forEach(function (item) {
      var btn    = item.querySelector('.pfaq-question');
      var answer = item.querySelector('.pfaq-answer');
      btn.addEventListener('click', function () {
        var isOpen = item.classList.contains('pfaq-open');
        // Close all
        items.forEach(function (el) {
          el.classList.remove('pfaq-open');
          el.querySelector('.pfaq-answer').style.maxHeight = null;
        });
        // Open clicked (if it wasn't already open)
        if (!isOpen) {
          item.classList.add('pfaq-open');
          answer.style.maxHeight = answer.scrollHeight + 'px';
        }
      });
    });

    // Tab filter
    tabs.forEach(function (tab) {
      tab.addEventListener('click', function () {
        tabs.forEach(function (t) { t.classList.remove('pfaq-active'); });
        tab.classList.add('pfaq-active');
        var cat = tab.getAttribute('data-category');
        items.forEach(function (item) {
          var itemCat = item.getAttribute('data-category');
          item.style.display = (cat === 'all' || itemCat === cat) ? '' : 'none';
          // Close on tab switch
          item.classList.remove('pfaq-open');
          item.querySelector('.pfaq-answer').style.maxHeight = null;
        });
      });
    });
  });
</script>
