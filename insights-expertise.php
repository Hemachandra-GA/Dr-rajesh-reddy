        const INITIAL_LIMIT = 6;
        const expandedCategories = {};

        function renderGallery(activeCategory = 'all') {
            const container = document.getElementById('gallery-container');
            container.innerHTML = ''; // Clear existing DOM elements

            const categoriesToRender = activeCategory === 'all'
                ? Object.keys(CATEGORY_CONFIG)
                : [activeCategory];

            categoriesToRender.forEach(catKey => {
                const config = CATEGORY_CONFIG[catKey];
                const catVideos = VIDEO_DATABASE.filter(v => v.category === catKey);

                if (catVideos.length === 0) return; // Skip if no videos

                // Create the section element
                const section = document.createElement('section');
                section.className = `section-tile ${config.bgClass}`;
                section.id = catKey;

                // Create the header HTML
                let headerHtml = `
                    <div class="section-header">
                        <span class="overline" style="color: ${config.accentColor};">${config.overline}</span>
                        <h2 class="display-lg" style="${config.bgClass === 'tile-dark' ? 'color: #ffffff;' : ''}">${config.title}</h2>
                        <p class="lead" style="${config.bgClass === 'tile-dark' ? 'color: var(--color-body-muted);' : 'color: var(--color-ink-muted-80);'}">
                            ${getCategorySubtitle(catKey)}
                        </p>
                    </div>
                `;
                section.innerHTML = headerHtml;

                // Determine display threshold
                const limit = expandedCategories[catKey] ? catVideos.length : INITIAL_LIMIT;
                const visibleVideos = catVideos.slice(0, limit);
                // Create grid element
                const grid = document.createElement('div');
                grid.className = `video-grid`;

                if (visibleVideos.length === 2) {
                    grid.classList.add('video-grid-2col');
                }

                // Render video cards
                visibleVideos.forEach((video, index) => {
                    const card = document.createElement('div');
                    card.className = 'video-card';
                    card.style.animationDelay = `${index * 0.05}s`;
                    card.onclick = () => openVideo(video.id);

                    card.innerHTML = `
                        <div class="video-thumbnail-container">
                            <img src="https://img.youtube.com/vi/${video.id}/hqdefault.jpg" alt="Video cover" class="video-thumbnail">
                            <div class="play-overlay">
                                <div class="play-btn-circle">▶</div>
                            </div>
                        </div>
                        <div class="video-info-box">
                            <h3 class="body-strong">${video.title}</h3>
                            <p class="caption" style="${config.bgClass === 'tile-dark' ? 'color: var(--color-body-muted);' : ''}">${video.description}</p>
                        </div>
                    `;
                    grid.appendChild(card);
                });

                section.appendChild(grid);

                if (catVideos.length > INITIAL_LIMIT && !expandedCategories[catKey]) {
                    const showMoreRow = document.createElement('div');
                    showMoreRow.className = 'show-more-row';

                    const btn = document.createElement('button');
                    btn.className = config.bgClass === 'tile-dark' ? 'btn-secondary-pill' : 'btn-primary';
                    if (config.bgClass === 'tile-dark') {
                        btn.style.color = '#ffffff';
                        btn.style.borderColor = '#ffffff';
                    }
                    btn.innerText = `Show All (${catVideos.length})`;
                    btn.onclick = () => {
                        expandedCategories[catKey] = true;
                        renderGallery(activeCategory);
                    };

                    showMoreRow.appendChild(btn);
                    section.appendChild(showMoreRow);
                }

                container.appendChild(section);
            });
        }

        function getCategorySubtitle(catKey) {
            switch (catKey) {
                case 'testimonials': return 'Hear directly from patients about their neurosurgical recoveries.';
                case 'media': return 'Dr. Rajesh Reddy raising public awareness on critical neurological emergencies.';
                case 'education': return 'Important guides helping patients and families prepare for and recover from spine procedures.';
                default: return '';
            }
        }

        function filterGallery(category) {
            document.querySelectorAll('.filter-tab').forEach(tab => {
                tab.classList.remove('active');
            });
            const activeTab = document.getElementById(`tab-${category}`);
            if (activeTab) {
                activeTab.classList.add('active');
            }
            renderGallery(category);
        }

        document.addEventListener('DOMContentLoaded', () => {
            const hash = window.location.hash.substring(1);
            if (hash && CATEGORY_CONFIG[hash]) {
                filterGallery(hash);
            } else {
                renderGallery('all');
            }
        });
