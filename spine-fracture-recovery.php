                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Long-haul air travel is generally deferred for 6 weeks after major spine surgery because the combination of immobility, dehydration, and reduced cabin pressure significantly increases the risk of deep vein thrombosis. Short domestic flights may be acceptable from 2–3 weeks after minimally invasive procedures, with adequate hydration and in-flight movement. Confirm with Dr. Rajesh Reddy before booking any travel in the first 3 months after surgery.</p>
