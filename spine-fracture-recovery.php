            <h2>Bone Healing and Fusion: What the Follow-Up Imaging Shows</h2>
            <p>After a spinal fusion operation, the goal is osseous fusion — the implanted bone graft or bone substitute integrating with the patient's own vertebrae to form a continuous, solid bony bridge across the operated segment. This process takes time:</p>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li><strong>Early consolidation is visible on CT from 6–8 weeks:</strong> Bony callus formation indicates the healing response is active.</li>
              <li><strong>Solid fusion is typically confirmed on CT at 3–6 months post-operatively:</strong> Though it may take up to 12 months in some patients with compromised bone density.</li>
              <li><strong>Plain X-rays:</strong> Show implant position (pedicle screws, rods, cages) and overall spinal alignment but cannot reliably assess micro-trabecular fusion — CT remains the gold standard.</li>
              <li><strong>Follow-up MRI:</strong> Used at 6–12 months to assess residual cord or nerve compression, particularly if neurological symptoms persist or evolve.</li>
            </ul>
            <p>For osteoporotic compression fractures treated with kyphoplasty or vertebroplasty, the cement cures within minutes. X-ray or CT at 6–8 weeks confirms cement position and adjacent vertebral integrity. There is no 'fusion' to wait for — the treated level is mechanically stable from day one.</p>
            <p>For pathological fractures from cancer, imaging during recovery also monitors tumour response to systemic treatment and radiotherapy, and assesses the need for further intervention.</p>
