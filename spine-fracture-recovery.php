          <section id="pain-management" class="pillar-section">
            <h2>Pain Management During Recovery</h2>
            <p>Pain after a spine fracture — whether treated conservatively or surgically — is expected and manageable. The goal is not zero pain, but pain that is controlled well enough to allow mobility and rehabilitation.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">Pain Is Worst in the First 2 Weeks</h3>
            <p>Surgical pain peaks in the first 48–72 hours and then steadily decreases over 2 weeks. By 4–6 weeks, most patients need only over-the-counter analgesics for activity-related discomfort. Pain that is not improving on this trajectory should be reviewed.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">The Right Balance: Taking Enough to Move, Not So Much to Mask Problems</h3>
            <p>Adequate pain control enables physiotherapy and early mobilisation — both of which are essential for recovery. Undertreated pain causes patients to guard their spine, adopt harmful postures, and avoid the movement that heals. At the same time, pain that is completely masked may hide a warning sign. Dr. Rajesh Reddy's team calibrates the analgesic regimen at each review.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">Common Pain Medications After Spine Surgery</h3>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li><strong>Paracetamol (acetaminophen):</strong> Regular dosing (1 g four times daily) is the foundation — not just a mild option; it significantly reduces opioid requirements when taken regularly.</li>
              <li><strong>NSAIDs (ibuprofen, diclofenac):</strong> Effective for bone and soft tissue pain; avoid in patients with kidney disease, peptic ulcer history, or those on blood thinners; avoid or use cautiously in the first 6 weeks after fusion surgery as there is evidence they may impair bone fusion.</li>
              <li><strong>Tramadol or codeine:</strong> Moderate opioids for breakthrough pain; constipation is a significant side effect — stool softeners should be prescribed alongside.</li>
              <li><strong>Gabapentin / pregabalin:</strong> Used when there is a neuropathic (nerve) component to pain — shooting, burning, or electric-shock sensations down the arms or legs.</li>
              <li><strong>Muscle relaxants:</strong> For muscle spasm around the fracture site, particularly in the early weeks.</li>
            </ul>
            <p>Opioid medications (tramadol, codeine, morphine) are appropriate for short-term use after spine surgery but should be weaned as quickly as pain allows. Prolonged opioid use carries risks of dependence, cognitive effects, and constipation, and does not improve long-term recovery outcomes. Dr. Rajesh Reddy will guide the tapering schedule at each review.</p>
          </section>

