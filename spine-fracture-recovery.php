            <h2>What Happens in Hospital After Spine Surgery?</h2>
            
            <h3 style="font-size: 1.2rem; margin-top: 20px;">Day of Surgery</h3>
            <p>Most patients wake from spine surgery in the recovery room and are transferred to the ward or, for more complex procedures, the intensive care unit for overnight monitoring. Pain is managed with a combination of intravenous medication, nerve blocks, and oral analgesics from the outset — adequate pain control in the first 24 hours is essential for early mobilisation. A urinary catheter is usually in place and removed within 24–48 hours.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">Day 1–2: Early Mobilisation</h3>
            <p>Early mobilisation — getting out of bed — is one of the most important steps in spine surgery recovery and is typically initiated on the first post-operative day by the physiotherapy team. This is not rushing recovery; it is best practice. Bed rest beyond 24–48 hours increases the risk of deep vein thrombosis, chest infection, pressure sores, and muscle deconditioning without any benefit to healing. Patients are surprised to find they can stand and walk short distances the day after surgery, even after a multi-level fusion.</p>
            <p>Blood clot prevention (DVT prophylaxis) is a priority after spine surgery. Dr. Rajesh Reddy's protocol includes compression stockings from the day of surgery, a blood-thinning injection (low molecular weight heparin) starting 24–48 hours post-operatively, and early walking. Patients with higher clot risk may continue injections at home for 2–4 weeks.</p>

            <h3 style="font-size: 1.2rem; margin-top: 20px;">Before Discharge: What You Need to Be Able to Do</h3>
            <p>Before going home, patients are expected to reach a set of milestones that the physiotherapy team assesses daily:</p>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li>Walk independently or with a walking aid for a short distance</li>
              <li>Climb at least 2–3 stairs safely (if there are stairs at home)</li>
              <li>Manage basic self-care — washing, dressing, toilet — without excessive pain</li>
              <li>Understand their activity restrictions and brace-wearing instructions if applicable</li>
              <li>Understand their medication schedule and when to take pain relief</li>
              <li>Know what warning signs to watch for</li>
            </ul>
          </section>

