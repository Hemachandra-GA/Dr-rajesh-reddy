                  <span>Can I sleep flat after spine surgery?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Most patients find sleeping flat uncomfortable in the early post-operative period. A semi-reclined position (pillow under the knees for lumbar surgery; slight head elevation for cervical surgery) is generally more comfortable. From a medical perspective, there is no absolute restriction on sleeping position — comfort is the guide, provided you are not sleeping in a position that creates sustained pressure on the wound. By 4–6 weeks most patients can sleep in their preferred position. Specific advice may differ for cervical surgery patients.</p>
