              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>I had spine surgery two weeks ago and still have leg pain. Is this normal?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>Leg pain (sciatica or radiculopathy) that was present before surgery often persists for weeks to months after the surgery that relieved the nerve compression. The nerve that was compressed takes time to recover — sometimes weeks, sometimes months — even after the structural cause has been removed. Persisting neurological symptoms in the early weeks after surgery are not a sign of surgical failure. However, new leg pain that was not present before surgery, or leg pain that is worsening rather than improving, should be reviewed promptly.</p>
                </div>
              </div>

