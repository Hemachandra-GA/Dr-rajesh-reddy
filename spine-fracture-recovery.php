                <ul style="margin: 0; padding-left: 20px; line-height: 1.6; color: #475569;">
                  <li><strong>Return to sport or physically demanding work:</strong> Structured graded return with functional capacity evaluations.</li>
                  <li><strong>Management of persistent symptoms:</strong> Long-term core endurance and ergonomic optimization.</li>
