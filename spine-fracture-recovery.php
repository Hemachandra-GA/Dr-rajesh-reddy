                <h3 style="color: #0066cc; margin-top: 0; font-size: 1.15rem;">Subacute Phase (Weeks 2–6)</h3>
                <ul style="margin: 0; padding-left: 20px; line-height: 1.6; color: #475569;">
                  <li><strong>Gentle core activation exercises:</strong> Restoring control of the deep stabilising muscles (transversus abdominis, multifidus) without loading the fracture site.</li>
                  <li><strong>Postural correction:</strong> Reversing the protective postures patients adopt after injury (rounded shoulders, guarded gait) which become problematic if maintained.</li>
                  <li><strong>Hydrotherapy (water therapy):</strong> May be introduced for suitable patients; buoyancy reduces spinal load and allows more movement.</li>
                  <li><strong>Scar management:</strong> Gentle massage of the surgical scar once healed to prevent deep tissue adhesions.</li>
                </ul>
              </div>

              <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 22px;">
                <h3 style="color: #0066cc; margin-top: 0; font-size: 1.15rem;">Consolidation Phase (Weeks 6–12)</h3>
                <ul style="margin: 0; padding-left: 20px; line-height: 1.6; color: #475569;">
                  <li><strong>Progressive strengthening:</strong> Gluteal, hip, and core strengthening; gradually increasing resistance loads.</li>
                  <li><strong>Balance and proprioception training:</strong> Particularly important for patients with any residual neurological involvement.</li>
                  <li><strong>Functional activities:</strong> Returning to specific tasks (desk work, driving, household tasks) under expert guidance.</li>
                </ul>
