          <section id="factors" class="pillar-section">
            <h2>Factors That Determine Your Recovery Timeline</h2>
            <p>No two spine fracture recoveries are identical. The single most important factor is whether there was any neurological injury — damage to the spinal cord or nerve roots — because neurological recovery follows different principles from bone healing. Other key factors include:</p>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li><strong>Type and level of fracture:</strong> Cervical fractures have different recovery trajectories from thoracolumbar fractures; stable fractures heal faster than unstable ones.</li>
              <li><strong>Treatment chosen:</strong> Conservative management (brace alone) vs. surgery; and if surgery, minimally invasive vs. open; degree of instrumentation (single level vs. multi-level fusion).</li>
              <li><strong>Patient age and bone quality:</strong> Younger patients with good bone density heal faster; osteoporotic bone heals more slowly and is at higher risk of adjacent fractures.</li>
              <li><strong>Pre-existing health:</strong> Patients with diabetes, cardiovascular disease, or on immunosuppressants have slower healing and higher infection risk.</li>
              <li><strong>Underlying cause:</strong> Traumatic fractures heal differently from pathological fractures (osteoporosis, cancer); pathological fractures require concurrent treatment of the underlying disease.</li>
              <li><strong>Compliance with rehabilitation:</strong> Patients who engage consistently with physiotherapy and follow activity restrictions recover faster and with fewer complications.</li>
            </ul>
