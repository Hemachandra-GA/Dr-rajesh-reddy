          <section id="long-term" class="pillar-section">
            <h2>Long-Term Outcomes: What Recovery Looks Like at 12 Months</h2>
            <p>The large majority of patients who undergo spine fracture treatment — whether surgical or conservative — achieve a good functional outcome at 12 months. 'Good outcome' means:</p>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li>Pain reduced to a level that does not significantly limit daily activity (though mild residual stiffness at the operated level is common and not a sign of failure).</li>
              <li>Return to most or all pre-injury activities, modified where necessary.</li>
              <li>No progressive neurological deficit — and, for patients who had neurological injury, the maximum neurological recovery that their injury pattern allows.</li>
              <li>Radiological evidence of healed fracture or solid bony fusion.</li>
            </ul>
            <p>The factors most associated with a worse long-term outcome are: late presentation with established neurological injury, multi-level or highly unstable injuries, poor bone quality, significant comorbidities, and inadequate rehabilitation. None of these are within the patient's control at the time of the fracture — but the commitment to rehabilitation afterwards is.</p>
            <p>Studies consistently show that patients who complete their physiotherapy programme and attend all post-operative follow-up appointments have significantly better pain and function outcomes at 12 months than those who do not. Recovery from spine fracture is an active process, not a passive one — the surgeon provides the structural repair; the patient rebuilds the function around it.</p>
