            <h2>Activity Restrictions During Recovery: The BLT Principles</h2>
            <p>Specific restrictions vary by fracture type and operation, but the following general principles apply to almost all spine fracture recoveries:</p>

            <div style="background-color: #fff7ed; border-left: 4px solid #ea580c; padding: 18px 20px; border-radius: 0 8px 8px 0; margin: 20px 0;">
              <h4 style="margin: 0 0 10px; color: #9a3412; font-size: 1.1rem;">The BLT Principles (No Bending, No Lifting, No Twisting)</h4>
              <ul style="margin: 0; padding-left: 20px; line-height: 1.6; color: #7c2d12;">
                <li><strong>Bending at the waist:</strong> Avoid deep forward bending for the first 6–12 weeks; bend at the hips and knees (squat technique) when picking something up from the floor.</li>
                <li><strong>Lifting:</strong> Nothing heavier than 2–3 kg (a light bag) for the first 6 weeks; nothing heavy (more than 5–10 kg) for 3 months; specific limits depend on the level and extent of surgery.</li>
                <li><strong>Twisting the spine:</strong> Avoid rotational movements that torque the operated segment; turn the whole body rather than rotating just the trunk.</li>
              </ul>
            </div>

            <h3 style="font-size: 1.2rem; margin-top: 24px;">Driving Guidelines</h3>
            <p>Driving requires the ability to perform an emergency stop — which demands a rapid twisting action and application of force. It is typically restricted until:</p>
            <ul style="line-height: 1.7; color: #334155; margin-left: 20px;">
              <li><strong>Cervical surgery:</strong> 6–12 weeks, or until the surgeon confirms adequate neck mobility and control.</li>
              <li><strong>Thoracolumbar surgery:</strong> 4–8 weeks for minimally invasive; 6–12 weeks for open fusion.</li>
              <li><strong>Brace wearers:</strong> No driving while wearing a rigid brace — the brace restricts the movement required for safe control and emergency response.</li>
            </ul>

            <h3 style="font-size: 1.2rem; margin-top: 24px;">Return to Work</h3>
            <p>Return to work timing depends heavily on the physical demands of the job. Sedentary (desk) work can usually resume within 2–6 weeks for most fracture types; manual or physically demanding work may require 3–6 months. A phased return — starting part-time or on light duties — reduces strain and improves compliance with recovery restrictions.</p>
