              <div style="background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 10px; padding: 22px;">
                <h3 style="color: #0066cc; margin-top: 0; font-size: 1.15rem;">Acute Phase (In Hospital and First 2 Weeks at Home)</h3>
                <ul style="margin: 0; padding-left: 20px; line-height: 1.6; color: #475569;">
                  <li><strong>Safe mobilisation:</strong> Teaching correct techniques for moving, turning in bed (log-rolling), sitting up, and standing, which protect the operated or healing spine.</li>
                  <li><strong>Breathing exercises:</strong> Essential after chest or upper back surgery to prevent atelectasis and chest infections.</li>
                  <li><strong>Graduated walking programme:</strong> Distance and duration increased daily based on endurance.</li>
                  <li><strong>Pain management:</strong> Ice, heat, positioning, TENS where appropriate.</li>
                </ul>
