            <h2>Frequently Asked Questions About Spine Fracture Recovery</h2>

            <div class="faq-accordion" style="margin-top: 24px;">
              <div class="faq-item">
                <button class="faq-question" aria-expanded="false">
                  <span>How long does a spine fracture take to heal without surgery?</span>
                  <i class="fa-solid fa-chevron-down"></i>
                </button>
                <div class="faq-answer">
                  <p>A stable vertebral compression fracture treated conservatively — with a brace, pain management, and physiotherapy — typically heals sufficiently in 6–12 weeks for most daily activities to resume. Complete bone healing (assessed on CT) may take 3–6 months. However, 'healed' does not mean the spine looks entirely normal on imaging — some degree of vertebral height loss and altered contour may persist. The clinical goal is pain-free function, which for most stable fractures is achieved by 3 months.</p>
